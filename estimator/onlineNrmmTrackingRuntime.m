    rotation = localRotation(runtime.yawEstimate);
    inertialVelocity = rotation*runtime.bodyVelocityEstimate;
    measuredBodyAcceleration = observerInput.bodyAcceleration;
    inertialAcceleration = rotation*measuredBodyAcceleration;
    courseGeometry = observerInput.courseGeometry;
    yawMeasurement = courseGeometry.correspondence;
    courseHeading = yawMeasurement.heading;
    egoState = [ ...
        runtime.positionEstimate(1); inertialVelocity(1); ...
        inertialAcceleration(1); runtime.positionEstimate(2); ...
        inertialVelocity(2); inertialAcceleration(2)];

    output = struct( ...
        "inertialVelocityEstimate",observerInput.gnssVelocity, ...
        "inertialVelocityEstimateTime",observerInput.time, ...
        "inertialVelocityEstimateErrorBound",observerInput.velocityErrorMaximum, ...
        "velocitySource",observerInput.velocitySource, ...
        "time", runtime.currentTime, ...
        "stateTime", runtime.currentTime, ...
        "inputSampleTime", observerInput.time, ...
        "lastGnssTime", runtime.lastGnssTime, ...
        "lastImuTime", runtime.lastImuTime, ...
        "lastGyroscopeTime", runtime.lastGyroscopeTime, ...
        "lastRadarTime", runtime.lastRadarTime, ...
        "egoState", egoState, ...
        "egoPositionInertial", runtime.positionEstimate, ...
        "egoVelocityInertial", inertialVelocity, ...
        "egoBodyVelocity", runtime.bodyVelocityEstimate, ...
        "egoAccelerationBody", measuredBodyAcceleration, ...
        "egoAccelerationInertial", inertialAcceleration, ...
        "egoYaw", runtime.yawEstimate, ...
        "yawEstimator", "gyro-plus-continuous-position-motion-innovation", ...
        "yawObserverCorrectionAvailable", norm(yawMeasurement.rotationVector)>0, ...
        "yawObservationSetInformative",yawMeasurement.informative, ...
        "egoYawRate", observerInput.yawRate, ...
        "egoYawRateMeasured", observerInput.yawRate, ...
        "yawCoursePseudoHeading", courseHeading, ...
        "yawCourseEstimatedSideslip", ...
            courseGeometry.estimatedSideslip, ...
        "yawCourseSideslipErrorMaximum", ...
            courseGeometry.sideslipErrorMaximum, ...
        "yawCourseSideslipSineErrorMaximum", ...
            courseGeometry.sineErrorMaximum, ...
        "yawCourseSideslipSpeedErrorContribution", ...
            courseGeometry.speedErrorContribution, ...
        "yawCourseSideslipYawRateAndModelContribution", ...
            courseGeometry.yawRateAndModelContribution, ...
        "yawCourseTrueSideslipInterval", ...
            courseGeometry.trueSideslipInterval, ...
        "yawCourseMeasuredSpeed", courseGeometry.measuredSpeed, ...
        "yawCourseTrueSpeedLowerBound", ...
            courseGeometry.trueSpeedLowerBound, ...
