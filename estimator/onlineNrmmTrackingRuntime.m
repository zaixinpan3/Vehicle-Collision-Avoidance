function varargout = onlineNrmmTrackingRuntime(action, varargin)
% onlineNrmmTrackingRuntime Run the cascaded measured-input NRMM observer.
%
% Every frame provides GNSS position, body acceleration, gyro yaw rate and
% optional radar relative position. Direct GNSS velocity fields are ignored.
% A four-state sampled position/IMU observer reconstructs inertial velocity;
% its evolving error ball is supplied to the body-velocity and NRMM cascade.
% Internal gnssVelocity fields retain the numeric kernel's historical name
% but always contain this reconstructed estimate, never a sensed velocity.
% The position/IMU observer couples yaw back into the ego cascade. Historical
% cascade ISS results apply conditionally to a bounded velocity-input error;
% they are not a stability proof of the enlarged interconnection.
% Yaw uses a continuous vector innovation and gyro propagation. Its correction
% does not branch on an informative-course flag. A separate circle-set audit
% may be uninformative without disabling the numerical observer.
% GNSS/radar predictors reset on sample arrivals. The remaining continuous
% states use held-input RK4. Numerical defects, sampling and model uncertainty
% enter separate conditional enclosures; no floating-point interval proof is
% claimed. See OBSERVER_ISS_THEORY.md for the position-only sensor amendment.

    action = lower(string(action));
    if ~isscalar(action)
        error("onlineNrmmTrackingRuntime:invalidAction", ...
            "action must be 'initialize', 'step', 'sample', 'output', or 'resetTarget'.");
    end
    switch action
        case "initialize"
            varargout{1} = localInitialize(varargin{:});
        case "step"
            if nargout>1
                [varargout{1}, varargout{2}] = localStep(varargin{:});
            else
                varargout{1} = localStep(varargin{:});
            end
        case "sample"
            [varargout{1},varargout{2}] = localStep(varargin{:},true);
        case "output"
            varargout{1} = localCurrentOutput(varargin{:});
        case "resettarget"
            varargout{1} = localResetTarget(varargin{:});
        otherwise
            error("onlineNrmmTrackingRuntime:invalidAction", ...
                "action must be 'initialize', 'step', 'sample', 'output', or 'resetTarget'.");
    end
end

function runtime = localResetTarget(runtime,physicalState)
% localResetTarget Reinitialize the acquired target without changing ego states.
    validateattributes(physicalState,{'double'},{'vector','numel',6,'finite','real'});
    physicalState = physicalState(:);
    runtime.targetState = physicalState;
    runtime.targetOutputPredictor = physicalState(1:2);
    runtime.lastRadarTime = NaN;
    runtime.positionErrorBound = nrmmPositionErrorBound("reset", ...
        runtime.positionErrorBound,localBoundState(localPackState(runtime)));
    audit = localOperatingDomainAudit(localPackState(runtime),runtime,"track-reset");
    runtime.lastIntervalDomainAudit = audit;
    runtime.estimatedDomainAudit = localMergeDomainAudits( ...
        runtime.estimatedDomainAudit,audit);
    runtime.lastIntervalTargetCertifiedSpeedDomainValid = audit.speedValid;
    runtime.targetCertifiedSpeedDomainValid = ...
        runtime.targetCertifiedSpeedDomainValid && audit.speedValid;
    runtime.minimumReconstructedTargetSpeed = min( ...
        runtime.minimumReconstructedTargetSpeed,audit.minimumTargetSpeed);
end

function runtime = localInitialize(cfg, options, observerDesign)
    localAddProjectPaths();
    if nargin < 1 || isempty(cfg)
        cfg = nrmmTrackingConfig();
    end
    if nargin < 2 || isempty(options)
        options = struct();
    end
    if nargin < 3 || isempty(observerDesign)
        observerDesign = synthesizeNrmmObserverGains(cfg);
    end

    samplePeriod = cfg.runtime.samplePeriod;
    integrationStepMaximum = cfg.runtime.integrationStepMaximum;
    validateattributes(samplePeriod, {'double'}, ...
        {'real', 'scalar', 'finite', 'positive'}, mfilename, ...
        'cfg.runtime.samplePeriod');
    validateattributes(integrationStepMaximum, {'double'}, ...
        {'real', 'scalar', 'finite', 'positive'}, mfilename, ...
        'cfg.runtime.integrationStepMaximum');
    integration = localIntegrationSettings(samplePeriod,integrationStepMaximum,observerDesign);
    integrationSubstepCount = integration.substepCount;
    integrationStep = samplePeriod/integrationSubstepCount;

    initialTime = localOptionFiniteScalar(options, "initialTime", 0.0);
    egoPosition = localRequiredOptionVector( ...
        options, "egoInitialPosition", 2);
    egoYaw = 0.0;
    if isfield(options,"egoInitialYaw") && ~isempty(options.egoInitialYaw)
        egoYaw = localWrapToPi(localRequiredOptionScalar(options,"egoInitialYaw"));
    end
    egoBodyVelocity = localRequiredOptionVector( ...
        options, "egoInitialBodyVelocity", 2);
    targetState = localInitialTarget(options);
    targetIdentifier = localTargetIdentifier(options);

    runtime = struct( ...
        "observerDesign", observerDesign, ...
        "samplePeriod", samplePeriod, ...
        "integrationStep", integrationStep, ...
        "integrationSubstepCount", integrationSubstepCount, ...
        "integrationSettings", integration, ...
        "currentTime", initialTime, ...
        "yawEstimate", egoYaw, ...
        "bodyVelocityEstimate", egoBodyVelocity, ...
        "positionEstimate", egoPosition, ...
        "gnssPositionPredictor", egoPosition, ...
        "targetState", targetState, ...
        "targetOutputPredictor", targetState(1:2), ...
        "targetIdentifier", targetIdentifier, ...
        "lastInputSampleTime", NaN, ...
        "lastGnssTime", NaN, ...
        "lastImuTime", NaN, ...
        "lastGyroscopeTime", NaN, ...
        "lastRadarTime", NaN, ...
        "targetCertifiedSpeedDomainValid", true, ...
        "minimumReconstructedTargetSpeed", Inf, ...
        "lastIntervalTargetCertifiedSpeedDomainValid", true);
    rotation=[cos(egoYaw),-sin(egoYaw);sin(egoYaw),cos(egoYaw)];
    velocity=rotation*egoBodyVelocity;
    velocityRadius=observerDesign.operatingDomain.egoSpeedMaximum+norm(velocity);
    if isfield(options,"initialErrorBounds") && ~isempty(fieldnames(options.initialErrorBounds))
        initialBound=options.initialErrorBounds;
        velocityRadius=initialBound.bodyVelocity+2*norm(egoBodyVelocity)*sin(initialBound.yaw/2);
    end
    if isfield(options,"inertialVelocityInitialization")
        initialization=options.inertialVelocityInitialization;
        velocity=initialization.value;
        velocityRadius=initialization.radius;
    end
    runtime.positionVelocity=nrmmPositionVelocity("initialize",egoPosition,velocity, ...
        observerDesign.sensors.positionNoiseMaximum,velocityRadius,samplePeriod, ...
        observerDesign.positionVelocity.bandwidth);
    runtime.positionVelocity.initialPositionPending=true;
    initialAudit = localOperatingDomainAudit( ...
        localPackState(runtime), runtime, "initialization");
    runtime.estimatedDomainAudit = initialAudit;
    runtime.lastIntervalDomainAudit = initialAudit;
    runtime.targetCertifiedSpeedDomainValid = initialAudit.speedValid;
    runtime.minimumReconstructedTargetSpeed = initialAudit.minimumTargetSpeed;
    runtime.lastIntervalTargetCertifiedSpeedDomainValid = ...
        initialAudit.speedValid;
    prior = struct();
    if isfield(options,"initialErrorBounds")
        prior = options.initialErrorBounds;
    end
    runtime.positionErrorBound = nrmmPositionErrorBound("initialize", ...
        observerDesign,cfg,localBoundState(localPackState(runtime)),initialTime,prior);
    if isfield(options,"targetMeasurementHistory")
        for historyInput = options.targetMeasurementHistory(:).'
            if historyInput.time > initialTime
                error("onlineNrmmTrackingRuntime:futureHistory","Initialization cannot use future observations.");
            end
            if historyInput.radarDetectionAvailable
                runtime.positionErrorBound.targetHistory = nrmmTargetHistory("sensor", ...
                    runtime.positionErrorBound.targetHistory,historyInput,observerDesign);
            end
        end
    end
end

function settings = localIntegrationSettings(samplePeriod,requestedStep,design)
% Test the exact sampled, straight, constant-velocity error map before running.
% Between radar resets r = yPredictor - rhoHat obeys r' = -l1*r, while
% e' = N*e - L*r and r(0) = e_rho(0). Instability of this admissible nominal
% case is sufficient to reject the sample period. Passing this necessary
% check is not a nonlinear or dropout stability certificate.
    gains = design.target.innovationGains(:);
    generator = zeros(4);
    generator(1,2) = 1;
    generator(2,3) = 1;
    generator(1:3,4) = -gains;
    generator(4,4) = -gains(1);
    transition = expm(samplePeriod*generator);
    sampledMap = transition(1:3,:)*[eye(3);1,0,0];
    spectralRadius = max(abs(eig(sampledMap)));
    if ~isfinite(spectralRadius) || spectralRadius >= 1
        error('onlineNrmmTrackingRuntime:unstableSamplePeriod', ...
            'The radar sample period %.9g s destabilizes the nominal sampled observer (radius %.9g).', ...
            samplePeriod,spectralRadius);
    end
    % Resolve the fastest correction/rotation time scale with at least two
    % RK4 substeps per time constant. The requested maximum is an upper
    % limit, not permission to take an unstable explicit integration step.
    lipschitz = design.target.lipschitzCertificate;
    fastestRate = max([design.velocity.gain,design.position.gain, ...
        design.yaw.correctionBandwidth,gains(1),sqrt(gains(2)),nthroot(gains(3),3)]) ...
        +design.operatingDomain.egoYawRateMaximum+design.sensors.gyroscopeNoiseMaximum ...
        +lipschitz.phiAcceleration+sqrt(lipschitz.phiVelocity);
    safeStep = min(requestedStep,.5/fastestRate);
    count = max(1,ceil(samplePeriod/safeStep));
    settings = struct('requestedStepMaximum',requestedStep,'rateLimitedStepMaximum',.5/fastestRate, ...
        'substepCount',count,'nominalSampledSpectralRadius',spectralRadius, ...
        'scope',"Necessary nominal sampling check and gain-aware RK4 resolution; no nonlinear digital certificate");
end

function [runtime, output] = localStep(runtime, frame, publishCurrent)
    if nargin<3,publishCurrent = false;end
    observerInput = localSynchronizedInput(frame, runtime);

    runtime.positionVelocity=observerInput.positionVelocity;
    runtime.gnssPositionPredictor = observerInput.gnssPosition;
    if observerInput.radarDetectionAvailable
        runtime.targetOutputPredictor = observerInput.radarRelativePosition;
    end
    runtime.positionErrorBound = nrmmPositionErrorBound("measure", ...
        runtime.positionErrorBound,observerInput, ...
        localBoundState(localPackState(runtime)));
    if publishCurrent
        outputRuntime = localRecordMeasurementTimes(runtime,observerInput);
        outputRuntime.currentTime = observerInput.time;
        output = localOutput(outputRuntime,observerInput);
    end
    runtime.positionVelocity=nrmmPositionVelocity("predict",runtime.positionVelocity, ...
        observerInput.bodyAcceleration,runtime.yawEstimate,runtime.positionErrorBound.yaw, ...
        runtime.observerDesign,runtime.positionErrorBound.holdBounds);
    [state, intervalAudit, runtime.positionErrorBound] = localRungeKuttaInterval( ...
        localPackState(runtime), observerInput, runtime);
    [runtime.bodyVelocityEstimate, ...
        runtime.positionEstimate, runtime.gnssPositionPredictor, ...
        runtime.targetState, runtime.targetOutputPredictor, runtime.yawEstimate] = ...
        localUnpackState(state);
    runtime.targetCertifiedSpeedDomainValid = ...
        runtime.targetCertifiedSpeedDomainValid ...
        && intervalAudit.speedValid;
    runtime.minimumReconstructedTargetSpeed = min( ...
        runtime.minimumReconstructedTargetSpeed, ...
        intervalAudit.minimumTargetSpeed);
    runtime.lastIntervalTargetCertifiedSpeedDomainValid = ...
        intervalAudit.speedValid;
    runtime.estimatedDomainAudit = localMergeDomainAudits( ...
        runtime.estimatedDomainAudit, intervalAudit);
    runtime.lastIntervalDomainAudit = intervalAudit;
    runtime.currentTime = observerInput.time+runtime.samplePeriod;
    runtime.positionErrorBound.time = runtime.currentTime;
    runtime = localRecordMeasurementTimes(runtime, observerInput);
    if nargout>1 && ~publishCurrent,output = localOutput(runtime, observerInput);end
end

function output = localCurrentOutput(runtime, frame)
    observerInput = localSynchronizedInput(frame, runtime);
    outputRuntime = localRecordMeasurementTimes(runtime, observerInput);
    % localSynchronizedInput already verifies that these timestamps denote
    % the same sample within floating-point grid tolerance. Publish using
    % the accepted sensor timestamp so a fresh gyro is not assigned a tiny
    % positive age and consequently the full rate-domain uncertainty.
    outputRuntime.currentTime = observerInput.time;
    boundState = localBoundState(localPackState(runtime));
    if observerInput.radarDetectionAvailable
        boundState.radarPredictor = observerInput.radarRelativePosition;
    end
    outputRuntime.positionErrorBound = nrmmPositionErrorBound("measure", ...
        runtime.positionErrorBound,observerInput,boundState);
    output = localOutput(outputRuntime, observerInput);
end

function [nextState, intervalAudit, positionErrorBound] = localRungeKuttaInterval( ...
        state, observerInput, runtime)
    nextState = state;
    intervalAudit = localOperatingDomainAudit( ...
        nextState, runtime, "interval-start", observerInput);
    step = runtime.integrationStep;
    positionErrorBound = runtime.positionErrorBound;
    design = runtime.observerDesign;
    kernelDesign = struct("velocity",struct("gain",design.velocity.gain), ...
        "position",struct("gain",design.position.gain), ...
        "target",struct("innovationGains",design.target.innovationGains,"domain",design.target.domain), ...
        "yaw",struct("correctionBandwidth",design.yaw.correctionBandwidth,"courseModel", ...
        struct("rearAxleDistance",design.yaw.courseModel.rearAxleDistance, ...
        "sideslipDomainMaximum",design.yaw.courseModel.sideslipDomainMaximum)));
    % The compiled kernel uses only the inverse floor, not the truth-domain
    % audit. Preserve its existing struct ABI and identical point dynamics.
    if isfield(design.target.domain,"regularizationSpeedMinimum")
        kernelDesign.target.domain = rmfield(design.target.domain,"regularizationSpeedMinimum");
        kernelDesign.target.domain.speedMinimum = design.target.domain.regularizationSpeedMinimum;
    end
    correspondence = observerInput.courseGeometry.correspondence;
    lateralVelocity = observerInput.courseGeometry.lateralMeasurement.center;
    if observerInput.courseGeometry.lateralMeasurement.source=="kinematic" || ~isfinite(lateralVelocity)
        lateralVelocity = NaN;
    end
    measurement = struct("yawRate",observerInput.yawRate,"gnssVelocity",observerInput.gnssVelocity, ...
        "bodyAcceleration",observerInput.bodyAcceleration, ...
        "radarDetectionAvailable",observerInput.radarDetectionAvailable, ...
        "correspondence",struct("rotationVector",correspondence.rotationVector), ...
        "lateralVelocity",lateralVelocity);
    if exist("nrmmObserverIntegrationKernelV2Mex","file")==3
        [states,firstDerivatives] = nrmmObserverIntegrationKernelV2Mex(state,measurement,kernelDesign,step,runtime.integrationSubstepCount);
    else
        [states,firstDerivatives] = nrmmObserverVectorField("integrate",state,measurement,kernelDesign,step,runtime.integrationSubstepCount);
    end
    for substepIdx = 1:runtime.integrationSubstepCount
        previousState = states(:,substepIdx);
        nextState = states(:,substepIdx+1);
        first = firstDerivatives(:,substepIdx);
        positionErrorBound = nrmmPositionErrorBound("advance",positionErrorBound, ...
            observerInput,localBoundState(previousState), ...
            localBoundState(nextState), ...
            localBoundState(first),step);
        substepAudit = localOperatingDomainAudit( ...
            nextState, runtime, ...
            "substep-" + string(substepIdx) + "-accepted", ...
            observerInput);
        intervalAudit = localMergeDomainAudits( ...
            intervalAudit, substepAudit);
    end
end

function audit = localOperatingDomainAudit( ...
        state, runtime, location, observerInput)
% localOperatingDomainAudit Audit domain assumptions without gating.
%
% The audit records whether the estimated states and measured inputs lie
% inside the certified operating domain of the boundedness theorem. It is
% reporting only: the Lipschitz extension keeps the observer well defined
% outside the domain, so no rejection is performed.

    if nargin < 4
        observerInput = struct();
    end
    [bodyVelocity, ~, ~, targetState] = ...
        localUnpackState(state);
    design = runtime.observerDesign;
    domain = design.operatingDomain;
    targetDomain = design.target.domain;
    ego = struct("bodyVelocity", bodyVelocity, "yawRate", 0.0);
    tolerance = 128.0*eps(max(1.0, max(abs(state))));
    valid = true;
    speedValid = true;
    violationQuantities = strings(0, 1);
    violationLocations = strings(0, 1);
    [~, estimate] = nrmmTargetTrackerDerivative( ...
        targetState, ego, targetDomain);
    targetLabel = location+"-target";
    minimumTargetSpeed = estimate.targetSpeed;
    maximumTargetAcceleration = abs(estimate.targetScalarAcceleration);
    maximumTargetYawRate = abs(estimate.targetYawRate);
    relativePositionNorm = norm(estimate.relativePosition);
    maximumRelativePosition = relativePositionNorm;
    saturationObserved = estimate.saturationActive;
    [valid, speedValid, violationQuantities, violationLocations] = ...
        localAuditUpperAndLowerBound( ...
        estimate.targetSpeed, targetDomain.speedMinimum, ...
        targetDomain.speedMaximum, "targetSpeed", targetLabel, ...
        valid, speedValid, violationQuantities, ...
        violationLocations, tolerance);
    [valid, ~, violationQuantities, violationLocations] = ...
        localAuditUpperAndLowerBound( ...
        relativePositionNorm, 0.0, ...
        targetDomain.relativePositionMaximum, ...
        "relativePosition", targetLabel, valid, true, ...
        violationQuantities, violationLocations, tolerance);
    if estimate.saturationActive
        valid = false;
        violationQuantities = [violationQuantities; ...
            estimate.saturatedQuantities];
        violationLocations = [violationLocations; ...
            repmat(targetLabel, ...
                numel(estimate.saturatedQuantities), 1)];
    end

    egoSpeed = norm(bodyVelocity);
    [valid, ~, violationQuantities, violationLocations] = ...
        localAuditUpperAndLowerBound( ...
        egoSpeed, domain.egoSpeedMinimum, domain.egoSpeedMaximum, ...
        "egoSpeed", location, valid, true, ...
        violationQuantities, violationLocations, tolerance);

    courseDirectionMagnitude = Inf;
    measuredYawRateMagnitude = 0.0;
    if isfield(observerInput, "gnssVelocity")
        courseDirectionMagnitude = norm(observerInput.gnssVelocity);
        measuredYawRateMagnitude = abs(observerInput.yawRate);
        courseGeometry = observerInput.courseGeometry;
        courseDirectionValid = courseGeometry.correspondence.informative;
        courseKinematicInversionValid = courseGeometry.inversionValid;
        courseModelBoundsConsistent = courseGeometry.boundsConsistent;
        courseTrueSpeedLowerBound = courseGeometry.trueSpeedLowerBound;
        courseSideslipErrorMaximum = courseGeometry.sideslipErrorMaximum;
        [valid, ~, violationQuantities, violationLocations] = ...
            localAuditUpperAndLowerBound( ...
            measuredYawRateMagnitude, 0.0, ...
            domain.measuredYawRateMaximum, ...
            "measuredYawRate", location, valid, true, ...
            violationQuantities, violationLocations, tolerance);
    else
        courseDirectionValid = true;
        courseKinematicInversionValid = true;
        courseModelBoundsConsistent = true;
        courseTrueSpeedLowerBound = Inf;
        courseSideslipErrorMaximum = 0.0;
    end
    directionViolationQuantities = strings(0, 1);
    directionViolationLocations = strings(0, 1);
    if ~courseDirectionValid
        directionViolationQuantities(end+1, 1) = ...
            "courseDirectionMagnitude";
        directionViolationLocations(end+1, 1) = location;
    end

    audit = struct( ...
        "valid", valid, ...
        "speedValid", speedValid, ...
        "directionEndpointsValid", courseDirectionValid, ...
        "yawMeasurementAvailable", courseDirectionValid, ...
        "courseDirectionValid", courseDirectionValid, ...
        "courseKinematicInversionValid", ...
            courseKinematicInversionValid, ...
        "courseModelBoundsConsistent", ...
            courseModelBoundsConsistent, ...
        "minimumCourseTrueSpeedLowerBound", ...
            courseTrueSpeedLowerBound, ...
        "maximumCourseSideslipError", ...
            courseSideslipErrorMaximum, ...
        "headingCorrectionGatedByDirectionAudit", false, ...
        "minimumCourseDirectionMagnitude", courseDirectionMagnitude, ...
        "maximumMeasuredYawRate", measuredYawRateMagnitude, ...
        "minimumTargetSpeed", minimumTargetSpeed, ...
        "maximumTargetScalarAcceleration", maximumTargetAcceleration, ...
        "maximumTargetYawRate", maximumTargetYawRate, ...
        "maximumRelativePosition", maximumRelativePosition, ...
        "targetSaturationObserved", saturationObserved, ...
        "minimumEgoSpeed", egoSpeed, ...
        "maximumEgoSpeed", egoSpeed, ...
        "evaluationPointCount", 1, ...
        "violationQuantities", violationQuantities, ...
        "violationLocations", violationLocations, ...
        "directionViolationQuantities", directionViolationQuantities, ...
        "directionViolationLocations", directionViolationLocations, ...
        "estimatedStateChecked", true, ...
        "trueTrajectoryChecked", false);
end

function [valid, selectedBoundValid, quantities, locations] = ...
        localAuditUpperAndLowerBound( ...
        value, lowerBound, upperBound, quantity, location, ...
        valid, selectedBoundValid, quantities, locations, tolerance)
    within = value >= lowerBound-tolerance ...
        && value <= upperBound+tolerance;
    valid = valid && within;
    selectedBoundValid = selectedBoundValid && within;
    if ~within
        quantities(end+1, 1) = quantity;
        locations(end+1, 1) = location;
    end
end

function combined = localMergeDomainAudits(first, second)
    combined = first;
    combined.valid = first.valid && second.valid;
    combined.speedValid = first.speedValid && second.speedValid;
    combined.directionEndpointsValid = ...
        first.directionEndpointsValid ...
        && second.directionEndpointsValid;
    combined.yawMeasurementAvailable = ...
        first.yawMeasurementAvailable && second.yawMeasurementAvailable;
    combined.courseDirectionValid = ...
        first.courseDirectionValid && second.courseDirectionValid;
    combined.courseKinematicInversionValid = ...
        first.courseKinematicInversionValid ...
        && second.courseKinematicInversionValid;
    combined.courseModelBoundsConsistent = ...
        first.courseModelBoundsConsistent ...
        && second.courseModelBoundsConsistent;
    combined.minimumCourseTrueSpeedLowerBound = min( ...
        first.minimumCourseTrueSpeedLowerBound, ...
        second.minimumCourseTrueSpeedLowerBound);
    combined.maximumCourseSideslipError = max( ...
        first.maximumCourseSideslipError, ...
        second.maximumCourseSideslipError);
    combined.minimumCourseDirectionMagnitude = min( ...
        first.minimumCourseDirectionMagnitude, ...
        second.minimumCourseDirectionMagnitude);
    combined.maximumMeasuredYawRate = max( ...
        first.maximumMeasuredYawRate, second.maximumMeasuredYawRate);
    combined.minimumTargetSpeed = min( ...
        first.minimumTargetSpeed, second.minimumTargetSpeed);
    combined.maximumTargetScalarAcceleration = max( ...
        first.maximumTargetScalarAcceleration, ...
        second.maximumTargetScalarAcceleration);
    combined.maximumTargetYawRate = max( ...
        first.maximumTargetYawRate, second.maximumTargetYawRate);
    combined.maximumRelativePosition = max( ...
        first.maximumRelativePosition, ...
        second.maximumRelativePosition);
    combined.targetSaturationObserved = ...
        first.targetSaturationObserved ...
        || second.targetSaturationObserved;
    combined.minimumEgoSpeed = min( ...
        first.minimumEgoSpeed, second.minimumEgoSpeed);
    combined.maximumEgoSpeed = max( ...
        first.maximumEgoSpeed, second.maximumEgoSpeed);
    combined.evaluationPointCount = ...
        first.evaluationPointCount+second.evaluationPointCount;
    combined.violationQuantities = [ ...
        first.violationQuantities; second.violationQuantities];
    combined.violationLocations = [ ...
        first.violationLocations; second.violationLocations];
    combined.directionViolationQuantities = [ ...
        first.directionViolationQuantities; ...
        second.directionViolationQuantities];
    combined.directionViolationLocations = [ ...
        first.directionViolationLocations; ...
        second.directionViolationLocations];
    combined.estimatedStateChecked = ...
        first.estimatedStateChecked && second.estimatedStateChecked;
    combined.trueTrajectoryChecked = ...
        first.trueTrajectoryChecked && second.trueTrajectoryChecked;
end

function output = localOutput(runtime, observerInput)
