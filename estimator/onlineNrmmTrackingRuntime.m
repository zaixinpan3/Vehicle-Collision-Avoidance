function measurement = localCertifiedYawMeasurement( ...
        gnssVelocity, yawRateMeasured, design)
% localCertifiedYawMeasurement Certified GNSS-course yaw arc.
%
% The corrected course pair is the only rotation correspondence: its arc
% centre is the yaw measurement yF and its radius is BF. An uninformative
% pair is a violated operating-domain assumption, not an estimator output.
    courseGeometry = certifiedKinematicCourseCorrespondence( ...
        gnssVelocity, yawRateMeasured, ...
        design.yaw.courseModel.rearAxleDistance, ...
        design.sensors.velocityNoiseMaximum, ...
        design.sensors.gyroscopeNoiseMaximum, ...
        design.yaw.courseModel.singleTrackYawRateMismatchMaximum, ...
        design.yaw.courseModel.sideslipDomainMaximum);
    course = courseGeometry.correspondence;
    if ~course.informative
        error("onlineNrmmTrackingRuntime:uninformativeCourseChannel", ...
            "The certified course pair must be informative.");
    end
    measurement = struct( ...
        "heading", course.heading, ...
        "radius", course.radius, ...
        "informative", course.informative, ...
        "course", courseGeometry);
end
