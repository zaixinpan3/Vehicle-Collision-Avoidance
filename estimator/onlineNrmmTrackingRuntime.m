        "certificateScope",struct( ...
            "continuousVectorField",true,"sampledImplementationCertified",false, ...
            "positionVelocityInterconnectionCertified",false, ...
            "yawAssessment","orientation set enclosed about the parallel yaw observer"), ...
        "radarDetectionAvailable", ...
            observerInput.radarDetectionAvailable, ...
        "targetCertifiedSpeedDomainValid", ...
            runtime.targetCertifiedSpeedDomainValid, ...
        "targetCertifiedSpeedDomainValidThisInterval", ...
            runtime.lastIntervalTargetCertifiedSpeedDomainValid, ...
        "minimumReconstructedTargetSpeed", ...
            runtime.minimumReconstructedTargetSpeed, ...
        "estimatedOperatingDomainValid", ...
            runtime.estimatedDomainAudit.valid, ...
        "estimatedOperatingDomainValidThisInterval", ...
            runtime.lastIntervalDomainAudit.valid, ...
        "estimatedOperatingDomainAudit", ...
            runtime.estimatedDomainAudit, ...
        "lastIntervalOperatingDomainAudit", ...
            runtime.lastIntervalDomainAudit, ...
        "targetState", runtime.targetState, ...
        "targetEstimate", localTargetEstimate(runtime, observerInput));
    output.relativePositionErrorBound = runtime.positionErrorBound.targetComponents(1);
    if ~runtime.positionErrorBound.valid
        output.relativePositionErrorBound = Inf;
    end
    output.positionErrorBoundAvailable = runtime.positionErrorBound.valid ...
        && isfinite(output.relativePositionErrorBound);
    output.egoYawErrorBound = runtime.positionErrorBound.yaw;
    output.egoBodyVelocityErrorBound = runtime.positionErrorBound.bodyVelocity;
    output.egoInertialVelocitySet = struct( ...
        "orientation",runtime.positionErrorBound.orientationSet, ...
        "bodyCenter",runtime.bodyVelocityEstimate, ...
        "bodyRadius",runtime.positionErrorBound.bodyVelocity, ...
        "trueNormMaximum",design.operatingDomain.egoSpeedMaximum, ...
        "definition","union over yaw of rotated body-frame ball intersected with true norm domain", ...
        "available",runtime.positionErrorBound.egoValid ...
            && runtime.positionErrorBound.orientationSet.valid);
    output.egoInertialVelocityErrorBound = runtime.positionErrorBound.bodyVelocity ...
        +2*min(norm(runtime.bodyVelocityEstimate),design.operatingDomain.egoSpeedMaximum) ...
        *sin(min(runtime.positionErrorBound.yaw,pi)/2);
    if ~output.egoInertialVelocitySet.available
        output.egoInertialVelocityErrorBound = Inf;
    end
    output = nrmmControllerErrorBounds("publish",output, runtime.positionErrorBound, ...
        observerInput, design);
    if output.controllerErrorBound.available && abs(runtime.currentTime-observerInput.time)<1e-9
        output.controllerErrorBound.jointPrediction=nrmmJointPrediction('contract',runtime,observerInput);
    end
end

function estimate = localTargetEstimate(runtime, observerInput)
    design = runtime.observerDesign;
    rotation = localRotation(runtime.yawEstimate);
    planarCross = [0.0, -1.0; 1.0, 0.0];
    ego = struct( ...
        "bodyVelocity", runtime.bodyVelocityEstimate, ...
        "yawRate", observerInput.yawRate);
    measuredBodyAcceleration = observerInput.bodyAcceleration;
    [~, estimate] = nrmmTargetTrackerDerivative( ...
        runtime.targetState, ego, ...
        design.target.domain);
    estimate.certifiedSpeedMinimum = ...
        design.target.domain.speedMinimum;
    estimate.certifiedSpeedDomainValid = ...
        estimate.targetSpeed >= estimate.certifiedSpeedMinimum;
    estimate.relativePositionDerivative = ...
        estimate.targetVelocity-runtime.bodyVelocityEstimate ...
        - observerInput.yawRate*planarCross ...
            * estimate.relativePosition;
    estimate.velocityDifferenceEgoFrame = ...
        estimate.targetVelocity-runtime.bodyVelocityEstimate;
    estimate.accelerationDifferenceEgoFrame = ...
        estimate.targetAcceleration-measuredBodyAcceleration;
    estimate.targetPositionInertial = runtime.positionEstimate ...
        + rotation*estimate.relativePosition;
    estimate.targetVelocityInertial = ...
        rotation*estimate.targetVelocity;
    estimate.targetAccelerationInertial = ...
        rotation*estimate.targetAcceleration;
    estimate.targetCourseAngleInertial = localWrapToPi( ...
        runtime.yawEstimate+estimate.targetCourseAngleEgoFrame);
    estimate.targetHeadingInertial = localWrapToPi( ...
        estimate.targetCourseAngleInertial ...
        - estimate.targetSideslip);
    estimate.stateTime = runtime.currentTime;
    estimate.estimateTime = runtime.currentTime;
    estimate.lastRadarTime = runtime.lastRadarTime;
    radius = runtime.positionErrorBound.targetComponents(1);
    available = runtime.positionErrorBound.valid && isfinite(radius);
    if ~available
        radius = Inf;
    end
    estimate.relativePositionErrorBound = radius;
    estimate.inertialRelativePositionErrorBound = radius ...
        +2*min(norm(estimate.relativePosition),runtime.positionErrorBound.trueRangeMaximum) ...
        *sin(min(runtime.positionErrorBound.yaw,pi)/2);
    estimate.inertialOutputSet = struct("orientation",runtime.positionErrorBound.orientationSet, ...
        "bodyCenters",runtime.targetState, ...
        "bodyRadii",runtime.positionErrorBound.targetComponents, ...
        "trueNormBounds",[runtime.positionErrorBound.trueRangeMaximum; ...
            design.target.domain.speedMaximum;design.target.domain.accelerationNormBound], ...
        "definition","union over yaw of rotated body-frame balls intersected with true norm domains", ...
        "available",available && runtime.positionErrorBound.orientationSet.valid);
    if ~runtime.positionErrorBound.orientationSet.valid
        estimate.inertialRelativePositionErrorBound = Inf;
    end
    estimate.positionErrorBound = struct("time",runtime.currentTime, ...
        "radius",radius,"frame","ego-body-at-state-time", ...
        "available",available,"reason",runtime.positionErrorBound.reason, ...
        "integrationErrorIncluded",true,"floatingPointVerified",false, ...
        "scope",runtime.positionErrorBound.scope, ...
        "futurePredictionIncluded",false);
    % Retained as a compatibility alias with corrected semantics.
    estimate.measurementTime = estimate.lastRadarTime;
    if strlength(runtime.targetIdentifier)>0
        estimate.trackId=runtime.targetIdentifier;
    end
end

function runtime = localRecordMeasurementTimes(runtime, observerInput)
    runtime.lastInputSampleTime = observerInput.time;
    runtime.lastGnssTime = observerInput.time;
    runtime.lastImuTime = observerInput.time;
    runtime.lastGyroscopeTime = observerInput.time;
    if observerInput.radarDetectionAvailable,runtime.lastRadarTime=observerInput.time;end
end

function observerInput = localSynchronizedInput(frame, runtime)
    [radarRelativePosition, radarDetectionAvailable] = ...
        localRadarPosition(frame, runtime);
    observerInput = struct( ...
        "time", localRequiredFrameScalar(frame, "time"), ...
        "gnssPosition", [ ...
            localRequiredFrameScalar(frame, "xGps"); ...
            localRequiredFrameScalar(frame, "yGps")], ...
        "bodyAcceleration", [ ...
            localRequiredFrameScalar(frame, "longitudinalAcceleration"); ...
            localRequiredFrameScalar(frame, "lateralAcceleration")], ...
        "yawRate", localRequiredFrameScalar(frame, "yawRateMeasured"), ...
        "radarRelativePosition", radarRelativePosition, ...
        "radarDetectionAvailable", radarDetectionAvailable, ...
        "radarTargetIdentifier", runtime.targetIdentifier);
    tolerance = localTimeTolerance([observerInput.time; ...
        runtime.currentTime; runtime.samplePeriod]);
    if abs(observerInput.time-runtime.currentTime) > tolerance
        error("onlineNrmmTrackingRuntime:offSampleGrid", ...
            "The synchronized frame time must equal the observer time.");
    end

    % The controller's held input, when the frame carries it, makes the
    % shared-model lateral measurement available (nrmmEgoCourseGeometry).
    observerInput.heldInput = zeros(0,1);
    if isfield(frame,"heldSteeringAngle") && isfield(frame,"heldBrakingRatio")
        observerInput.heldInput = [double(frame.heldSteeringAngle);double(frame.heldBrakingRatio)];
    end
    % These measurements are held over the interval. Reuse their geometry
    % in every RK4 stage, domain audit, and output reconstruction.
    design = runtime.observerDesign;
    posterior=nrmmPositionVelocity("measure",runtime.positionVelocity, ...
        observerInput.gnssPosition,design.sensors.positionNoiseMaximum);
    observerInput.positionVelocity=posterior;
    observerInput.gnssVelocity=posterior.point(3:4); % Derived estimate, not a GNSS channel.
    observerInput.velocityErrorMaximum=posterior.velocityRadius;
    observerInput.velocitySource="position-history-and-imu";
    observerInput.courseGeometry = nrmmEgoCourseGeometry("course",observerInput, design);
end

function [radar, available] = localRadarPosition(frame, runtime)
    if ~isstruct(frame) || ~isscalar(frame) || ~isfield(frame,"radarRelativePosition") ...
            || isempty(frame.radarRelativePosition)
        error("onlineNrmmTrackingRuntime:missingSynchronizedRadar", ...
            "Every observer frame must contain a synchronized radar position.");
    end
    radar=double(frame.radarRelativePosition);
    available=true;
    if isfield(frame,"radarDetectionAvailable") && ~isempty(frame.radarDetectionAvailable)
        available=frame.radarDetectionAvailable;
        if ~isscalar(available) || ~(islogical(available) || ...
                (isnumeric(available) && isfinite(available) && any(available==[0,1])))
            error("onlineNrmmTrackingRuntime:invalidRadarDetectionAvailability", ...
                "radarDetectionAvailable must be a logical scalar.");
        end
        available=logical(available);
    end
    if ~isvector(radar) || numel(radar)~=2
        error("onlineNrmmTrackingRuntime:invalidSynchronizedRadar", ...
            "radarRelativePosition must be a two-vector.");
    end
    radar=radar(:);
    if (available && any(~isfinite(radar))) || (~available && any(~isnan(radar)))
        error("onlineNrmmTrackingRuntime:invalidSynchronizedRadar", ...
            "A detected position must be finite; an unavailable position must be NaN.");
    end
    if isfield(frame,"radarTargetIdentifier") && ~isempty(frame.radarTargetIdentifier)
        identifier=string(frame.radarTargetIdentifier);
        if ~isscalar(identifier) || ismissing(identifier) || strlength(identifier)==0
            error("onlineNrmmTrackingRuntime:invalidRadarTargetIdentifier", ...
                "radarTargetIdentifier must be nonempty scalar text.");
        end
        if identifier~=runtime.targetIdentifier
            error("onlineNrmmTrackingRuntime:unknownRadarTargetIdentifier", ...
                "The measurement identifier must match the initialized target.");
        end
    end
end

function state = localPackState(runtime)
    state = [ ...
        runtime.bodyVelocityEstimate; ...
        runtime.positionEstimate; runtime.gnssPositionPredictor; ...
        runtime.targetState(:); runtime.targetOutputPredictor(:); runtime.yawEstimate];
end

function [bodyVelocity, position, gnssPositionPredictor, targetState, ...
        targetOutputPredictor, yaw] = localUnpackState(state)
    bodyVelocity = state(1:2);
    position = state(3:4);
    gnssPositionPredictor = state(5:6);
    targetState = state(7:12);
    targetOutputPredictor = state(13:14);
    yaw = state(end);
end

function state = localBoundState(packed)
    [velocity,~,~,target,predictor,yaw] = localUnpackState(packed);
    state = struct("yaw",yaw,"bodyVelocity",velocity, ...
        "targetState",target,"radarPredictor",predictor);
end

