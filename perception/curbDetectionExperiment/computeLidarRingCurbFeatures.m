function [maximumValue, valid] = localMaximumAvailable( ...
        leftValue, leftValid, rightValue, rightValid)
    valid = leftValid | rightValid;
    maximumValue = nan(size(leftValue));
    maximumValue(leftValid) = leftValue(leftValid);
    rightOnly = rightValid & ~leftValid;
    maximumValue(rightOnly) = rightValue(rightOnly);
    bothValid = leftValid & rightValid;
    maximumValue(bothValid) = max( ...
        leftValue(bothValid), rightValue(bothValid));
end

function windowIndices = localCircularWindowIndices(pointCount, offsets)
%LOCALCIRCULARWINDOWINDICES Circular neighbor indices, one row per center.
    windowIndices = mod( ...
        (1:pointCount).' + reshape(offsets, 1, []) - 1, pointCount) + 1;
end

function connected = localWindowAllConnected(connectedEdge, radius)
%LOCALWINDOWALLCONNECTED True where every edge within RADIUS is connected.
%   Edge indices (center-radius .. center+radius-1) wrap circularly, which
%   matches walking RADIUS steps in both directions from each center.
    pointCount = numel(connectedEdge);
    connected = false(1, pointCount);
    if pointCount <= 2 * radius
        return;
    end
    edgeCumulative = cumsum([0, connectedEdge, connectedEdge]);
    windowLength = 2 * radius;
    startEdge = mod((1:pointCount) - radius - 1, pointCount) + 1;
    connected = (edgeCumulative(startEdge + windowLength) ...
        - edgeCumulative(startEdge)) == windowLength;
end

function norms = localRowNorms(rowVectors)
%LOCALROWNORMS Per-row Euclidean norms matching scalar norm() bitwise.
    norms = vecnorm(rowVectors, 2, 2);
end

function [smoothness, valid] = localChenSmoothness( ...
        row, centerPoints, connectedEdge, radius)
    pointCount = numel(row.x);
    smoothness = nan(1, pointCount);
    valid = false(1, pointCount);
    windowConnected = localWindowAllConnected(connectedEdge, radius);
    if ~any(windowConnected)
        return;
    end
    centerNorms = localRowNorms(centerPoints);
    usable = windowConnected & reshape(centerNorms > eps, 1, []);
    if ~any(usable)
        return;
    end

    % Neighbor rows are summed in the original walk order:
    % center-1, center-2, ..., center-radius, center+1, ..., center+radius.
    window = localCircularWindowIndices( ...
        pointCount, [-(1:radius), 1:radius]);
    neighborSum = zeros(pointCount, 3);
    for columnIndex = 1:3
        source = centerPoints(:, columnIndex);
        windowValues = reshape(source(window), pointCount, []);
        columnSum = windowValues(:, 1);
        for windowColumn = 2:size(windowValues, 2)
            columnSum = columnSum + windowValues(:, windowColumn);
        end
        neighborSum(:, columnIndex) = columnSum;
    end
    responseVector = neighborSum - 2.0 * radius * centerPoints;
    responseNorms = localRowNorms(responseVector);
    smoothnessColumn = responseNorms ./ (2.0 * radius * centerNorms);
    smoothness(usable) = smoothnessColumn(usable);
    valid = usable;
end

function [arcLength, valid] = localChenSmoothArcLength( ...
        connectedEdge, edgeLengths, chenSmoothness, chenValidity, ...
        direction, smoothnessThreshold, maximumSearchRadius)
%LOCALCHENSMOOTHARCLENGTH Vectorized directional smooth-arc walk.
%   All centers advance one step per iteration; each stalled center keeps
%   its accumulated length, so the per-center addition order matches the
%   original scalar walk exactly.
    pointCount = numel(connectedEdge);
    arcLength = nan(1, pointCount);
    valid = false(1, pointCount);
    if pointCount < 2
        return;
    end
    edgeLengthColumn = reshape(edgeLengths, [], 1);
    if direction > 0
        targetIndex = [2:pointCount, 1];
        stepEdgeIndex = 1:pointCount;
    else
        targetIndex = [pointCount, 1:(pointCount - 1)];
        stepEdgeIndex = [pointCount, 1:(pointCount - 1)];
    end
    stepAllowed = connectedEdge(stepEdgeIndex) ...
        & chenValidity(targetIndex) ...
        & ~(chenSmoothness(targetIndex) > smoothnessThreshold);

    currentIndex = 1:pointCount;
    accumulated = zeros(1, pointCount);
    stepCount = zeros(1, pointCount);
    alive = true(1, pointCount);
    for step = 1:min(maximumSearchRadius, pointCount - 1)
        alive = alive & stepAllowed(currentIndex);
        if ~any(alive)
            break;
        end
        accumulated(alive) = accumulated(alive) ...
            + reshape(edgeLengthColumn( ...
                stepEdgeIndex(currentIndex(alive))), 1, []);
        currentIndex(alive) = targetIndex(currentIndex(alive));
        stepCount(alive) = stepCount(alive) + 1;
    end
    valid = stepCount > 0;
    arcLength(valid) = accumulated(valid);
end

function expectedSpacing = localExpectedHorizontalChord( ...
        centerRange, neighborRange, angularGapDegrees)
    localRadius = 0.5 * (abs(centerRange) + abs(neighborRange));
    expectedSpacing = ...
        2.0 * localRadius .* sind(0.5 * angularGapDegrees);
end

function [residual, valid] = localChordResidual( ...
        row, previousIndex, nextIndex, bothNeighborsValid)
    leftX = row.x(previousIndex);
    leftY = row.y(previousIndex);
    chordX = row.x(nextIndex) - leftX;
    chordY = row.y(nextIndex) - leftY;
    chordLengthSquared = chordX.^2 + chordY.^2;
    valid = bothNeighborsValid & chordLengthSquared > eps;
    projection = ...
        ((row.x - leftX) .* chordX + (row.y - leftY) .* chordY) ...
        ./ chordLengthSquared;
    projection = min(1.0, max(0.0, projection));
    closestX = leftX + projection .* chordX;
    closestY = leftY + projection .* chordY;
    residual = hypot(row.x - closestX, row.y - closestY);
    residual(~valid) = NaN;
end

function [residuals, slopes] = localBatchLineFit(row, radius, centers)
%LOCALBATCHLINEFIT Least-squares z-versus-arc line fit per center.
%   The design matrix, height vector, and accumulation order per center
%   replicate the original per-point construction exactly, and
%   pagemldivide/pagemtimes match per-page mldivide/mtimes bitwise.
    pointCount = numel(row.x);
    windowWidth = 2 * radius + 1;
    centerCount = numel(centers);
    horizontalStep = reshape(hypot( ...
        row.x([2:pointCount, 1]) - row.x, ...
        row.y([2:pointCount, 1]) - row.y), [], 1);

    arcCoordinate = zeros(centerCount, windowWidth);
    leftAccumulated = zeros(centerCount, 1);
    rightAccumulated = zeros(centerCount, 1);
    for step = 1:radius
        leftEdge = mod(centers - step - 1, pointCount) + 1;
        rightEdge = mod(centers + step - 2, pointCount) + 1;
        leftAccumulated = leftAccumulated + horizontalStep(leftEdge);
        rightAccumulated = rightAccumulated + horizontalStep(rightEdge);
        arcCoordinate(:, radius + 1 - step) = -leftAccumulated;
        arcCoordinate(:, radius + 1 + step) = rightAccumulated;
    end

    window = mod(centers + (-radius:radius) - 1, pointCount) + 1;
    heightColumn = reshape(row.z, [], 1);
    windowHeights = reshape(heightColumn(window), centerCount, []);

    designPages = ones(windowWidth, 2, centerCount);
    designPages(:, 1, :) = reshape( ...
        arcCoordinate.', windowWidth, 1, centerCount);
    heightPages = reshape( ...
        windowHeights.', windowWidth, 1, centerCount);
    coefficients = pagemldivide(designPages, heightPages);
    fitted = pagemtimes(designPages, coefficients);
    squaredResiduals = reshape( ...
        (heightPages - fitted).^2, windowWidth, centerCount);
    residuals = sqrt(mean(squaredResiduals, 1));
    slopes = reshape(abs(coefficients(1, 1, :)), 1, centerCount);
end

function [response, valid] = localMultiscaleHaar( ...
        values, connectedEdge, scales)
    pointCount = numel(values);
    response = nan(pointCount, numel(scales));
    valid = false(pointCount, numel(scales));
    valueColumn = reshape(values, [], 1);
    for scaleIndex = 1:numel(scales)
        radius = scales(scaleIndex);
        windowConnected = localWindowAllConnected( ...
            connectedEdge, radius);
        if ~any(windowConnected)
            continue;
        end
        % Left indices keep the walk order center-1, ..., center-radius.
        leftWindow = localCircularWindowIndices( ...
            pointCount, -(1:radius));
        rightWindow = localCircularWindowIndices( ...
            pointCount, 1:radius);
        leftMean = mean(reshape( ...
            valueColumn(leftWindow), pointCount, []), 2);
        rightMean = mean(reshape( ...
            valueColumn(rightWindow), pointCount, []), 2);
        scaleResponse = abs(rightMean - leftMean);
        response(windowConnected, scaleIndex) = ...
            scaleResponse(windowConnected);
        valid(:, scaleIndex) = reshape(windowConnected, [], 1);
    end
end

function [features, validity] = localComputeHuangHdInRadius( ...
        features, validity, x, y, z, baseValid)
    numberOfRings = size(x, 1);
    for ringIndex = 1:numberOfRings
        [lowerDirectionValue, lowerDirectionValid] = ...
            localHuangHdTriplet( ...
                ringIndex, -1, x, y, z, baseValid);
        [upperDirectionValue, upperDirectionValid] = ...
            localHuangHdTriplet( ...
                ringIndex, 1, x, y, z, baseValid);
        [features.huangHdInRadius(ringIndex, :), ...
            validity.huangHdInRadius(ringIndex, :)] = ...
                localMaximumAvailable( ...
                    lowerDirectionValue, lowerDirectionValid, ...
                    upperDirectionValue, upperDirectionValid);
    end
end

function [residualMagnitude, valid] = localHuangHdTriplet( ...
        cRingIndex, direction, x, y, z, baseValid)
    residualMagnitude = nan(1, size(x, 2));
    valid = false(1, size(x, 2));
    bRingIndex = cRingIndex + direction;
    aRingIndex = cRingIndex + 2 * direction;
    if aRingIndex < 1 || aRingIndex > size(x, 1)
        return;
    end

    valid = baseValid(aRingIndex, :) ...
        & baseValid(bRingIndex, :) ...
        & baseValid(cRingIndex, :);
    distanceAb = hypot( ...
        x(bRingIndex, :) - x(aRingIndex, :), ...
        y(bRingIndex, :) - y(aRingIndex, :));
    distanceBc = hypot( ...
        x(cRingIndex, :) - x(bRingIndex, :), ...
        y(cRingIndex, :) - y(bRingIndex, :));
    valid = valid & distanceAb > eps;
    residualMagnitude(valid) = abs( ...
        z(cRingIndex, valid) - z(bRingIndex, valid) ...
        - (z(bRingIndex, valid) - z(aRingIndex, valid)) ...
            .* distanceBc(valid) ./ distanceAb(valid));
end

function [features, validity] = localComputeHataCompression( ...
        features, validity, x, y, baseValid, parameters)
    numberOfRings = size(x, 1);
    for lowerRingIndex = 2:numberOfRings
        upperRingIndex = lowerRingIndex - 1;
        upperColumns = find(baseValid(upperRingIndex, :));
        lowerColumns = find(baseValid(lowerRingIndex, :));
        if isempty(upperColumns) || isempty(lowerColumns)
            continue;
        end
        upperAngle = parameters.verticalAnglesDegrees(upperRingIndex);
        lowerAngle = parameters.verticalAnglesDegrees(lowerRingIndex);
        if upperAngle >= -eps || lowerAngle >= -eps
            continue;
        end
        expectedUpperRange = ...
            parameters.sensorHeightM / tand(-upperAngle);
        expectedLowerRange = ...
            parameters.sensorHeightM / tand(-lowerAngle);
        expectedSpacing = ...
            expectedUpperRange - expectedLowerRange;
        if ~isfinite(expectedSpacing) || expectedSpacing <= eps
            continue;
        end

        upperAzimuth = mod(atan2d( ...
            y(upperRingIndex, upperColumns), ...
            x(upperRingIndex, upperColumns)), 360.0);
        lowerAzimuth = mod(atan2d( ...
            y(lowerRingIndex, lowerColumns), ...
            x(lowerRingIndex, lowerColumns)), 360.0);
        upperHorizontalRange = hypot( ...
            x(upperRingIndex, upperColumns), ...
            y(upperRingIndex, upperColumns));
        lowerHorizontalRange = hypot( ...
            x(lowerRingIndex, lowerColumns), ...
            y(lowerRingIndex, lowerColumns));
        % One row per lower-ring return; min along dim 2 picks the same
        % first-minimum upper index as the original per-point min call.
        angularDistanceMatrix = abs(localWrapTo180( ...
            reshape(upperAzimuth, 1, []) ...
            - reshape(lowerAzimuth, [], 1)));
        [minimumAngularDistance, closestUpperIndex] = ...
            min(angularDistanceMatrix, [], 2);
        withinGap = reshape(minimumAngularDistance, 1, []) ...
            <= parameters.maximumAngularGapDegrees;
        if ~any(withinGap)
            continue;
        end
        observedSpacing = abs( ...
            upperHorizontalRange(closestUpperIndex) ...
            - lowerHorizontalRange);
        rawCompression = expectedSpacing - observedSpacing;
        targetColumns = lowerColumns(withinGap);
        features.hataCompressionRaw(lowerRingIndex, targetColumns) = ...
            rawCompression(withinGap);
        features.hataCompressionExpected( ...
            lowerRingIndex, targetColumns) = expectedSpacing;
        features.hataCompressionNormalized( ...
            lowerRingIndex, targetColumns) = ...
            rawCompression(withinGap) / expectedSpacing;
        validity.hataCompressionRaw( ...
            lowerRingIndex, targetColumns) = true;
        validity.hataCompressionExpected( ...
            lowerRingIndex, targetColumns) = true;
        validity.hataCompressionNormalized( ...
            lowerRingIndex, targetColumns) = true;
    end
end

function angle = localWrapToPi(angle)
    angle = mod(angle + pi, 2.0 * pi) - pi;
end

function angle = localWrapTo180(angle)
    angle = mod(angle + 180.0, 360.0) - 180.0;
end
