        "localHeightStd", scalarNan, ...
        "localRangeStd", scalarNan, ...
        "localHeightRange", scalarNan, ...
        "localMeanElevation", scalarNan, ...
        "chenSmoothness", scalarNan, ...
        "leftSmoothArcLength", scalarNan, ...
