function [features, validity] = localComputeOrderedRingFeatures( ...
        row, parameters)
    pointCount = numel(row.x);
    [features, validity] = localInitializeRowOutputs( ...
        pointCount, numel(parameters.haarScales));
    if pointCount < 2
        return;
    end

    angularGapDegrees = mod( ...
        [diff(row.azimuthDegrees), ...
         row.azimuthDegrees(1) + 360.0 - row.azimuthDegrees(end)], ...
        360.0);
    connectedEdge = ...
        angularGapDegrees > eps ...
        & angularGapDegrees <= parameters.maximumAngularGapDegrees;
    previousIndex = [pointCount, 1:(pointCount - 1)];
    nextIndex = [2:pointCount, 1];
    leftConnected = connectedEdge(previousIndex);
    rightConnected = connectedEdge;

    leftHeightStep = abs(row.z - row.z(previousIndex));
    rightHeightStep = abs(row.z(nextIndex) - row.z);
    leftRangeStep = abs(row.range - row.range(previousIndex));
    rightRangeStep = abs(row.range(nextIndex) - row.range);
    [features.heightStep, validity.heightStep] = ...
        localMaximumAvailable( ...
            leftHeightStep, leftConnected, ...
            rightHeightStep, rightConnected);
    [features.rangeStep, validity.rangeStep] = ...
        localMaximumAvailable( ...
            leftRangeStep, leftConnected, ...
            rightRangeStep, rightConnected);

    centerPoints = [row.x(:), row.y(:), row.z(:)];
    [features.chenSmoothness, validity.chenSmoothness] = ...
        localChenSmoothness( ...
            row, centerPoints, connectedEdge, parameters.chenRadius);
    edgeLengths = localRowNorms( ...
        centerPoints(nextIndex, :) - centerPoints);
    [features.leftSmoothArcLength, ...
        validity.leftSmoothArcLength] = localChenSmoothArcLength( ...
            connectedEdge, edgeLengths, features.chenSmoothness, ...
            validity.chenSmoothness, -1, ...
            parameters.chenSmoothnessThreshold, ...
            parameters.smoothArcMaximumSearchRadius);
    [features.rightSmoothArcLength, ...
        validity.rightSmoothArcLength] = localChenSmoothArcLength( ...
            connectedEdge, edgeLengths, features.chenSmoothness, ...
            validity.chenSmoothness, 1, ...
            parameters.chenSmoothnessThreshold, ...
            parameters.smoothArcMaximumSearchRadius);

    bothNeighborsValid = leftConnected & rightConnected;
    leftPoints = centerPoints(previousIndex, :);
    rightPoints = centerPoints(nextIndex, :);
    leftHorizontalGap = hypot( ...
        row.x - row.x(previousIndex), ...
        row.y - row.y(previousIndex));
    rightHorizontalGap = hypot( ...
        row.x(nextIndex) - row.x, ...
        row.y(nextIndex) - row.y);
    leftSlope = atan2( ...
        row.z - row.z(previousIndex), leftHorizontalGap);
    rightSlope = atan2( ...
        row.z(nextIndex) - row.z, rightHorizontalGap);
    leftSlopeMagnitudeValid = leftConnected & leftHorizontalGap > eps;
    rightSlopeMagnitudeValid = rightConnected & rightHorizontalGap > eps;
    [features.sameRingSlopeMagnitude, ...
        validity.sameRingSlopeMagnitude] = localMaximumAvailable( ...
            abs(leftSlope), leftSlopeMagnitudeValid, ...
            abs(rightSlope), rightSlopeMagnitudeValid);
    validity.sameRingSlopeChange = bothNeighborsValid ...
        & leftHorizontalGap > eps & rightHorizontalGap > eps;
    features.sameRingSlopeChange = abs( ...
        localWrapToPi(rightSlope - leftSlope));
    features.sameRingSlopeChange( ...
        ~validity.sameRingSlopeChange) = NaN;

    leftVector = leftPoints - centerPoints;
    rightVector = rightPoints - centerPoints;
    leftNorm = sqrt(sum(leftVector.^2, 2));
    rightNorm = sqrt(sum(rightVector.^2, 2));
    validity.bilateralTangentDeflection = ...
        reshape(bothNeighborsValid, [], 1) ...
        & leftNorm > eps & rightNorm > eps;
    bilateralCosine = sum(leftVector .* rightVector, 2) ...
        ./ (leftNorm .* rightNorm);
    bilateralCosine = min(1.0, max(-1.0, bilateralCosine));
    bilateralDeflection = pi - acos(bilateralCosine);
    bilateralDeflection( ...
        ~validity.bilateralTangentDeflection(:)) = NaN;
    features.bilateralTangentDeflection = ...
        reshape(bilateralDeflection, 1, []);
    validity.bilateralTangentDeflection = reshape( ...
        validity.bilateralTangentDeflection, 1, []);

    centerRoadPlane = centerPoints(:, 1:2);
    neighborRoadPlaneChord = ...
        rightPoints(:, 1:2) - leftPoints(:, 1:2);
    radialNorm = sqrt(sum(centerRoadPlane.^2, 2));
    chordNorm = sqrt(sum(neighborRoadPlaneChord.^2, 2));
    validity.huangTangentialStrength = ...
        reshape(bothNeighborsValid, [], 1) ...
        & radialNorm > eps & chordNorm > eps;
    huangStrength = abs(sum( ...
        centerRoadPlane .* neighborRoadPlaneChord, 2)) ...
        ./ (radialNorm .* chordNorm);
    huangStrength(~validity.huangTangentialStrength(:)) = NaN;
    features.huangTangentialStrength = reshape(huangStrength, 1, []);
    validity.huangTangentialStrength = reshape( ...
        validity.huangTangentialStrength, 1, []);

    leftRadiusRatioValid = leftConnected ...
        & abs(row.range(previousIndex)) > eps;
    rightRadiusRatioValid = rightConnected ...
        & abs(row.range(nextIndex)) > eps;
    leftRadiusRatioDeviation = nan(size(row.range));
    rightRadiusRatioDeviation = nan(size(row.range));
    leftRadiusRatioDeviation(leftRadiusRatioValid) = abs( ...
        row.range(leftRadiusRatioValid) ...
            ./ row.range(previousIndex(leftRadiusRatioValid)) - 1.0);
    rightRadiusRatioDeviation(rightRadiusRatioValid) = abs( ...
        row.range(rightRadiusRatioValid) ...
            ./ row.range(nextIndex(rightRadiusRatioValid)) - 1.0);
    [features.huangRadiusRatioDeviation, ...
        validity.huangRadiusRatioDeviation] = localMaximumAvailable( ...
            leftRadiusRatioDeviation, leftRadiusRatioValid, ...
            rightRadiusRatioDeviation, rightRadiusRatioValid);

    validity.hataDifferentialHeightResponse = bothNeighborsValid;
    features.hataDifferentialHeightResponse = 2.0 * abs( ...
        row.z(nextIndex) - row.z(previousIndex));
    features.hataDifferentialHeightResponse( ...
        ~validity.hataDifferentialHeightResponse) = NaN;

    leftAngularGap = angularGapDegrees(previousIndex);
    rightAngularGap = angularGapDegrees;
    totalAngularGap = leftAngularGap + rightAngularGap;
    validity.radiusRatioReconstructionDeviation = ...
        bothNeighborsValid & totalAngularGap > eps;
    reconstructedRadius = ...
        (rightAngularGap .* row.range(previousIndex) ...
            + leftAngularGap .* row.range(nextIndex)) ...
        ./ totalAngularGap;
    features.radiusRatioReconstructionDeviation = abs( ...
        row.range ./ reconstructedRadius - 1.0);
    validity.radiusRatioReconstructionDeviation = ...
        validity.radiusRatioReconstructionDeviation ...
        & isfinite(reconstructedRadius) ...
        & abs(reconstructedRadius) > eps;
    features.radiusRatioReconstructionDeviation( ...
        ~validity.radiusRatioReconstructionDeviation) = NaN;

    leftExpectedSpacing = localExpectedHorizontalChord( ...
        row.range, row.range(previousIndex), leftAngularGap);
    rightExpectedSpacing = localExpectedHorizontalChord( ...
        row.range, row.range(nextIndex), rightAngularGap);
    leftSpacingRatio = leftHorizontalGap ./ leftExpectedSpacing;
    rightSpacingRatio = rightHorizontalGap ./ rightExpectedSpacing;
    validity.wangHorizontalSpacingRatio = bothNeighborsValid ...
        & leftExpectedSpacing > eps & rightExpectedSpacing > eps;
    features.wangHorizontalSpacingRatio = max( ...
        leftSpacingRatio, rightSpacingRatio);
    features.wangHorizontalSpacingRatio( ...
        ~validity.wangHorizontalSpacingRatio) = NaN;
    validity.wangHorizontalSpacingExcess = ...
        validity.wangHorizontalSpacingRatio;
    features.wangHorizontalSpacingExcess = max( ...
        0.0, features.wangHorizontalSpacingRatio - 1.0);

    validity.radialSecondDifference = bothNeighborsValid;
    features.radialSecondDifference = abs( ...
        row.range(previousIndex) - 2.0 * row.range ...
            + row.range(nextIndex));
    features.radialSecondDifference( ...
        ~validity.radialSecondDifference) = NaN;

    [features.localChordResidual, validity.localChordResidual] = ...
        localChordResidual(row, previousIndex, nextIndex, ...
            bothNeighborsValid);

    [features, validity] = localWindowStatistics( ...
        features, validity, row, connectedEdge, parameters);

    [features.localMultiscaleHaarZ, ...
        validity.localMultiscaleHaarZ] = localMultiscaleHaar( ...
            row.z, connectedEdge, parameters.haarScales);
    [features.localMultiscaleHaarRange, ...
        validity.localMultiscaleHaarRange] = localMultiscaleHaar( ...
            row.range, connectedEdge, parameters.haarScales);
end

function [features, validity] = localWindowStatistics( ...
        features, validity, row, connectedEdge, parameters)
%LOCALWINDOWSTATISTICS Vectorized symmetric-window statistics and line fit.
    pointCount = numel(row.x);
    heightColumn = reshape(row.z, [], 1);
    rangeColumn = reshape(row.range, [], 1);

    statisticsConnected = localWindowAllConnected( ...
        connectedEdge, parameters.statisticsRadius);
    if any(statisticsConnected)
        window = localCircularWindowIndices(pointCount, ...
            -parameters.statisticsRadius:parameters.statisticsRadius);
        windowHeights = reshape(heightColumn(window), pointCount, []);
        windowRanges = reshape(rangeColumn(window), pointCount, []);
        heightStd = std(windowHeights, 0, 2);
        rangeStd = std(windowRanges, 0, 2);
        heightRange = max(windowHeights, [], 2) ...
            - min(windowHeights, [], 2);
        meanElevation = mean(windowHeights, 2);
        features.localHeightStd(statisticsConnected) = ...
            heightStd(statisticsConnected);
        features.localRangeStd(statisticsConnected) = ...
            rangeStd(statisticsConnected);
        features.localHeightRange(statisticsConnected) = ...
            heightRange(statisticsConnected);
        features.localMeanElevation(statisticsConnected) = ...
            meanElevation(statisticsConnected);
        validity.localHeightStd = statisticsConnected;
        validity.localRangeStd = statisticsConnected;
        validity.localHeightRange = statisticsConnected;
        validity.localMeanElevation = statisticsConnected;
    end

    lineConnected = localWindowAllConnected( ...
        connectedEdge, parameters.lineFitRadius);
    if any(lineConnected)
        centers = reshape(find(lineConnected), [], 1);
        [residuals, slopes] = localBatchLineFit( ...
            row, parameters.lineFitRadius, centers);
        features.ilpLineFitResidual(lineConnected) = residuals;
        features.ilpLineSlopeMagnitude(lineConnected) = slopes;
        validity.ilpLineFitResidual = lineConnected;
        validity.ilpLineSlopeMagnitude = lineConnected;
    end
end

function [features, validity] = localInitializeRowOutputs( ...
