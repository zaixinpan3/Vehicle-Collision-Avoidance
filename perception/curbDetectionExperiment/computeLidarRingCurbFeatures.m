function [features, featureValidity] = ...
        computeLidarRingCurbFeatures(frame, cfg)
%COMPUTELIDARRINGCURBFEATURES Compute side-agnostic LiDAR ring features.
%   [FEATURES, FEATUREVALIDITY] =
%   COMPUTELIDARRINGCURBFEATURES(FRAME, CFG) computes curb evidence from the
%   valid returns of each organized LiDAR ring. Required FRAME fields x, y,
%   z, and range are [ring x azimuth-bin] matrices. An optional valid
%   matrix uses the same layout.
%
%   Empty organized bins are skipped. Valid returns are sorted by their
%   measured atan2(y,x) azimuth, and a neighborhood path is usable only when
%   every consecutive measured angular gap is no larger than 2.1 degrees by
%   default. The ordered sequence wraps through 360 degrees.
%
%   Scalar feature fields have the same size as FRAME.z. The local
%   multiscale Haar response fields have size [ring x azimuth-bin x scale].
%   Invalid feature values are NaN. FEATUREVALIDITY contains a same-named
%   logical array for every feature and a base field for finite valid input.
%
%   The Chen feature is
%       norm(sum(neighbor XYZ) - 2*k*center XYZ) ...
%           / (2*k*norm(center XYZ)).
%   bilateralTangentDeflection is the Wang-style angle between the two
%   adjacent 3D vectors. huangTangentialStrength is evaluated strictly in
%   the XY road-plane projection as
%       abs(OP dot MN) / (norm(OP)*norm(MN)),
%   where O is the sensor, P is the center return, and MN is the chord
%   joining its immediate same-ring neighbors.
%   huangRadiusRatioDeviation is the maximum available value of
%       abs(r_i/r_(i-1) - 1) and abs(r_i/r_(i+1) - 1)
%   over connected immediate same-ring neighbors.
%   huangHdInRadius evaluates Huang's three-beam same-azimuth residual
%       abs(z_C - z_B - (z_B - z_A)*d_BC/d_AB),
%   where d is XY-projected distance. Each return C evaluates triplets in
%   both ring-index directions and retains the maximum available magnitude.
%   sameRingSlopeMagnitude is the maximum available absolute atan2(dz,dxy)
%   over the two immediate same-ring edges. hataDifferentialHeightResponse
%   is the absolute Hata [-2, 0, +2] height-stencil response,
%       2*abs(z_(i+1) - z_(i-1)).
%   localMeanElevation is mean z over the statistics window.
%   ilpLineFitResidual and ilpLineSlopeMagnitude respectively report the
%   RMS residual and absolute slope of one least-squares line fitted to z
%   versus accumulated horizontal arc length.
%
%   Hata adjacent-ring compression uses each valid lower-ring return and
%   the closest-azimuth valid return in the immediately upper ring. For
%   downward vertical angles, expected flat-ground horizontal spacing is
%   computed from sensor height. Raw compression is expected spacing minus
%   observed radial spacing; normalized compression divides by expected
%   spacing.
%
%   Supported CFG fields and defaults are:
%       ringFeatureStatisticsRadius                  2 returns
%       ringFeatureChenRadius                        2 returns
%       ringFeatureChenSmoothnessThreshold           0.005
%       ringFeatureSmoothArcMaximumSearchRadius      8 returns
%       ringFeatureLineFitRadius                     3 returns
%       ringFeatureHaarScales                  [1, 2, 4] returns
%       ringFeatureMaximumAngularGapDegrees           2.1 degrees
%       ringFeatureSensorHeightM                      2.35 m
%       ringFeatureUpperVerticalAngleDegrees         10.0 degrees
%       ringFeatureLowerVerticalAngleDegrees        -30.0 degrees
%       ringFeatureVerticalAnglesDegrees             optional vector

    if nargin < 2 || isempty(cfg)
        cfg = struct();
    end
    if ~isstruct(frame) || ~isscalar(frame)
        error( ...
            "computeLidarRingCurbFeatures:InvalidFrame", ...
            "frame must be a scalar structure.");
    end
    if ~isstruct(cfg) || ~isscalar(cfg)
        error( ...
            "computeLidarRingCurbFeatures:InvalidConfig", ...
            "cfg must be a scalar structure.");
    end

    [x, y, z, radialRange, baseValid] = ...
        localValidateAndConvertFrame(frame);
    parameters = localFeatureParameters(cfg, size(z, 1));
    [features, featureValidity] = localInitializeOutputs( ...
        size(z), parameters.haarScales, baseValid);

    scalarFeatureNames = [ ...
        "heightStep", ...
        "rangeStep", ...
        "localHeightStd", ...
        "localRangeStd", ...
        "localHeightRange", ...
        "localMeanElevation", ...
        "chenSmoothness", ...
        "leftSmoothArcLength", ...
        "rightSmoothArcLength", ...
        "sameRingSlopeMagnitude", ...
        "sameRingSlopeChange", ...
        "bilateralTangentDeflection", ...
        "huangTangentialStrength", ...
        "huangRadiusRatioDeviation", ...
        "hataDifferentialHeightResponse", ...
        "radiusRatioReconstructionDeviation", ...
        "wangHorizontalSpacingRatio", ...
        "wangHorizontalSpacingExcess", ...
        "radialSecondDifference", ...
        "localChordResidual", ...
        "ilpLineFitResidual", ...
        "ilpLineSlopeMagnitude"];
    haarFeatureNames = [ ...
        "localMultiscaleHaarZ", ...
        "localMultiscaleHaarRange"];

    for ringIndex = 1:size(z, 1)
        organizedColumns = find(baseValid(ringIndex, :));
        if isempty(organizedColumns)
            continue;
        end
        measuredAzimuthDegrees = mod(atan2d( ...
            y(ringIndex, organizedColumns), ...
            x(ringIndex, organizedColumns)), 360.0);
        [measuredAzimuthDegrees, order] = sort(measuredAzimuthDegrees);
        organizedColumns = organizedColumns(order);
        row = struct( ...
            "x", x(ringIndex, organizedColumns), ...
            "y", y(ringIndex, organizedColumns), ...
            "z", z(ringIndex, organizedColumns), ...
            "range", radialRange(ringIndex, organizedColumns), ...
            "azimuthDegrees", measuredAzimuthDegrees);

        [rowFeatures, rowValidity] = ...
            localComputeOrderedRingFeatures(row, parameters);
        for fieldName = scalarFeatureNames
            features.(fieldName)(ringIndex, organizedColumns) = ...
                rowFeatures.(fieldName);
            featureValidity.(fieldName)(ringIndex, organizedColumns) = ...
                rowValidity.(fieldName);
        end
        for fieldName = haarFeatureNames
            features.(fieldName)(ringIndex, organizedColumns, :) = ...
                reshape( ...
                    rowFeatures.(fieldName), ...
                    [1, numel(organizedColumns), ...
                     numel(parameters.haarScales)]);
            featureValidity.(fieldName)( ...
                ringIndex, organizedColumns, :) = reshape( ...
                    rowValidity.(fieldName), ...
                    [1, numel(organizedColumns), ...
                     numel(parameters.haarScales)]);
        end
    end

    [features, featureValidity] = localComputeHuangHdInRadius( ...
        features, featureValidity, x, y, z, baseValid);
    [features, featureValidity] = localComputeHataCompression( ...
        features, featureValidity, x, y, baseValid, parameters);
end

function [x, y, z, radialRange, valid] = ...
        localValidateAndConvertFrame(frame)
    requiredFields = ["x", "y", "z", "range"];
    if ~all(isfield(frame, requiredFields))
        error( ...
            "computeLidarRingCurbFeatures:MissingFrameField", ...
            "frame must contain numeric x, y, z, and range matrices.");
    end

    referenceSize = size(frame.z);
    if numel(referenceSize) ~= 2 || any(referenceSize == 0)
        error( ...
            "computeLidarRingCurbFeatures:InvalidFrameSize", ...
            "frame matrices must be nonempty two-dimensional arrays.");
    end
    for fieldName = requiredFields
        candidate = frame.(fieldName);
        if ~isnumeric(candidate) || ~isreal(candidate) ...
                || ~isequal(size(candidate), referenceSize)
            error( ...
                "computeLidarRingCurbFeatures:InconsistentFrameSize", ...
                "frame.%s must be a real numeric matrix matching frame.z.", ...
                fieldName);
        end
    end

    x = double(frame.x);
    y = double(frame.y);
    z = double(frame.z);
    radialRange = double(frame.range);
    valid = isfinite(x) & isfinite(y) & isfinite(z) ...
        & isfinite(radialRange) & hypot(x, y) > eps;
    if isfield(frame, "valid")
        if ~(islogical(frame.valid) || isnumeric(frame.valid)) ...
                || ~isequal(size(frame.valid), referenceSize)
            error( ...
                "computeLidarRingCurbFeatures:InvalidValidityMask", ...
                "frame.valid must match the organized frame size.");
        end
        valid = valid & logical(frame.valid);
    end
end

function parameters = localFeatureParameters(cfg, numberOfRings)
    parameters = struct( ...
        "statisticsRadius", localPositiveIntegerConfigValue( ...
            cfg, "ringFeatureStatisticsRadius", 2), ...
        "chenRadius", localPositiveIntegerConfigValue( ...
            cfg, "ringFeatureChenRadius", 2), ...
        "chenSmoothnessThreshold", max(0.0, localScalarConfigValue( ...
            cfg, "ringFeatureChenSmoothnessThreshold", 0.005)), ...
        "smoothArcMaximumSearchRadius", ...
            localPositiveIntegerConfigValue( ...
                cfg, ...
                "ringFeatureSmoothArcMaximumSearchRadius", ...
                8), ...
        "lineFitRadius", localPositiveIntegerConfigValue( ...
            cfg, "ringFeatureLineFitRadius", 3), ...
        "haarScales", localHaarScales(cfg), ...
        "maximumAngularGapDegrees", max(eps, localScalarConfigValue( ...
            cfg, "ringFeatureMaximumAngularGapDegrees", 2.1)), ...
        "sensorHeightM", max(eps, localScalarConfigValue( ...
            cfg, "ringFeatureSensorHeightM", 2.35)), ...
        "verticalAnglesDegrees", localVerticalAngles( ...
            cfg, numberOfRings));
end

function value = localPositiveIntegerConfigValue( ...
        cfg, fieldName, defaultValue)
    value = localScalarConfigValue(cfg, fieldName, defaultValue);
    if value < 1 || value ~= floor(value)
        error( ...
            "computeLidarRingCurbFeatures:InvalidRadius", ...
            "%s must be a positive integer.", fieldName);
    end
end

function value = localScalarConfigValue(cfg, fieldName, defaultValue)
    value = double(defaultValue);
    if ~isfield(cfg, fieldName)
        return;
    end
    candidate = cfg.(fieldName);
    if ~isnumeric(candidate) || ~isreal(candidate) ...
            || ~isscalar(candidate) || ~isfinite(candidate)
        error( ...
            "computeLidarRingCurbFeatures:InvalidConfigValue", ...
            "%s must be a finite real numeric scalar.", fieldName);
    end
    value = double(candidate);
end

function scales = localHaarScales(cfg)
    scales = [1, 2, 4];
    fieldName = "ringFeatureHaarScales";
    if ~isfield(cfg, fieldName)
        return;
    end
    candidate = cfg.(fieldName);
    if ~isnumeric(candidate) || ~isreal(candidate) ...
            || ~isvector(candidate) || isempty(candidate) ...
            || any(~isfinite(candidate)) ...
            || any(candidate < 1) ...
            || any(candidate ~= floor(candidate))
        error( ...
            "computeLidarRingCurbFeatures:InvalidHaarScales", ...
            "ringFeatureHaarScales must contain positive integers.");
    end
    scales = unique(reshape(double(candidate), 1, []), "stable");
end

function verticalAnglesDegrees = localVerticalAngles(cfg, numberOfRings)
    fieldName = "ringFeatureVerticalAnglesDegrees";
    if isfield(cfg, fieldName)
        candidate = cfg.(fieldName);
        if ~isnumeric(candidate) || ~isreal(candidate) ...
                || ~isvector(candidate) ...
                || numel(candidate) ~= numberOfRings ...
                || any(~isfinite(candidate))
            error( ...
                "computeLidarRingCurbFeatures:InvalidVerticalAngles", ...
                "ringFeatureVerticalAnglesDegrees must contain one " + ...
                "finite angle per organized ring.");
        end
        verticalAnglesDegrees = reshape(double(candidate), 1, []);
        return;
    end
    upperAngle = localScalarConfigValue( ...
        cfg, "ringFeatureUpperVerticalAngleDegrees", 10.0);
    lowerAngle = localScalarConfigValue( ...
        cfg, "ringFeatureLowerVerticalAngleDegrees", -30.0);
    verticalAnglesDegrees = linspace( ...
        upperAngle, lowerAngle, numberOfRings);
end

