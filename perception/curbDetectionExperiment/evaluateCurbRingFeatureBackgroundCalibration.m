end


function finiteValues = localFinite(values)
    finiteValues = values(isfinite(values));
end


function rate = localRate(mask)
    if isempty(mask)
        rate = NaN;
    else
        rate = mean(mask);
    end
end


function auc = localAuc(positiveValues, negativeValues)
    positiveValues = localFinite(positiveValues);
    negativeValues = localFinite(negativeValues);
    positiveCount = numel(positiveValues);
    negativeCount = numel(negativeValues);
    if positiveCount == 0 || negativeCount == 0
        auc = NaN;
        return;
    end

    combined = [positiveValues(:); negativeValues(:)];
    [~, ~, valueGroup] = unique(combined);
    groupCount = accumarray(valueGroup, 1);
    firstRank = [1; 1 + cumsum(groupCount(1:end - 1))];
    averageRank = firstRank + 0.5*(groupCount - 1);
    rankSum = sum(averageRank(valueGroup(1:positiveCount)));
    auc = (rankSum - positiveCount*(positiveCount + 1)/2) ...
        / (positiveCount*negativeCount);
end


function value = localEmpiricalQuantile(values, probability)
    values = sort(localFinite(values));
    if isempty(values)
        value = NaN;
        return;
    end
    position = 1 + (numel(values) - 1)*probability;
    lowerIndex = floor(position);
    upperIndex = ceil(position);
    if lowerIndex == upperIndex
        value = values(lowerIndex);
    else
        fraction = position - lowerIndex;
        value = values(lowerIndex)*(1 - fraction) ...
            + values(upperIndex)*fraction;
    end
end
