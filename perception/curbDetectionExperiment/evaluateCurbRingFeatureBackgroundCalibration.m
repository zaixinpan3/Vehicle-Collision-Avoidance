function [gridTable, frameTable] = localEvaluateRuleGrid( ...
        positiveFeatures, positiveRanks, positiveFrames, ...
        localFeatures, localRanks, globalFeatures, globalRanks, ...
        hardNegativeFeatures, hardNegativeRanks, ...
        positiveFamilyScores, positiveFamilyRanks, ...
        localFamilyScores, localFamilyRanks, ...
        globalFamilyScores, globalFamilyRanks, ...
        hardNegativeFamilyScores, hardNegativeFamilyRanks, ...
        featureFamilies, familyNames, ...
        commonMultipliers, backgroundQuantiles, ...
        localPercentiles, minimumVotes, minimumSalientVotes)
    familyCount = numel(familyNames);
    commonCount = numel(commonMultipliers);
    quantileCount = size(backgroundQuantiles, 1);
    thresholdCount = commonCount + quantileCount;
    thresholdModes = strings(thresholdCount, 1);
    multiplierRows = zeros(thresholdCount, familyCount);
    for multiplierIndex = 1:commonCount
        multiplier = commonMultipliers(multiplierIndex);
        thresholdModes(multiplierIndex) = ...
            "common-" + string(multiplier);
        multiplierRows(multiplierIndex, :) = ...
            repmat(multiplier, 1, familyCount);
    end
    quantileNames = ["global-q90", "global-q95", ...
        "global-q97_5", "global-q99"];
    for quantileIndex = 1:quantileCount
        outputIndex = commonCount + quantileIndex;
        thresholdModes(outputIndex) = quantileNames(quantileIndex);
        multiplierRows(outputIndex, :) = ...
            backgroundQuantiles(quantileIndex, :);
    end

    formationNames = [ ...
        "any-member", "vertical-pair", "radial-pair", ...
        "shape-pair", "vertical-radial-pairs", ...
        "all-multimember-pairs"];
    noSaliencyFormationCount = numel(formationNames);
    saliencyStrategyCount = numel(formationNames) + 1;
    saliencyCombinationCount = noSaliencyFormationCount ...
        + nnz(localPercentiles > 0)*numel(minimumSalientVotes) ...
            * saliencyStrategyCount;
    ruleCount = size(multiplierRows, 1) ...
        * saliencyCombinationCount*numel(minimumVotes);
    rows = cell(ruleCount, 1);
    frameRows = cell(ruleCount, 1);
    ruleIndex = 0;
    for thresholdIndex = 1:size(multiplierRows, 1)
        thresholds = multiplierRows(thresholdIndex, :);
        for localPercentile = localPercentiles
            if localPercentile > 0
                salientVoteCandidates = minimumSalientVotes;
                saliencyBases = [ ...
                    repmat("member-feature", ...
                        1, numel(formationNames)), ...
                    "family-maximum"];
                familyFormations = [formationNames, "any-member"];
            else
                salientVoteCandidates = 0;
                saliencyBases = repmat( ...
                    "none", 1, numel(formationNames));
                familyFormations = formationNames;
            end
            for voteCount = minimumVotes
                for salientVoteCount = salientVoteCandidates
                    for strategyIndex = 1:numel(saliencyBases)
                        saliencyBasis = saliencyBases(strategyIndex);
                        familyFormation = ...
                            familyFormations(strategyIndex);
                        minimumMemberCounts = ...
                            localFormationMemberCounts( ...
                                familyFormation);
                        ruleIndex = ruleIndex + 1;
                        if saliencyBasis == "family-maximum"
                            positiveAccepted = localApplyFamilyRule( ...
                                positiveFamilyScores, ...
                                positiveFamilyRanks, thresholds, ...
                                localPercentile, voteCount, ...
                                salientVoteCount);
                            localAccepted = localApplyFamilyRule( ...
                                localFamilyScores, localFamilyRanks, ...
                                thresholds, localPercentile, ...
                                voteCount, salientVoteCount);
                            globalAccepted = localApplyFamilyRule( ...
                                globalFamilyScores, ...
                                globalFamilyRanks, thresholds, ...
                                localPercentile, voteCount, ...
                                salientVoteCount);
                            hardNegativeAccepted = ...
                                localApplyFamilyRule( ...
                                    hardNegativeFamilyScores, ...
                                    hardNegativeFamilyRanks, ...
                                    thresholds, localPercentile, ...
                                    voteCount, salientVoteCount);
                        else
                            positiveAccepted = ...
                                localApplyFeatureRule( ...
                                    positiveFeatures, ...
                                    positiveRanks, featureFamilies, ...
                                    familyNames, thresholds, ...
                                    localPercentile, voteCount, ...
                                    salientVoteCount, ...
                                    minimumMemberCounts);
                            localAccepted = ...
                                localApplyFeatureRule( ...
                                    localFeatures, localRanks, ...
                                    featureFamilies, familyNames, ...
                                    thresholds, localPercentile, ...
                                    voteCount, salientVoteCount, ...
                                    minimumMemberCounts);
                            globalAccepted = ...
                                localApplyFeatureRule( ...
                                    globalFeatures, globalRanks, ...
                                    featureFamilies, familyNames, ...
                                    thresholds, localPercentile, ...
                                    voteCount, salientVoteCount, ...
                                    minimumMemberCounts);
                            hardNegativeAccepted = ...
                                localApplyFeatureRule( ...
                                    hardNegativeFeatures, ...
                                    hardNegativeRanks, ...
                                    featureFamilies, familyNames, ...
                                    thresholds, localPercentile, ...
                                    voteCount, salientVoteCount, ...
                                    minimumMemberCounts);
                        end
                        [minimumFrameRecall, medianFrameRecall, ...
                            currentFrameTable] = localFrameRecall( ...
                                positiveFrames, positiveAccepted, ...
                                ruleIndex);
                        frameRows{ruleIndex} = currentFrameTable;
                        rows{ruleIndex} = table( ...
                            ruleIndex, ...
                            thresholdModes(thresholdIndex), ...
                            saliencyBasis, familyFormation, ...
                            thresholds(1), thresholds(2), ...
                            thresholds(3), thresholds(4), ...
                            localPercentile, voteCount, ...
                            salientVoteCount, ...
                            nnz(positiveAccepted), ...
                            localRate(positiveAccepted), ...
                            minimumFrameRecall, ...
                            medianFrameRecall, ...
                            nnz(localAccepted), ...
                            localRate(localAccepted), ...
                            nnz(globalAccepted), ...
                            localRate(globalAccepted), ...
                            nnz(hardNegativeAccepted), ...
                            localRate(hardNegativeAccepted), ...
                            VariableNames=[ ...
                                "ruleIndex", "thresholdMode", ...
                                "saliencyBasis", "familyFormation", ...
                                "compressionMultiplier", ...
                                "verticalMultiplier", ...
                                "radialMultiplier", ...
                                "shapeMultiplier", ...
                                "localPercentile", ...
                                "minimumFamilyVotes", ...
                                "minimumSalientFamilyVotes", ...
                                "positiveAcceptedCount", ...
                                "positiveRecall", ...
                                "minimumFrameRecall", ...
                                "medianFrameRecall", ...
                                "localBackgroundAcceptedCount", ...
                                "localBackgroundActivation", ...
                                "globalBackgroundAcceptedCount", ...
                                "globalBackgroundActivation", ...
                                "hardNegativeAcceptedCount", ...
                                "hardNegativeActivation"]);
                    end
                end
            end
        end
    end
    gridTable = vertcat(rows{:});
    frameTable = vertcat(frameRows{:});
end


function counts = localFormationMemberCounts(formation)
    switch formation
        case "any-member"
            counts = [1, 1, 1, 1];
        case "vertical-pair"
            counts = [1, 2, 1, 1];
        case "radial-pair"
            counts = [1, 1, 2, 1];
        case "shape-pair"
            counts = [1, 1, 1, 2];
        case "vertical-radial-pairs"
            counts = [1, 2, 2, 1];
        case "all-multimember-pairs"
            counts = [1, 2, 2, 2];
        otherwise
            error( ...
                "evaluateCurbRingFeatureBackgroundCalibration:" + ...
                "UnknownFamilyFormation", ...
                "Unsupported family formation: %s", formation);
    end
end


function accepted = localApplyFeatureRule( ...
        normalizedFeatures, featureRanks, featureFamilies, ...
        familyNames, familyMultipliers, localPercentile, ...
        minimumVotes, minimumSalientVotes, minimumMemberCounts)
    absoluteFamilyActive = false(size(normalizedFeatures, 1), ...
        numel(familyNames));
    salientFamilyActive = false(size(normalizedFeatures, 1), ...
        numel(familyNames));
    for familyIndex = 1:numel(familyNames)
        memberMask = featureFamilies == familyNames(familyIndex);
        absoluteMemberActive = normalizedFeatures(:, memberMask) ...
            >= familyMultipliers(familyIndex);
        absoluteFamilyActive(:, familyIndex) = ...
            sum(absoluteMemberActive, 2) ...
                >= minimumMemberCounts(familyIndex);
        if localPercentile > 0
            salientMemberActive = absoluteMemberActive ...
                & featureRanks(:, memberMask) >= localPercentile;
            salientFamilyActive(:, familyIndex) = ...
                any(salientMemberActive, 2);
        end
    end
    accepted = sum(absoluteFamilyActive, 2) >= minimumVotes;
    if localPercentile > 0
        accepted = accepted ...
            & sum(salientFamilyActive, 2) >= minimumSalientVotes;
    end
end


function accepted = localApplyFamilyRule( ...
        familyScores, familyRanks, familyMultipliers, ...
        localPercentile, minimumVotes, minimumSalientVotes)
    absoluteFamilyActive = familyScores >= familyMultipliers;
    accepted = sum(absoluteFamilyActive, 2) >= minimumVotes;
    if localPercentile > 0
        salientFamilyActive = absoluteFamilyActive ...
            & familyRanks >= localPercentile;
        accepted = accepted ...
            & sum(salientFamilyActive, 2) ...
                >= minimumSalientVotes;
    end
end


function accepted = localApplyRule( ...
        scores, ranks, multipliers, localPercentile, minimumVotes)
    active = scores >= multipliers;
    if localPercentile > 0
        active = active & ranks >= localPercentile;
    end
    accepted = sum(active, 2) >= minimumVotes;
end


function [minimumRecall, medianRecall, frameTable] = ...
        localFrameRecall(frames, accepted, ruleIndex)
    uniqueFrames = unique(frames, "stable");
    frameCount = numel(uniqueFrames);
    frameRows = cell(frameCount, 1);
    recalls = nan(frameCount, 1);
    for frameIndex = 1:frameCount
        mask = frames == uniqueFrames(frameIndex);
        recalls(frameIndex) = localRate(accepted(mask));
        frameRows{frameIndex} = table( ...
            ruleIndex, uniqueFrames(frameIndex), nnz(mask), ...
            nnz(accepted(mask)), recalls(frameIndex), ...
            VariableNames=[ ...
                "ruleIndex", "frameIndex", "positiveCount", ...
                "acceptedCount", "positiveRecall"]);
    end
    minimumRecall = min(recalls);
    medianRecall = median(recalls);
    frameTable = vertcat(frameRows{:});
end


function [recommended, pareto] = localRecommendRules( ...
        grid, minimumRecall, minimumFrameRecall)
    feasible = grid.positiveRecall >= minimumRecall ...
        & grid.minimumFrameRecall >= minimumFrameRecall;
    if ~any(feasible)
        [~, bestIndex] = max( ...
            grid.positiveRecall + 0.25*grid.minimumFrameRecall ...
            - grid.globalBackgroundActivation);
        recommended = grid(bestIndex, :);
    else
        candidates = grid(feasible, :);
        candidates = sortrows( ...
            candidates, ...
            ["globalBackgroundActivation", ...
             "localBackgroundActivation", ...
             "hardNegativeActivation", ...
             "positiveRecall"], ...
            ["ascend", "ascend", "ascend", "descend"]);
        recommended = candidates(1, :);
    end

    dominated = false(height(grid), 1);
    for rowIndex = 1:height(grid)
        noWorse = ...
            grid.positiveRecall >= grid.positiveRecall(rowIndex) ...
            & grid.minimumFrameRecall ...
                >= grid.minimumFrameRecall(rowIndex) ...
            & grid.globalBackgroundActivation ...
                <= grid.globalBackgroundActivation(rowIndex) ...
            & grid.localBackgroundActivation ...
                <= grid.localBackgroundActivation(rowIndex);
        strictlyBetter = ...
            grid.positiveRecall > grid.positiveRecall(rowIndex) ...
            | grid.minimumFrameRecall ...
                > grid.minimumFrameRecall(rowIndex) ...
            | grid.globalBackgroundActivation ...
                < grid.globalBackgroundActivation(rowIndex) ...
            | grid.localBackgroundActivation ...
                < grid.localBackgroundActivation(rowIndex);
        dominated(rowIndex) = any(noWorse & strictlyBetter);
    end
    pareto = sortrows( ...
        grid(~dominated, :), ...
        ["globalBackgroundActivation", "positiveRecall"], ...
        ["ascend", "descend"]);
end


function output = localExtendedFeatureAblation( ...
        positiveFeatures, positiveRanks, positiveFrames, ...
        localFeatures, localRanks, globalFeatures, globalRanks, ...
        hardNegativeFeatures, hardNegativeRanks, ...
        featureNames, featureFamilies, familyNames)
    extendedNames = [ ...
        "huangRadiusRatioDeviation", ...
        "huangHdInRadius", ...
        "sameRingSlopeMagnitude", ...
        "hataDifferentialHeightResponse"];
    legacyMask = ~ismember(featureNames, extendedNames);
    variantNames = [ ...
        "all-16-features", ...
        "legacy-12-only", ...
        "legacy-plus-" + extendedNames, ...
        "all-minus-" + extendedNames];
    variantMasks = cell(numel(variantNames), 1);
    variantMasks{1} = true(size(featureNames));
    variantMasks{2} = legacyMask;
    for extendedIndex = 1:numel(extendedNames)
        variantMasks{2 + extendedIndex} = legacyMask ...
            | featureNames == extendedNames(extendedIndex);
        variantMasks{2 + numel(extendedNames) + extendedIndex} = ...
            featureNames ~= extendedNames(extendedIndex);
    end

    familyMultipliers = 1.25*ones(1, numel(familyNames));
    minimumMemberCounts = ones(1, numel(familyNames));
    rows = cell(numel(variantNames), 1);
    for variantIndex = 1:numel(variantNames)
        mask = variantMasks{variantIndex};
        positiveAccepted = localApplyFeatureRule( ...
            positiveFeatures(:, mask), positiveRanks(:, mask), ...
            featureFamilies(mask), familyNames, familyMultipliers, ...
            0.60, 3, 2, minimumMemberCounts);
        localAccepted = localApplyFeatureRule( ...
            localFeatures(:, mask), localRanks(:, mask), ...
            featureFamilies(mask), familyNames, familyMultipliers, ...
            0.60, 3, 2, minimumMemberCounts);
        globalAccepted = localApplyFeatureRule( ...
            globalFeatures(:, mask), globalRanks(:, mask), ...
            featureFamilies(mask), familyNames, familyMultipliers, ...
            0.60, 3, 2, minimumMemberCounts);
        hardNegativeAccepted = localApplyFeatureRule( ...
            hardNegativeFeatures(:, mask), ...
            hardNegativeRanks(:, mask), ...
            featureFamilies(mask), familyNames, familyMultipliers, ...
            0.60, 3, 2, minimumMemberCounts);
        [minimumFrameRecall, medianFrameRecall] = localFrameRecall( ...
            positiveFrames, positiveAccepted, variantIndex);
        rows{variantIndex} = table( ...
            variantNames(variantIndex), nnz(mask), ...
            nnz(positiveAccepted), localRate(positiveAccepted), ...
            minimumFrameRecall, medianFrameRecall, ...
            nnz(localAccepted), localRate(localAccepted), ...
            nnz(globalAccepted), localRate(globalAccepted), ...
