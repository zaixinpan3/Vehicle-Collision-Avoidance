function [scores, available] = localFamilyScores( ...
        values, valid, featureFamilies, thresholds, familyNames)
    gridSize = size(values{1});
    scores = nan([gridSize, numel(familyNames)]);
    available = false([gridSize, numel(familyNames)]);
    for familyIndex = 1:numel(familyNames)
        familyScore = nan(gridSize);
        familyAvailable = false(gridSize);
        memberIndices = find( ...
            featureFamilies == familyNames(familyIndex));
        for memberIndex = memberIndices
            memberValid = valid{memberIndex} ...
                & isfinite(values{memberIndex});
            normalizedValue = double(values{memberIndex}) ...
                / thresholds(memberIndex);
            firstEvidence = memberValid & ~familyAvailable;
            familyScore(firstEvidence) = ...
                normalizedValue(firstEvidence);
            sharedEvidence = memberValid & familyAvailable;
            familyScore(sharedEvidence) = max( ...
                familyScore(sharedEvidence), ...
                normalizedValue(sharedEvidence));
            familyAvailable = familyAvailable | memberValid;
        end
        familyScore(~familyAvailable) = NaN;
        scores(:, :, familyIndex) = familyScore;
        available(:, :, familyIndex) = familyAvailable;
    end
end


function [normalized, available] = localNormalizedFeatures( ...
        values, valid, thresholds)
    gridSize = size(values{1});
    featureCount = numel(values);
    normalized = nan([gridSize, featureCount]);
    available = false([gridSize, featureCount]);
    for featureIndex = 1:featureCount
        featureAvailable = valid{featureIndex} ...
            & isfinite(values{featureIndex});
        featureNormalized = double(values{featureIndex}) ...
            / thresholds(featureIndex);
        featureNormalized(~featureAvailable) = NaN;
        normalized(:, :, featureIndex) = featureNormalized;
        available(:, :, featureIndex) = featureAvailable;
    end
end


function [percentile, neighborCount] = localCircularPercentile( ...
        values, valid, halfWidthBins, exclusionBins, minimumCount)
    lowerCount = zeros(size(values), "uint16");
    equalCount = zeros(size(values), "uint16");
    neighborCount = zeros(size(values), "uint16");
    offsets = [ ...
        -halfWidthBins:-exclusionBins, ...
        exclusionBins:halfWidthBins];
    offsets(offsets == 0) = [];
    for offset = offsets
        neighborValue = circshift(values, [0, offset]);
        neighborValid = circshift(valid, [0, offset]) ...
            & isfinite(neighborValue);
        neighborCount = neighborCount + uint16(neighborValid);
        lowerCount = lowerCount + uint16( ...
            neighborValid & neighborValue < values);
        equalCount = equalCount + uint16( ...
            neighborValid & neighborValue == values);
    end
    percentile = ( ...
        single(lowerCount) + 0.5*single(equalCount)) ...
        ./ max(single(neighborCount), 1.0);
    percentile(~valid | neighborCount < minimumCount) = NaN;
end


function mask = localPositiveExclusionMask( ...
        indices, gridSize, exclusionBins)
    mask = false(gridSize);
    if isempty(indices)
        return;
    end
    [ringIndices, columnIndices] = ind2sub(gridSize, indices);
    offsets = -exclusionBins:exclusionBins;
    for index = 1:numel(indices)
        columns = mod( ...
            columnIndices(index) - 1 + offsets, gridSize(2)) + 1;
        mask(ringIndices(index), columns) = true;
    end
end


function mask = localPositiveNeighborhoodMask( ...
        indices, gridSize, exclusionBins, halfWidthBins)
    mask = false(gridSize);
    if isempty(indices)
        return;
    end
    [ringIndices, columnIndices] = ind2sub(gridSize, indices);
    offsets = [ ...
        -halfWidthBins:-exclusionBins, ...
        exclusionBins:halfWidthBins];
    offsets(offsets == 0) = [];
    for index = 1:numel(indices)
        columns = mod( ...
            columnIndices(index) - 1 + offsets, gridSize(2)) + 1;
        mask(ringIndices(index), columns) = true;
    end
end


