function summary = evaluateCurbRingFeatureBackgroundCalibration( ...
        datasetFolder, options)
%EVALUATECURBRINGFEATUREBACKGROUNDCALIBRATION Calibrate ring evidence.
%   SUMMARY = EVALUATECURBRINGFEATUREBACKGROUNDCALIBRATION() evaluates the
%   sixteen ring-local curb features and their four physical feature
%   families on the nine user-reviewed development frames.
%
%   The evaluator reports three distinct comparison populations:
%       positive         exact user-reviewed curb points
%       local-background valid cells on the same ring, 1.08 to 11.88
%                        degrees away from a positive
%       global-background all valid, non-annotated cells outside a
%                         1.08-degree same-ring exclusion around positives
%
%   A fourth, explicitly labelled hard-negative population is retained
%   separately. Global-background activation is an upper bound rather than
%   a false-positive rate because most global cells have not been manually
%   labelled and can contain real curb or other geometric discontinuities.
%
%   Candidate rules are side agnostic and frame agnostic. Each feature is
%   normalized by an explicit research baseline that is independent of the
%   production fusion thresholds. The twelve earlier baselines are the
%   pre-production development values. The four extended-feature baselines
%   equal their hard-negative 95th percentiles divided by 1.25, so the
%   common-1.25 rule evaluates those hard-negative percentiles directly.
%   Each family score is the maximum normalized member score, and optional
%   local saliency requires the family score to be above a same-ring local
%   percentile. The script does not modify the production detector or
%   feature-fusion implementation.

    arguments
        datasetFolder (1, 1) string = ""
        options.OutputDirectory (1, 1) string = ""
        options.FrameIndices (1, :) double ...
            {mustBeInteger, mustBeNonnegative} = []
        options.MatchToleranceM (1, 1) double ...
            {mustBePositive, mustBeFinite} = 1.0e-4
        options.LocalHalfWidthBins (1, 1) double ...
            {mustBeInteger, mustBePositive} = 33
        options.LocalExclusionBins (1, 1) double ...
            {mustBeInteger, mustBeNonnegative} = 3
        options.MinimumLocalCount (1, 1) double ...
            {mustBeInteger, mustBePositive} = 12
        options.CommonFamilyMultipliers (1, :) double ...
            {mustBePositive, mustBeFinite} = ...
                [1.0, 1.25, 1.5, 2.0, 2.5, 3.0, 4.0]
        options.LocalPercentiles (1, :) double ...
            {mustBeGreaterThanOrEqual(options.LocalPercentiles, 0), ...
             mustBeLessThan(options.LocalPercentiles, 1)} = ...
                [0.0, 0.50, 0.60, 0.70, 0.75, 0.80, ...
                 0.85, 0.90, 0.95]
        options.MinimumFamilyVotes (1, :) double ...
            {mustBeInteger, mustBeGreaterThanOrEqual( ...
                options.MinimumFamilyVotes, 1), ...
             mustBeLessThanOrEqual( ...
                options.MinimumFamilyVotes, 4)} = [2, 3]
        options.MinimumSalientFamilyVotes (1, :) double ...
            {mustBeInteger, mustBeGreaterThanOrEqual( ...
                options.MinimumSalientFamilyVotes, 1), ...
             mustBeLessThanOrEqual( ...
                options.MinimumSalientFamilyVotes, 4)} = [1, 2]
        options.MinimumPositiveRecall (1, 1) double ...
            {mustBeGreaterThanOrEqual( ...
                options.MinimumPositiveRecall, 0), ...
             mustBeLessThanOrEqual( ...
                options.MinimumPositiveRecall, 1)} = 0.80
        options.MinimumFrameRecall (1, 1) double ...
            {mustBeGreaterThanOrEqual( ...
                options.MinimumFrameRecall, 0), ...
             mustBeLessThanOrEqual( ...
                options.MinimumFrameRecall, 1)} = 0.60
    end

    if options.LocalExclusionBins >= options.LocalHalfWidthBins
        error( ...
            "evaluateCurbRingFeatureBackgroundCalibration:" + ...
            "InvalidLocalWindow", ...
            "LocalExclusionBins must be smaller than " + ...
            "LocalHalfWidthBins.");
    end

    repositoryRoot = fileparts(fileparts(fileparts( ...
        mfilename("fullpath"))));
    if strlength(datasetFolder) == 0
        datasetFolder = fullfile( ...
            repositoryRoot, "simulation", "data", ...
            "carla_outer_loop_lap_10hz_20260802_epic_no_rt_auto");
    end
    if strlength(options.OutputDirectory) == 0
        options.OutputDirectory = fullfile( ...
            repositoryRoot, "simulation_output", ...
            "curb_ring_feature_extended_background_calibration");
    end
    if ~isfolder(datasetFolder)
        error( ...
            "evaluateCurbRingFeatureBackgroundCalibration:" + ...
            "MissingDataset", ...
            "Dataset folder does not exist: %s", datasetFolder);
    end
    if ~isfolder(options.OutputDirectory)
        mkdir(options.OutputDirectory);
    end

    catalog = curbRingFeatureDevelopmentLabels();
    anchors = catalog.anchors;
    if ~isempty(options.FrameIndices)
        anchors = anchors(ismember( ...
            [anchors.frameIndex], options.FrameIndices));
    end
    if isempty(anchors)
        error( ...
            "evaluateCurbRingFeatureBackgroundCalibration:" + ...
            "NoFrames", ...
            "No labelled development frame matches FrameIndices.");
    end

    featureFolder = fullfile( ...
        repositoryRoot, "perception", "curbDetectionExperiment");
    originalPath = path();
    pathCleanup = onCleanup(@() path(originalPath));
    addpath(featureFolder);

    frameCount = numel(anchors);
    featureCount = 16;
    familyCount = 4;
    positiveFeatureCells = cell(frameCount, featureCount);
    localFeatureCells = cell(frameCount, featureCount);
    globalFeatureCells = cell(frameCount, featureCount);
    hardNegativeFeatureCells = cell(frameCount, featureCount);
    positiveNormalizedCells = cell(frameCount, 1);
    positiveFeatureRankCells = cell(frameCount, 1);
    localNormalizedCells = cell(frameCount, 1);
    localFeatureRankCells = cell(frameCount, 1);
    globalNormalizedCells = cell(frameCount, 1);
    globalFeatureRankCells = cell(frameCount, 1);
    hardNegativeNormalizedCells = cell(frameCount, 1);
    hardNegativeFeatureRankCells = cell(frameCount, 1);
    positiveScoreCells = cell(frameCount, 1);
    positiveFamilyRankCells = cell(frameCount, 1);
    localScoreCells = cell(frameCount, 1);
    localFamilyRankCells = cell(frameCount, 1);
    globalScoreCells = cell(frameCount, 1);
    globalFamilyRankCells = cell(frameCount, 1);
    hardNegativeScoreCells = cell(frameCount, 1);
    hardNegativeFamilyRankCells = cell(frameCount, 1);
    positiveFrameCells = cell(frameCount, 1);
    frameSummaryRows = cell(frameCount, 1);
    featureNames = strings(1, featureCount);
    featureFamilies = strings(1, featureCount);
    defaultThresholds = nan(1, featureCount);
    familyNames = ["compression", "vertical", "radial", "shape"];

    for anchorIndex = 1:frameCount
        anchor = anchors(anchorIndex);
        framePath = fullfile( ...
            datasetFolder, "lidar", ...
            sprintf("%06d.npy", anchor.frameIndex));
        rawPoints = localLoadNpy(framePath);
        [organizedFrame, ~, rawToOrganized] = ...
            organizeLidarSweepGrid(rawPoints);
        positiveIndices = localMatchIndices( ...
            anchor.positiveCoordinatesM, rawPoints, rawToOrganized, ...
            options.MatchToleranceM, anchor.frameIndex, "positive");
        hardNegativeIndices = localMatchIndices( ...
            anchor.hardNegativeCoordinatesM, rawPoints, rawToOrganized, ...
            options.MatchToleranceM, anchor.frameIndex, "hard-negative");

        [features, validity] = computeLidarRingCurbFeatures( ...
            organizedFrame);
        [featureValues, featureValid, names, families, thresholds] = ...
            localFeatureArrays(features, validity);
        if anchorIndex == 1
            featureNames = names;
            featureFamilies = families;
            defaultThresholds = thresholds;
        elseif ~isequal(featureNames, names) ...
                || ~isequal(featureFamilies, families) ...
                || any(defaultThresholds ~= thresholds)
            error( ...
                "evaluateCurbRingFeatureBackgroundCalibration:" + ...
                "FeatureSchemaChanged", ...
                "Feature schema or default thresholds changed by frame.");
        end

        [familyScores, familyAvailable] = localFamilyScores( ...
            featureValues, featureValid, featureFamilies, ...
            defaultThresholds, familyNames);
        [normalizedFeatures, normalizedAvailable] = ...
            localNormalizedFeatures( ...
                featureValues, featureValid, defaultThresholds);
        normalizedFeatureRanks = nan( ...
            size(normalizedFeatures), "single");
        for featureIndex = 1:featureCount
            normalizedFeatureRanks(:, :, featureIndex) = ...
                localCircularPercentile( ...
                    normalizedFeatures(:, :, featureIndex), ...
                    normalizedAvailable(:, :, featureIndex), ...
                    options.LocalHalfWidthBins, ...
                    options.LocalExclusionBins, ...
                    options.MinimumLocalCount);
        end
        familyRanks = nan(size(familyScores), "single");
        for familyIndex = 1:familyCount
            familyRanks(:, :, familyIndex) = ...
                localCircularPercentile( ...
                    familyScores(:, :, familyIndex), ...
                    familyAvailable(:, :, familyIndex), ...
                    options.LocalHalfWidthBins, ...
                    options.LocalExclusionBins, ...
                    options.MinimumLocalCount);
        end
        baseValid = validity.base;
        positiveExclusion = localPositiveExclusionMask( ...
            positiveIndices, size(baseValid), ...
            options.LocalExclusionBins);
        localBackground = localPositiveNeighborhoodMask( ...
            positiveIndices, size(baseValid), ...
            options.LocalExclusionBins, ...
            options.LocalHalfWidthBins) & baseValid;
        localBackground(positiveExclusion) = false;
        globalBackground = baseValid & ~positiveExclusion;

        for featureIndex = 1:featureCount
            values = featureValues{featureIndex};
            valid = featureValid{featureIndex} & isfinite(values);
            positiveFeatureCells{anchorIndex, featureIndex} = ...
                localSelectValues(values, valid, positiveIndices);
            localFeatureCells{anchorIndex, featureIndex} = ...
                double(values(localBackground & valid));
            globalFeatureCells{anchorIndex, featureIndex} = ...
                double(values(globalBackground & valid));
            hardNegativeFeatureCells{anchorIndex, featureIndex} = ...
                localSelectValues(values, valid, hardNegativeIndices);
        end

        positiveScoreCells{anchorIndex} = ...
            localSelectRows(familyScores, positiveIndices);
        positiveFamilyRankCells{anchorIndex} = ...
            localSelectRows(familyRanks, positiveIndices);
        localScoreCells{anchorIndex} = ...
            localSelectRows(familyScores, find(localBackground));
        localFamilyRankCells{anchorIndex} = ...
            localSelectRows(familyRanks, find(localBackground));
        globalScoreCells{anchorIndex} = ...
            localSelectRows(familyScores, find(globalBackground));
        globalFamilyRankCells{anchorIndex} = ...
            localSelectRows(familyRanks, find(globalBackground));
        hardNegativeScoreCells{anchorIndex} = ...
            localSelectRows(familyScores, hardNegativeIndices);
        hardNegativeFamilyRankCells{anchorIndex} = ...
            localSelectRows(familyRanks, hardNegativeIndices);
        positiveNormalizedCells{anchorIndex} = ...
            localSelectRows(normalizedFeatures, positiveIndices);
        positiveFeatureRankCells{anchorIndex} = ...
            localSelectRows(normalizedFeatureRanks, positiveIndices);
        localNormalizedCells{anchorIndex} = ...
            localSelectRows(normalizedFeatures, find(localBackground));
        localFeatureRankCells{anchorIndex} = ...
            localSelectRows( ...
                normalizedFeatureRanks, find(localBackground));
        globalNormalizedCells{anchorIndex} = ...
            localSelectRows(normalizedFeatures, find(globalBackground));
        globalFeatureRankCells{anchorIndex} = ...
            localSelectRows( ...
                normalizedFeatureRanks, find(globalBackground));
        hardNegativeNormalizedCells{anchorIndex} = ...
            localSelectRows(normalizedFeatures, hardNegativeIndices);
        hardNegativeFeatureRankCells{anchorIndex} = ...
            localSelectRows( ...
                normalizedFeatureRanks, hardNegativeIndices);
        positiveFrameCells{anchorIndex} = repmat( ...
            anchor.frameIndex, numel(positiveIndices), 1);

        defaultAccepted = localApplyRule( ...
            localSelectRows(familyScores, find(baseValid)), ...
            localSelectRows(familyScores, find(baseValid)), ...
            ones(1, familyCount), 0.0, 2);
        frameSummaryRows{anchorIndex} = table( ...
            anchor.frameIndex, nnz(baseValid), ...
            numel(positiveIndices), numel(hardNegativeIndices), ...
            nnz(localBackground), nnz(globalBackground), ...
            nnz(defaultAccepted), mean(defaultAccepted), ...
            VariableNames=[ ...
                "frameIndex", "baseValidCount", "positiveCount", ...
                "hardNegativeCount", "localBackgroundCount", ...
                "globalBackgroundCount", ...
                "defaultAcceptedCellCount", ...
                "defaultAcceptedCellRate"]);
    end
    clear pathCleanup;

    positiveFeatureValues = localConcatenateFeatureCells( ...
        positiveFeatureCells);
    localFeatureValues = localConcatenateFeatureCells( ...
        localFeatureCells);
    globalFeatureValues = localConcatenateFeatureCells( ...
        globalFeatureCells);
    hardNegativeFeatureValues = localConcatenateFeatureCells( ...
        hardNegativeFeatureCells);
    positiveScores = vertcat(positiveScoreCells{:});
    positiveFamilyRanks = vertcat(positiveFamilyRankCells{:});
    localScores = vertcat(localScoreCells{:});
    localFamilyRanks = vertcat(localFamilyRankCells{:});
    globalScores = vertcat(globalScoreCells{:});
    globalFamilyRanks = vertcat(globalFamilyRankCells{:});
    hardNegativeScores = vertcat(hardNegativeScoreCells{:});
    hardNegativeFamilyRanks = ...
        vertcat(hardNegativeFamilyRankCells{:});
    positiveNormalized = vertcat(positiveNormalizedCells{:});
    positiveFeatureRanks = vertcat(positiveFeatureRankCells{:});
    localNormalized = vertcat(localNormalizedCells{:});
    localFeatureRanks = vertcat(localFeatureRankCells{:});
    globalNormalized = vertcat(globalNormalizedCells{:});
    globalFeatureRanks = vertcat(globalFeatureRankCells{:});
    hardNegativeNormalized = ...
        vertcat(hardNegativeNormalizedCells{:});
    hardNegativeFeatureRanks = ...
        vertcat(hardNegativeFeatureRankCells{:});
    positiveFrames = vertcat(positiveFrameCells{:});
    frameSummaryTable = vertcat(frameSummaryRows{:});

    featureMetricTable = localFeatureMetrics( ...
        featureNames, featureFamilies, defaultThresholds, ...
        positiveFeatureValues, localFeatureValues, ...
        globalFeatureValues, hardNegativeFeatureValues);
    familyMetricTable = localFamilyMetrics( ...
        familyNames, positiveScores, localScores, globalScores, ...
        hardNegativeScores);

    backgroundFamilyQuantiles = localFamilyQuantiles( ...
        globalScores, [0.90, 0.95, 0.975, 0.99]);
    [ruleGridTable, frameRuleTable] = localEvaluateRuleGrid( ...
        positiveNormalized, positiveFeatureRanks, positiveFrames, ...
        localNormalized, localFeatureRanks, ...
        globalNormalized, globalFeatureRanks, ...
        hardNegativeNormalized, hardNegativeFeatureRanks, ...
        positiveScores, positiveFamilyRanks, ...
        localScores, localFamilyRanks, ...
        globalScores, globalFamilyRanks, ...
        hardNegativeScores, hardNegativeFamilyRanks, ...
        featureFamilies, familyNames, ...
        options.CommonFamilyMultipliers, ...
        backgroundFamilyQuantiles, ...
        options.LocalPercentiles, options.MinimumFamilyVotes, ...
        options.MinimumSalientFamilyVotes);
    [recommendedRuleTable, paretoTable] = localRecommendRules( ...
        ruleGridTable, options.MinimumPositiveRecall, ...
        options.MinimumFrameRecall);
    extendedFeatureAblationTable = localExtendedFeatureAblation( ...
        positiveNormalized, positiveFeatureRanks, positiveFrames, ...
        localNormalized, localFeatureRanks, ...
        globalNormalized, globalFeatureRanks, ...
        hardNegativeNormalized, hardNegativeFeatureRanks, ...
        featureNames, featureFamilies, familyNames);

    outputFiles = struct( ...
        "featureMetricsCsv", fullfile( ...
            options.OutputDirectory, ...
            "feature_background_metrics.csv"), ...
        "familyMetricsCsv", fullfile( ...
            options.OutputDirectory, ...
            "family_background_metrics.csv"), ...
        "frameSummaryCsv", fullfile( ...
            options.OutputDirectory, ...
            "frame_background_activation.csv"), ...
        "ruleGridCsv", fullfile( ...
            options.OutputDirectory, ...
            "fusion_rule_grid.csv"), ...
        "frameRuleMetricsCsv", fullfile( ...
            options.OutputDirectory, ...
            "fusion_rule_frame_metrics.csv"), ...
        "recommendedRuleCsv", fullfile( ...
            options.OutputDirectory, ...
            "recommended_fusion_rule.csv"), ...
        "paretoRulesCsv", fullfile( ...
            options.OutputDirectory, ...
            "pareto_fusion_rules.csv"), ...
        "extendedFeatureAblationCsv", fullfile( ...
            options.OutputDirectory, ...
            "extended_feature_ablation.csv"), ...
        "summaryMat", fullfile( ...
            options.OutputDirectory, ...
            "background_calibration_summary.mat"));
    writetable(featureMetricTable, outputFiles.featureMetricsCsv);
    writetable(familyMetricTable, outputFiles.familyMetricsCsv);
    writetable(frameSummaryTable, outputFiles.frameSummaryCsv);
    writetable(ruleGridTable, outputFiles.ruleGridCsv);
    writetable(frameRuleTable, outputFiles.frameRuleMetricsCsv);
    writetable(recommendedRuleTable, outputFiles.recommendedRuleCsv);
    writetable(paretoTable, outputFiles.paretoRulesCsv);
    writetable( ...
        extendedFeatureAblationTable, ...
        outputFiles.extendedFeatureAblationCsv);

    summary = struct( ...
        "status", "completed-development-background-calibration", ...
        "datasetFolder", datasetFolder, ...
        "outputDirectory", options.OutputDirectory, ...
        "frameIndices", [anchors.frameIndex], ...
        "positiveCount", size(positiveScores, 1), ...
        "hardNegativeCount", size(hardNegativeScores, 1), ...
        "localBackgroundCount", size(localScores, 1), ...
        "globalBackgroundCount", size(globalScores, 1), ...
        "azimuthBinDegrees", 0.36, ...
        "localHalfWidthDegrees", ...
            options.LocalHalfWidthBins*0.36, ...
        "localExclusionDegrees", ...
            options.LocalExclusionBins*0.36, ...
        "minimumLocalCount", options.MinimumLocalCount, ...
        "minimumPositiveRecall", options.MinimumPositiveRecall, ...
        "minimumFrameRecall", options.MinimumFrameRecall, ...
        "featureCount", featureCount, ...
        "featureNames", featureNames, ...
        "researchBaselineThresholds", defaultThresholds, ...
        "thresholdBaselineSource", ...
            "The first twelve values are fixed pre-production " + ...
            "development baselines; the four extended values are " + ...
            "hard-negative q95 divided by 1.25.", ...
        "ablationRule", ...
            "common-1.25, member-feature saliency 0.60, " + ...
            "minimum 3 absolute families and 2 salient families", ...
        "recommendedRule", recommendedRuleTable, ...
        "globalBackgroundCaveat", ...
            "Unannotated global cells can contain true curb or other " + ...
            "legitimate discontinuities; activation is not an FPR.", ...
        "sideSpecificLogicUsed", false, ...
        "frameSpecificLogicUsed", false, ...
        "outputFiles", outputFiles);
    save( ...
        outputFiles.summaryMat, "summary", "featureMetricTable", ...
        "familyMetricTable", "frameSummaryTable", "ruleGridTable", ...
        "frameRuleTable", "recommendedRuleTable", "paretoTable", ...
        "extendedFeatureAblationTable", ...
        "backgroundFamilyQuantiles");
end


function rawPoints = localLoadNpy(framePath)
    if ~isfile(framePath)
        error( ...
            "evaluateCurbRingFeatureBackgroundCalibration:" + ...
            "MissingFrame", ...
            "LiDAR frame does not exist: %s", framePath);
    end
    try
        rawPoints = double(py.numpy.load(framePath));
    catch exception
        error( ...
            "evaluateCurbRingFeatureBackgroundCalibration:" + ...
            "NpyLoadFailed", ...
            "Unable to load %s through NumPy: %s", ...
            framePath, exception.message);
    end
    if size(rawPoints, 2) < 3 ...
            || any(~isfinite(rawPoints(:, 1:3)), "all")
        error( ...
            "evaluateCurbRingFeatureBackgroundCalibration:" + ...
            "InvalidFrame", ...
            "LiDAR frame must contain finite XYZ columns: %s", ...
            framePath);
    end
end


function organizedIndices = localMatchIndices( ...
        coordinates, rawPoints, rawToOrganized, toleranceM, ...
        frameIndex, labelName)
    organizedIndices = zeros(size(coordinates, 1), 1);
    for coordinateIndex = 1:size(coordinates, 1)
        displacement = rawPoints(:, 1:3) ...
            - coordinates(coordinateIndex, :);
        [minimumSquaredDistance, rawIndex] = min( ...
            sum(displacement.^2, 2));
        distanceM = sqrt(minimumSquaredDistance);
        if distanceM > toleranceM
            error( ...
                "evaluateCurbRingFeatureBackgroundCalibration:" + ...
                "LabelOutsideTolerance", ...
                "Frame %d %s coordinate %d is %.6g m from its " + ...
                "nearest point.", ...
                frameIndex, labelName, coordinateIndex, distanceM);
        end
        if rawToOrganized(rawIndex) == 0
            error( ...
                "evaluateCurbRingFeatureBackgroundCalibration:" + ...
                "LabelNotOrganized", ...
                "Frame %d %s coordinate %d was not retained in the " + ...
                "organized grid.", ...
                frameIndex, labelName, coordinateIndex);
        end
        organizedIndices(coordinateIndex) = ...
            rawToOrganized(rawIndex);
    end
    organizedIndices = unique(organizedIndices, "stable");
end


