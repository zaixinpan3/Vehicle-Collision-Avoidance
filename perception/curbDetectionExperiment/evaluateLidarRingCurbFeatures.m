function metricTable = localEvaluateSplits( ...
        sampleTable, splitMode, explicitTestFrames)
    metricTable = localEmptyMetricTable();
    if isempty(sampleTable)
        return;
    end
    baseVariables = [ ...
        "frameIndex", "label", ...
        "labelX", "labelY", "labelZ", ...
        "matchedX", "matchedY", "matchedZ", ...
        "rawPointIndexZeroBased", ...
        "ringIndex", "azimuthBinIndex", ...
        "organizedLinearIndex", "matchDistanceM"];
    featureNames = setdiff( ...
        string(sampleTable.Properties.VariableNames), ...
        baseVariables, "stable");
    if isempty(featureNames)
        return;
    end

    frameIndices = unique(sampleTable.frameIndex).';
    splits = localBuildSplits( ...
        frameIndices, splitMode, explicitTestFrames);
    rowCount = numel(splits)*numel(featureNames);
    rows = repmat(localMetricRow(), rowCount, 1);
    rowIndex = 0;
    for splitIndex = 1:numel(splits)
        split = splits(splitIndex);
        trainingRows = ismember( ...
            sampleTable.frameIndex, split.trainingFrames);
        testRows = ismember( ...
            sampleTable.frameIndex, split.testFrames);
        for featureIndex = 1:numel(featureNames)
            rowIndex = rowIndex + 1;
            featureName = featureNames(featureIndex);
            trainingValues = sampleTable.(featureName)(trainingRows);
            trainingLabels = sampleTable.label(trainingRows);
            testValues = sampleTable.(featureName)(testRows);
            testLabels = sampleTable.label(testRows);
            [trainingAuc, trainingDelta, trainingPositiveCount, ...
                trainingNegativeCount] = localSeparation( ...
                    trainingValues, trainingLabels);
            [testAuc, testDelta, testPositiveCount, ...
                testNegativeCount] = localSeparation( ...
                    testValues, testLabels);

            direction = 1;
            if isfinite(trainingAuc) && trainingAuc < 0.5
                direction = -1;
            end
            rows(rowIndex) = struct( ...
                "foldIndex", splitIndex, ...
                "splitMode", splitMode, ...
                "featureName", featureName, ...
                "trainingFrames", ...
                    localFrameList(split.trainingFrames), ...
                "testFrames", localFrameList(split.testFrames), ...
                "positiveHighDirection", direction, ...
                "trainingPositiveCount", trainingPositiveCount, ...
                "trainingHardNegativeCount", trainingNegativeCount, ...
                "testPositiveCount", testPositiveCount, ...
                "testHardNegativeCount", testNegativeCount, ...
                "trainingAucRaw", trainingAuc, ...
                "trainingAucOriented", ...
                    localOrientAuc(trainingAuc, direction), ...
                "testAucRaw", testAuc, ...
                "testAucOriented", ...
                    localOrientAuc(testAuc, direction), ...
                "trainingCliffDeltaRaw", trainingDelta, ...
                "trainingCliffDeltaOriented", ...
                    direction*trainingDelta, ...
                "testCliffDeltaRaw", testDelta, ...
                "testCliffDeltaOriented", direction*testDelta);
        end
    end
    metricTable = struct2table(rows);
end


function metricTable = localPooledFeatureMetrics(sampleTable)
    metricTable = localEmptyPooledMetricTable();
    if isempty(sampleTable)
        return;
    end
    baseVariables = [ ...
        "frameIndex", "label", ...
        "labelX", "labelY", "labelZ", ...
        "matchedX", "matchedY", "matchedZ", ...
        "rawPointIndexZeroBased", ...
        "ringIndex", "azimuthBinIndex", ...
        "organizedLinearIndex", "matchDistanceM"];
    featureNames = setdiff( ...
        string(sampleTable.Properties.VariableNames), ...
        baseVariables, "stable");
    for featureName = featureNames
        positiveValues = double(sampleTable.(featureName)( ...
            sampleTable.label == "positive"));
        hardNegativeValues = double(sampleTable.(featureName)( ...
            sampleTable.label == "hard-negative"));
        positiveValues = positiveValues(isfinite(positiveValues));
        hardNegativeValues = ...
            hardNegativeValues(isfinite(hardNegativeValues));
        if isempty(positiveValues) || isempty(hardNegativeValues)
            continue;
        end
        rawAuc = localTieAwareAuc( ...
            positiveValues, hardNegativeValues);
        positiveHighDirection = 1;
        if rawAuc < 0.5
            positiveHighDirection = -1;
        end
        orientedPositive = ...
            positiveHighDirection * positiveValues;
        orientedHardNegative = ...
            positiveHighDirection * hardNegativeValues;
        hardNegativeTailThreshold = quantile( ...
            orientedHardNegative, 0.95);
        positiveTailActivation = mean( ...
            orientedPositive >= hardNegativeTailThreshold);
        hardNegativeTailActivation = mean( ...
            orientedHardNegative >= hardNegativeTailThreshold);
        orientedAuc = localOrientAuc( ...
            rawAuc, positiveHighDirection);
        newRow = table( ...
            featureName, positiveHighDirection, ...
            numel(positiveValues), numel(hardNegativeValues), ...
            rawAuc, orientedAuc, 2.0 * orientedAuc - 1.0, ...
            median(positiveValues), median(hardNegativeValues), ...
            hardNegativeTailThreshold, ...
            positiveTailActivation, ...
            hardNegativeTailActivation, ...
            VariableNames=metricTable.Properties.VariableNames);
        metricTable = [metricTable; newRow]; %#ok<AGROW>
    end
    if ~isempty(metricTable)
        metricTable = sortrows( ...
            metricTable, "pooledAucOriented", "descend");
    end
end


function splits = localBuildSplits( ...
        frameIndices, splitMode, explicitTestFrames)
    if splitMode == "leave-one-frame-out"
        splitCount = numel(frameIndices);
        splits = repmat(struct( ...
            "trainingFrames", [], "testFrames", []), ...
            splitCount, 1);
        for splitIndex = 1:splitCount
            splits(splitIndex).testFrames = frameIndices(splitIndex);
            splits(splitIndex).trainingFrames = ...
                frameIndices(frameIndices ~= frameIndices(splitIndex));
        end
    else
        if isempty(explicitTestFrames)
            error( ...
                "evaluateLidarRingCurbFeatures:MissingTestFrames", ...
                "TestFrameIndices is required for SplitMode=""explicit"".");
        end
        testFrames = intersect( ...
            frameIndices, explicitTestFrames, "stable");
        if isempty(testFrames)
            error( ...
                "evaluateLidarRingCurbFeatures:NoTestLabels", ...
                "No labeled frame belongs to TestFrameIndices.");
        end
        splits = struct( ...
            "trainingFrames", ...
                setdiff(frameIndices, testFrames, "stable"), ...
            "testFrames", testFrames);
    end
end


function [auc, cliffDelta, positiveCount, negativeCount] = ...
        localSeparation(values, labels)
    finiteRows = isfinite(values);
    positiveValues = values( ...
        finiteRows & labels == "positive");
    negativeValues = values( ...
        finiteRows & labels == "hard-negative");
    positiveCount = numel(positiveValues);
    negativeCount = numel(negativeValues);
    if positiveCount == 0 || negativeCount == 0
        auc = NaN;
        cliffDelta = NaN;
        return;
    end
    auc = localTieAwareAuc(positiveValues, negativeValues);
    cliffDelta = 2*auc - 1;
end


function auc = localTieAwareAuc(positiveValues, negativeValues)
    combinedValues = [positiveValues(:); negativeValues(:)];
    positiveCount = numel(positiveValues);
    negativeCount = numel(negativeValues);
    isPositive = [ ...
        true(positiveCount, 1); false(negativeCount, 1)];
    [sortedValues, order] = sort(combinedValues);
    sortedPositive = isPositive(order);
    ranks = zeros(size(sortedValues));
    groupStart = 1;
    while groupStart <= numel(sortedValues)
        groupEnd = groupStart;
        while groupEnd < numel(sortedValues) ...
                && sortedValues(groupEnd + 1) ...
                == sortedValues(groupStart)
            groupEnd = groupEnd + 1;
        end
        ranks(groupStart:groupEnd) = ...
            0.5*(groupStart + groupEnd);
        groupStart = groupEnd + 1;
    end
    positiveRankSum = sum(ranks(sortedPositive));
    auc = (positiveRankSum ...
        - positiveCount*(positiveCount + 1)/2) ...
        / (positiveCount*negativeCount);
end


function orientedAuc = localOrientAuc(rawAuc, direction)
    if ~isfinite(rawAuc)
        orientedAuc = NaN;
    elseif direction > 0
        orientedAuc = rawAuc;
    else
        orientedAuc = 1 - rawAuc;
    end
end


