function value = localLogicalConfigValue(cfg, fieldName, defaultValue)
%LOCALLOGICALCONFIGVALUE Return a validated logical configuration value.
    value = logical(defaultValue);
    if ~isstruct(cfg) || ~isfield(cfg, fieldName)
        return;
    end
    candidate = cfg.(fieldName);
    validLogical = islogical(candidate) && isscalar(candidate);
    validNumeric = isnumeric(candidate) && isreal(candidate) ...
        && isscalar(candidate) && isfinite(candidate) ...
        && (candidate == 0 || candidate == 1);
    if ~validLogical && ~validNumeric
        error( ...
            "groundPointsProcessing:InvalidLogicalConfig", ...
            "%s must be a logical scalar.", fieldName);
    end
    value = logical(candidate);
end

function value = localOptionalConfigValue(cfg, fieldName)
%LOCALOPTIONALCONFIGVALUE Return a finite scalar or NaN when unspecified.
    value = NaN;
    if ~isstruct(cfg) || ~isfield(cfg, fieldName)
        return;
    end

    candidateValue = double(cfg.(fieldName));
    if isscalar(candidateValue) && isfinite(candidateValue)
        value = candidateValue;
    end
end

function value = localConfigValue(cfg, fieldNames, defaultValue)
%LOCALCONFIGVALUE Return the first finite scalar configuration value.
    value = double(defaultValue);
    if ~isstruct(cfg)
        return;
    end

    fieldNames = string(fieldNames);
    for fieldIndex = 1:numel(fieldNames)
        fieldName = char(fieldNames(fieldIndex));
        if ~isfield(cfg, fieldName)
            continue;
        end

        candidateValue = double(cfg.(fieldName));
        if isscalar(candidateValue) && isfinite(candidateValue)
            value = candidateValue;
            return;
        end
    end
end
