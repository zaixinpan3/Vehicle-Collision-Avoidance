function boundaryMask = localExpandBoundaryPair( ...
        lineModel, forwardModel, x, y, z, valid, maxCurbZ, ...
        lineDistanceTolerance, forwardDistanceTolerance, ...
        lineLongitudinalMargin, forwardLongitudinalMargin, heightMargin, ...
        topSurfaceDistanceTolerance, topSurfaceHeightOffset, ...
        topSurfaceAzimuthRadius, topSurfaceRingRadius)
%LOCALEXPANDBOUNDARYPAIR Prefer a supported curve over its line anchor.
%   The line is only an anchor for the quadratic search. Retaining it beyond
%   the curve support can reintroduce a long, straight road-surface seam or
%   scenery edge. Extend a supported bidirectional curve over the line
%   anchor's observed domain and use the curve exclusively.
    if forwardModel.found
        expansionModel = forwardModel;
        if lineModel.found
            expansionModel.minimumX = min( ...
                forwardModel.minimumX, lineModel.minimumX);
            expansionModel.maximumX = max( ...
                forwardModel.maximumX, lineModel.maximumX);
        end
        boundaryMask = localExpandBoundary( ...
            expansionModel, x, y, z, valid, maxCurbZ, ...
            forwardDistanceTolerance, forwardLongitudinalMargin, ...
            heightMargin, ...
            topSurfaceDistanceTolerance, topSurfaceHeightOffset, ...
            topSurfaceAzimuthRadius, topSurfaceRingRadius);
        return;
    end

    boundaryMask = localExpandBoundary( ...
        lineModel, x, y, z, valid, maxCurbZ, ...
        lineDistanceTolerance, lineLongitudinalMargin, heightMargin, ...
        topSurfaceDistanceTolerance, topSurfaceHeightOffset, ...
        topSurfaceAzimuthRadius, topSurfaceRingRadius);
end

function boundaryMask = localExpandBoundary( ...
        model, x, y, z, valid, maxCurbZ, distanceTolerance, ...
        longitudinalMargin, heightMargin, ...
        topSurfaceDistanceTolerance, topSurfaceHeightOffset, ...
        topSurfaceAzimuthRadius, topSurfaceRingRadius)
%LOCALEXPANDBOUNDARY Recover curb-face points omitted by sparse seed detection.
    boundaryMask = false(size(valid));
    if ~model.found
        return;
    end

    curveY = model.curvature * x.^2 + model.slope * x + model.intercept;
    curveSlope = 2.0 * model.curvature * x + model.slope;
    perpendicularDistance = abs(y - curveY) ./ hypot(1.0, curveSlope);
    domainMask = valid & ...
        z <= maxCurbZ & ...
        z >= model.minimumZ - heightMargin & ...
        z <= model.maximumZ + heightMargin & ...
        x >= model.minimumX - longitudinalMargin & ...
        x <= model.maximumX + longitudinalMargin;
    boundaryMask = domainMask & ...
        perpendicularDistance <= distanceTolerance;
    topSurfaceCandidateMask = domainMask & ...
        z >= model.maximumZ + topSurfaceHeightOffset & ...
        perpendicularDistance <= max( ...
            distanceTolerance, topSurfaceDistanceTolerance);
    nearbyBoundaryMask = localCircularNeighborhoodMask( ...
        boundaryMask, topSurfaceRingRadius, topSurfaceAzimuthRadius);
    boundaryMask = boundaryMask | ...
        (topSurfaceCandidateMask & nearbyBoundaryMask);
end

function neighborhoodMask = localCircularNeighborhoodMask( ...
        mask, ringRadius, azimuthRadius)
%LOCALCIRCULARNEIGHBORHOODMASK Find nearby responses with azimuth wrapping.
    supportCount = zeros(size(mask));
    for azimuthOffset = -azimuthRadius:azimuthRadius
        shiftedMask = circshift(mask, [0, azimuthOffset]);
        supportCount = supportCount + movsum( ...
            double(shiftedMask), [ringRadius, ringRadius], 1);
    end
    neighborhoodMask = supportCount > 0;
end

