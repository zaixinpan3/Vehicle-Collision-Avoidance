function [enabled, source] = localRingFeatureFusionActivation( ...
        cfg, numberOfRings, numberOfAzimuths)
%LOCALRINGFEATUREFUSIONACTIVATION Enable only for the calibrated sensor.
    enabled = numberOfRings == 64 && numberOfAzimuths == 1000;
    source = "automatic-sensor-profile";
    fieldName = "curbRingFeatureFusionEnabled";
    if ~isstruct(cfg) || ~isfield(cfg, fieldName)
        return;
    end
    candidate = cfg.(fieldName);
    validLogical = islogical(candidate) && isscalar(candidate);
    validNumeric = isnumeric(candidate) && isreal(candidate) ...
        && isscalar(candidate) && isfinite(candidate) ...
        && (candidate == 0 || candidate == 1);
    if ~validLogical && ~validNumeric
        error( ...
            "groundPointsProcessing:InvalidRingFeatureFusionEnabled", ...
            "%s must be a logical scalar.", fieldName);
    end
    enabled = logical(candidate);
    source = "configured";
end

