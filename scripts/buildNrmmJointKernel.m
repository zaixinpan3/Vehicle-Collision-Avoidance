function information = buildNrmmJointKernel()
%buildNrmmJointKernel Compile joint plant/observer values and sensitivities.
% The generated adapter calls the same RK4 source as the MATLAB fallback.
% All gains, saturation domains, sensor inputs, and integration settings are
% runtime arguments. No noise channels or feedback couplings are removed.
    root = fileparts(fileparts(mfilename('fullpath')));
    addpath(fullfile(root,'estimator'),fullfile(root,'controller'),fullfile(root,'config'));
    output = fullfile(root,'solver','nrmm');
    if ~isfolder(output),mkdir(output);end
    addpath(output);
    domain = struct('speedMinimum',1,'speedMaximum',20, ...
        'scalarAccelerationMaximum',2,'yawRateMaximum',.1, ...
        'accelerationNormBound',3,'regularizationSpeedMinimum',1);
    design = struct('velocity',struct('gain',1),'position',struct('gain',1), ...
        'yaw',struct('correctionBandwidth',1), ...
        'target',struct('innovationGains',ones(3,1),'domain',domain));
    measurement = struct('bodyAcceleration',zeros(2,1),'yawRate',0, ...
        'gnssVelocity',zeros(2,1),'radarDetectionAvailable',false);
    % Both the ego-only (7) and coupled (15) observer lifts use this kernel.
    % The number of shared primitive columns follows the sensor-block length.
    state = coder.typeof(0,[15,1],[true,false]);
    tangent = coder.typeof(0,[15,Inf],[true,true]);
    measurementTangent = coder.typeof(0,[11,Inf],[true,true]);
    pseudoTangent = coder.typeof(0,[4,Inf],[false,true]);
    types = {state,tangent,measurement,measurementTangent,zeros(4,1),pseudoTangent,design,0,0};
    wrapper = fullfile(output,'nrmmJointObserverKernel.m');
    file = fopen(wrapper,'w');
    assert(file>=0,'buildNrmmJointKernel:writeFailed','Cannot create generated adapter.');
    cleanup = onCleanup(@()fclose(file));
    fprintf(file,'%s\n', ...
        'function result = nrmmJointObserverKernel(state,gradient,input,dm,pseudo,dpseudo,design,step,count)', ...
        "result = nrmmJointPrediction('observerRk4',state,gradient,input,dm,pseudo,dpseudo,design,step,count);", ...
        'end');
    clear cleanup nrmmJointObserverKernelMex;
    settings = coder.config('mex');
    settings.GenerateReport = false;settings.EnableOpenMP = false;
    codegen('-config',settings,wrapper,'-args',types, ...
        '-o',fullfile(output,'nrmmJointObserverKernelMex'), ...
        '-d',fullfile(output,'generatedJointObserver'));
    plant=nrmmJointPrediction('plantConfiguration',collisionAvoidanceControllerConfig(),zeros(4,1));
    types={zeros(6,1),zeros(2,1),plant,ones(4,1), ...
        coder.typeof(0,[6,Inf],[false,true]),coder.typeof(0,[2,Inf],[false,true]), ...
        coder.typeof(0,[4,Inf],[false,true])};
    wrapper=fullfile(output,'nrmmJointPlantKernel.m');
    file=fopen(wrapper,'w');
    assert(file>=0,'buildNrmmJointKernel:writeFailed','Cannot create generated adapter.');
    cleanup=onCleanup(@()fclose(file));
    fprintf(file,'%s\n', ...
        'function result = nrmmJointPlantKernel(x,u,plant,ratio,dx,du,dp)', ...
        "result = nrmmJointPrediction('plantField',x,u,plant,ratio,dx,du,dp);",'end');
    clear cleanup nrmmJointPlantKernelMex;
    codegen('-config',settings,wrapper,'-args',types, ...
        '-o',fullfile(output,'nrmmJointPlantKernelMex'), ...
        '-d',fullfile(output,'generatedJointPlant'));
    rehash;
    information = struct('binary',fullfile(output,"nrmmJointObserverKernelMex."+mexext), ...
        'plantBinary',fullfile(output,"nrmmJointPlantKernelMex."+mexext), ...
        'matlabVersion',string(version),'algorithmSource',"estimator/nrmmJointPrediction.m", ...
        'targetSource',"estimator/nrmmTargetJacobian.m",'plantSource',"controller/nonlinearBicycleModel.m");
end
