            double(parser.Results.StraightTargetInitialDistance), ...
        "straightTargetLateralOffset", ...
            double(parser.Results.StraightTargetLateralOffset), ...
        "straightTargetWidth", ...
            double(parser.Results.StraightTargetWidth), ...
        "curvedTargetInitialDistance", ...
            double(parser.Results.CurvedTargetInitialDistance), ...
        "curvedTargetWidth", ...
            double(parser.Results.CurvedTargetWidth), ...
        "curvedTargetCollisionLateralOffset", ...
            double(parser.Results ...
                .CurvedTargetCollisionLateralOffset), ...
        "curvedArcLengthAfter", ...
            double(parser.Results.CurvedArcLengthAfter), ...
        "seed", double(parser.Results.Seed), ...
        "circularRadius", double(parser.Results.CircularRadius), ...
        "sCurveMaximumCurvature", ...
            double(parser.Results.SCurveMaximumCurvature), ...
        "sCurveCurvatureWavelength", ...
            double(parser.Results.SCurveCurvatureWavelength), ...
        "sCurveArcLengthBefore", ...
            double(parser.Results.SCurveArcLengthBefore), ...
