function summary = generateEstimatedStateAvoidanceVideos(varargin)
% generateEstimatedStateAvoidanceVideos Simulate and render three videos.
%
% The active straight and circular cases and the retained S-curve
% visualization case use the configured
% GNSS/IMU/gyroscope/radar estimator-controller interface. The target
% starts outside that range. The ego first cruises on the centerline, then
% the target enters the shared sensing range and is provisionally acquired
% from the first radar sample using the configured oncoming-speed prior.
% The internal target track may coast for the configured finite timeout,
% but it is published to the controller only while radar currently
% observes it; an expired track is retired. Every video shows the shared
% target/road sensing range, the current finite quadratic fits of the
% sensed left and right outer curbs, and the known nominal-path-offset
% shoulder corridors. The retained S curve is generated here for the
% requested visualization but remains outside the active two-road
% controller acceptance entry point.
% MP4 files are written to the repository root unless OutputDirectory is
% set.

    options = localOptions(varargin{:});
    repositoryRoot = fileparts(fileparts(mfilename("fullpath")));
    addpath(fullfile(repositoryRoot, "config"));
    addpath(fullfile(repositoryRoot, "scripts"));

    outputDirectory = options.outputDirectory;
    if strlength(outputDirectory) == 0
        outputDirectory = string(repositoryRoot);
    end

    scenarioResult = runEstimatedStateAvoidanceScenarios( ...
        Duration=options.duration, ...
        ReferenceSpeed=options.referenceSpeed, ...
        TargetSpeed=options.targetSpeed, ...
        StraightTargetInitialDistance= ...
            options.straightTargetInitialDistance, ...
        StraightTargetLateralOffset= ...
            options.straightTargetLateralOffset, ...
        StraightTargetWidth=options.straightTargetWidth, ...
        CurvedTargetInitialDistance= ...
            options.curvedTargetInitialDistance, ...
        CurvedTargetWidth=options.curvedTargetWidth, ...
        CurvedTargetCollisionLateralOffset= ...
            options.curvedTargetCollisionLateralOffset, ...
        CurvedArcLengthAfter=options.curvedArcLengthAfter, ...
        CircularRadius=options.circularRadius, ...
        RecoveryWindow=options.recoveryWindow, ...
        RequireCruiseRecovery=true, ...
        MinimumPreDetectionCruiseDuration= ...
            options.minimumPreDetectionCruiseDuration, ...
        RequirePreDetectionCruise=true, ...
        LongitudinalAccelerationThreshold= ...
            options.longitudinalAccelerationThreshold, ...
        LateralAccelerationThreshold= ...
            options.lateralAccelerationThreshold, ...
        MinimumCoupledDuration=options.minimumCoupledDuration, ...
        RequireCoupledManeuver=true, ...
        Seed=options.seed, ...
        Report=options.report, ...
        Progress=options.progress);
    if ~scenarioResult.allScenariosPassed
        failedScenario = scenarioResult.scenarioNames( ...
            ~scenarioResult.scenarioPassed);
        failureText = strjoin(failedScenario, ", ");
        if ~scenarioResult.couplingRequirementMet
            if strlength(failureText) > 0
                failureText = failureText ...
                    + "; coupled-maneuver suite coverage";
            else
                failureText = "coupled-maneuver suite coverage";
            end
        end
        error("generateEstimatedStateAvoidanceVideos:" ...
            + "scenarioAcceptanceFailed", ...
            "Refusing to render failed scenario(s): %s.", ...
            failureText);
    end

    sCurveConfiguration = scenarioResult.configuration;
    sCurveConfiguration.randomSeed = options.seed+2;
    sCurveConfiguration.observer.ego.domain.yawRateMaximum = max( ...
        sCurveConfiguration.observer.ego.domain.yawRateMaximum, ...
        1.5*options.referenceSpeed*options.sCurveMaximumCurvature);
    sCurve = runVaryingCurvatureStraightTargetAvoidanceScenario( ...
        MaximumCurvature=options.sCurveMaximumCurvature, ...
        CurvatureWavelength=options.sCurveCurvatureWavelength, ...
        ArcLengthBefore=options.sCurveArcLengthBefore, ...
        ArcLengthAfter=options.sCurveArcLengthAfter, ...
        Duration=options.duration, ...
        ReferenceSpeed=options.referenceSpeed, ...
        TargetSpeed=options.targetSpeed, ...
        TargetInitialDistance=options.sCurveTargetInitialDistance, ...
        TargetCollisionLateralOffset= ...
            options.sCurveTargetCollisionLateralOffset, ...
        TargetLength=5.0, ...
        TargetWidth=options.sCurveTargetWidth, ...
        PerceptionRange=30.0, ...
        RightRoadBoundaryOffset=6.0, ...
        LeftRoadBoundaryOffset=8.0, ...
        RoadShoulderWidth=2.6, ...
        EgoLength=5.0, EgoWidth=2.0, ...
        UseStateEstimator=true, ...
        EstimatorConfiguration=sCurveConfiguration, ...
        RecoveryWindow=options.recoveryWindow, ...
        RecoverySpeedTolerance=0.5, ...
        RecoveryLateralTolerance=0.2, ...
        RecoveryHeadingTolerance=0.02, ...
        Plot=false, Report=false, Progress=options.progress);
    sCurve.maneuverCoupling = evaluateManeuverCoupling( ...
        sCurve, ...
        LongitudinalAccelerationThreshold= ...
            options.longitudinalAccelerationThreshold, ...
        LateralAccelerationThreshold= ...
            options.lateralAccelerationThreshold, ...
        MinimumCoupledDuration=options.minimumCoupledDuration);
    sCurve.preDetectionCruise = evaluatePreDetectionCruise( ...
        sCurve, ...
        MinimumDuration=options.minimumPreDetectionCruiseDuration, ...
        SpeedTolerance=0.5, ...
        LateralTolerance=0.25, ...
        HeadingTolerance=0.03);
    sCurvePassed = localScenarioPassed(sCurve);

    scenarioResult.sCurve = sCurve;
    scenarioResult.scenarioNames = [ ...
        scenarioResult.scenarioNames; "sCurve"];
    scenarioResult.scenarioPassed = [ ...
        scenarioResult.scenarioPassed; sCurvePassed];
    scenarioResult.coupledScenario = [ ...
        scenarioResult.coupledScenario; ...
        sCurve.maneuverCoupling.significant];
    scenarioResult.couplingRequirementMet = ...
        ~scenarioResult.requireCoupledManeuver ...
        || any(scenarioResult.coupledScenario);
    scenarioResult.allScenariosPassed = ...
        all(scenarioResult.scenarioPassed) ...
        && scenarioResult.couplingRequirementMet;
    if ~scenarioResult.allScenariosPassed
        failedScenario = scenarioResult.scenarioNames( ...
            ~scenarioResult.scenarioPassed);
        failureText = strjoin(failedScenario, ", ");
        if ~scenarioResult.couplingRequirementMet
            failureText = strjoin( ...
                [failureText; "coupled-maneuver suite coverage"], ...
                ", ");
        end
        error("generateEstimatedStateAvoidanceVideos:" ...
            + "scenarioAcceptanceFailed", ...
            "Refusing to render failed scenario(s): %s.", ...
            failureText);
    end

    scenarioFields = ["straight"; "circular"; "sCurve"];
    scenarioLabels = [ ...
        "Straight-road oncoming-target avoidance"; ...
        compose("Circular-road (R = %.0f m) " ...
            + "straight-target avoidance", ...
            options.circularRadius); ...
        compose("Finite S-curve (|kappa|max = %.3f 1/m) " ...
            + "straight-target avoidance", ...
            options.sCurveMaximumCurvature)];
    fileNames = [ ...
        "estimated_state_avoidance_straight.mp4"; ...
        "estimated_state_avoidance_circular.mp4"; ...
        "estimated_state_avoidance_s_curve.mp4"];
    video = cell(numel(scenarioFields), 1);
    for scenarioIdx = 1:numel(scenarioFields)
        outputPath = fullfile( ...
            outputDirectory, fileNames(scenarioIdx));
        if options.progress
            fprintf("Rendering %s\n", outputPath);
        end
        video{scenarioIdx} = renderEstimatedStateAvoidanceVideo( ...
            scenarioResult.(scenarioFields(scenarioIdx)), ...
            outputPath, ...
            FramePeriod=options.framePeriod, ...
            FrameRate=options.frameRate, ...
            Quality=options.quality, ...
            HoldLastFrameSeconds=options.holdLastFrameSeconds, ...
            FigureVisible=options.figureVisible, ...
            ScenarioLabel=scenarioLabels(scenarioIdx), ...
            FfmpegPreset=options.ffmpegPreset, ...
            FfmpegCrf=options.ffmpegCrf);
    end
    video = vertcat(video{:});

    summary = struct( ...
        "scenarioResult", scenarioResult, ...
        "video", video, ...
        "allScenariosPassed", scenarioResult.allScenariosPassed, ...
        "allVideosCreated", all(isfile(string({video.outputPath}))));
    if options.report
        localReport(summary);
    end
end

