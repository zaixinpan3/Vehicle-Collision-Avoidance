function localReport(summary)
    fprintf("\nEstimator-in-the-loop avoidance videos\n");
    for videoIdx = 1:numel(summary.video)
        video = summary.video(videoIdx);
        fprintf("  %s\n", video.outputPath);
        fprintf("    %dx%d, %.1f fps, %d frames, %.2f s, %.1f MiB\n", ...
            video.width, video.height, video.frameRate, ...
            video.frameCount, video.videoDuration, ...
            video.fileSizeBytes/(1024.0^2));
        fprintf("    minimum d_rect %.4f m, collision free: %d\n", ...
            video.minimumSeparatingAxisMargin, video.collisionFree);
        fprintf("    perception %.1f m; %d road fits; " ...
            + "minimum road margin %.4f m; contained: %d\n", ...
            video.perceptionRange, ...
            video.perceivedRoadBoundaryCount, ...
            video.minimumRoadBoundaryMargin, ...
            video.noRoadBoundaryCrossing);
        fprintf("    target first detected at %.2f s after " ...
            + "%.2f s of out-of-range cruise\n", ...
            video.firstTargetDetectionTime, ...
            video.preDetectionCruiseDuration);
        fprintf("    cruise recovered: %d; final-window " ...
            + "speed/lateral/course-heading errors " ...
            + "%.3f m/s / %.3f m / %.3f rad\n", ...
            video.cruiseRecovered, ...
            video.maximumRecoverySpeedError, ...
            video.maximumRecoveryLateralError, ...
            video.maximumRecoveryHeadingError);
        fprintf("    coupled maneuver: %d; longest %.2f s; " ...
            + "peak |a_x| / |a_y| %.2f / %.2f m/s^2\n", ...
            video.coupledManeuverObserved, ...
            video.maximumContinuousCoupledDuration, ...
            video.maximumAbsoluteLongitudinalAcceleration, ...
            video.maximumAbsoluteLateralAcceleration);
    end
    fprintf("  Scenarios passed: %d; videos created: %d\n\n", ...
        summary.allScenariosPassed, summary.allVideosCreated);
end

function passed = localScenarioPassed(result)
    passed = ~result.failure.occurred ...
        && result.metrics.controllerCompletedScenario ...
        && result.avoidance.baselineCollides ...
        && result.avoidance.collisionFree ...
        && result.roadSafety.noBoundaryCrossing ...
        && result.avoidance.passedTarget ...
        && result.avoidance.remainedMoving ...
        && result.avoidance.recoveredCruise ...
        && result.estimator.metrics.allEstimatesFinite ...
        && result.estimator.metrics.controllerInputsFromEstimator ...
        && result.estimator.metrics.sensorContractValid ...
        && result.estimator.metrics.targetAcquisitionOccurred ...
        && result.estimator.metrics.allRadarDetectionsWithinRange ...
        && result.preDetectionCruise.passed;
end

function valid = localPositiveScalar(value)
    valid = isnumeric(value) && isreal(value) && isscalar(value) ...
        && isfinite(value) && value > 0.0;
end

function valid = localNonnegativeScalar(value)
    valid = isnumeric(value) && isreal(value) && isscalar(value) ...
        && isfinite(value) && value >= 0.0;
end

function valid = localFiniteScalar(value)
    valid = isnumeric(value) && isreal(value) && isscalar(value) ...
        && isfinite(value);
end

function valid = localIntegerScalar(value)
    valid = isnumeric(value) && isreal(value) && isscalar(value) ...
        && isfinite(value) && value == floor(value);
end

function valid = localValidQuality(value)
    valid = isnumeric(value) && isreal(value) && isscalar(value) ...
        && isfinite(value) && value >= 0.0 && value <= 100.0;
end

function valid = localValidCrf(value)
    valid = isnumeric(value) && isreal(value) && isscalar(value) ...
        && isfinite(value) && value >= 0.0 && value <= 51.0;
end

function valid = localLogicalScalar(value)
    valid = (islogical(value) || isnumeric(value)) ...
        && isscalar(value) && isfinite(value);
end

function valid = localTextScalar(value)
    valid = ischar(value) || (isstring(value) && isscalar(value));
end
