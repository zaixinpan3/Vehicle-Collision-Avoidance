function frame = localFullHdFrame(frame)
    targetHeight = 1080;
    targetWidth = 1920;
    image = frame.cdata;
    image = localCenteredCrop(image, targetHeight, targetWidth);
    imageHeight = size(image, 1);
    imageWidth = size(image, 2);
    canvas = repmat( ...
        uint8(255), targetHeight, targetWidth, size(image, 3));
    firstRow = floor((targetHeight-imageHeight)/2) + 1;
    firstColumn = floor((targetWidth-imageWidth)/2) + 1;
    canvas( ...
        firstRow:(firstRow+imageHeight-1), ...
        firstColumn:(firstColumn+imageWidth-1), :) = image;
    frame.cdata = canvas;
    frame.colormap = [];
end

function image = localCenteredCrop(image, targetHeight, targetWidth)
    imageHeight = size(image, 1);
    imageWidth = size(image, 2);
    if imageHeight > targetHeight
        firstRow = floor((imageHeight-targetHeight)/2) + 1;
        image = image(firstRow:(firstRow+targetHeight-1), :, :);
    end
    if imageWidth > targetWidth
        firstColumn = floor((imageWidth-targetWidth)/2) + 1;
        image = image(:, firstColumn:(firstColumn+targetWidth-1), :);
    end
end

function vertices = localPoseRectangle(position, yaw, length, width)
    bodyVertices = 0.5 * [ ...
        length, length, -length, -length; ...
        width, -width, -width, width];
    rotation = [cos(yaw), -sin(yaw); sin(yaw), cos(yaw)];
    vertices = rotation*bodyVertices+position;
end

function rotation = localRotation(yaw)
    rotation = [cos(yaw), -sin(yaw); sin(yaw), cos(yaw)];
end

function [xLimits, yLimits] = localCameraLimits( ...
        egoPosition, targetPosition, perceptionRange)
    relativePosition = targetPosition-egoPosition;
    rangePadding = 3.0;
    xLimits = egoPosition(1) ...
        + [-perceptionRange-rangePadding, ...
            perceptionRange+rangePadding];
    yLimits = egoPosition(2) ...
        + [-perceptionRange-rangePadding, ...
            perceptionRange+rangePadding];
    if norm(relativePosition) <= 65.0
        targetPadding = 6.0;
        xLimits(1) = min( ...
            xLimits(1), targetPosition(1)-targetPadding);
        xLimits(2) = max( ...
            xLimits(2), targetPosition(1)+targetPadding);
        yLimits(1) = min( ...
            yLimits(1), targetPosition(2)-targetPadding);
        yLimits(2) = max( ...
            yLimits(2), targetPosition(2)+targetPadding);
    end
end

function limits = localPaddedLimits(value)
    finiteValue = value(isfinite(value));
    minimum = min(finiteValue);
    maximum = max(finiteValue);
    padding = max(0.5, 0.10*(maximum-minimum));
    limits = [minimum-padding, maximum+padding];
end

function limits = localMarginLimits(controlledMargin, baselineMargin)
    value = [controlledMargin(:); baselineMargin(:); 0.0];
    finiteValue = value(isfinite(value));
    minimum = min(finiteValue);
    lowerPadding = max(0.5, 0.06*abs(minimum));
    lower = min(-1.0, minimum-lowerPadding);
    upper = min(45.0, max(5.0, max(finiteValue)+0.5));
    limits = [lower, upper];
end

function [writerPath, profile, transcodeToMp4] = ...
        localWriterConfiguration(outputPath)
    [outputDirectory, ~, extension] = fileparts(outputPath);
    transcodeToMp4 = lower(string(extension)) == ".mp4";
    if transcodeToMp4
        writerPath = string(tempname(outputDirectory))+".avi";
        profile = "Motion JPEG AVI";
    else
        writerPath = outputPath;
        profile = "Motion JPEG AVI";
    end
end

function localTranscodeToMp4(inputPath, outputPath, options)
    [locationStatus, ffmpegLocation] = ...
        system("command -v ffmpeg");
    ffmpegLocation = strtrim(string(ffmpegLocation));
    if locationStatus ~= 0 || strlength(ffmpegLocation) == 0
        error("renderEstimatedStateAvoidanceVideo:ffmpegUnavailable", ...
            "ffmpeg is required for H.264 MP4 output.");
    end
    ffmpegCommand = "env -u LD_LIBRARY_PATH " ...
        + localShellQuote(ffmpegLocation);
    [ffmpegStatus, ~] = system(ffmpegCommand+" -version");
    if ffmpegStatus ~= 0
        error("renderEstimatedStateAvoidanceVideo:ffmpegUnavailable", ...
            "The system ffmpeg executable could not be started.");
    end
    command = ffmpegCommand ...
        + " -hide_banner -loglevel error -y -i " ...
        + localShellQuote(inputPath) ...
        + " -an -c:v libx264 -preset " ...
        + localShellQuote(options.ffmpegPreset) ...
        + " -crf " + string(options.ffmpegCrf) ...
        + " -pix_fmt yuv420p -movflags +faststart " ...
        + localShellQuote(outputPath);
    [status, message] = system(command);
    if status ~= 0
        error("renderEstimatedStateAvoidanceVideo:transcodeFailed", ...
            "ffmpeg failed: %s", strtrim(message));
    end
end

