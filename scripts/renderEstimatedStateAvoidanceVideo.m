function graphics = localDrawRoad( ...
        axesHandle, centerline, boundaryOffsets, shoulderWidth)
    position = double(centerline);
    tangent = [gradient(position(:, 1)), gradient(position(:, 2))];
    tangentNorm = vecnorm(tangent, 2, 2);
    tangent = tangent ./ tangentNorm;
    normal = [-tangent(:, 2), tangent(:, 1)];
    rightOffset = boundaryOffsets(1);
    leftOffset = boundaryOffsets(2);
    leftLaneEdge = position + leftOffset*normal;
    rightLaneEdge = position - rightOffset*normal;
    leftShoulderOuter = position ...
        + (leftOffset+shoulderWidth)*normal;
    rightShoulderOuter = position ...
        - (rightOffset+shoulderWidth)*normal;

    shoulderSurface = patch(axesHandle, ...
        [leftShoulderOuter(:, 1); ...
            flipud(rightShoulderOuter(:, 1))], ...
        [leftShoulderOuter(:, 2); ...
            flipud(rightShoulderOuter(:, 2))], ...
        [0.82, 0.78, 0.66], EdgeColor="none", ...
        FaceAlpha=0.75, ...
        DisplayName=compose("%.1f m nominal shoulders", ...
            shoulderWidth));
    patch(axesHandle, ...
        [leftLaneEdge(:, 1); flipud(rightLaneEdge(:, 1))], ...
        [leftLaneEdge(:, 2); flipud(rightLaneEdge(:, 2))], ...
        [0.93, 0.93, 0.93], EdgeColor="none", ...
        HandleVisibility="off");
    laneEdge = plot(axesHandle, ...
        leftLaneEdge(:, 1), leftLaneEdge(:, 2), ...
        Color=[0.80, 0.55, 0.05], LineStyle="--", ...
        LineWidth=1.4, DisplayName="Lane edge / shoulder entry");
    plot(axesHandle, ...
        rightLaneEdge(:, 1), rightLaneEdge(:, 2), ...
        Color=[0.80, 0.55, 0.05], LineStyle="--", ...
        LineWidth=1.4, HandleVisibility="off");
    plot(axesHandle, ...
        leftShoulderOuter(:, 1), leftShoulderOuter(:, 2), ...
        Color=[0.25, 0.25, 0.25], LineStyle=":", ...
        LineWidth=1.0, HandleVisibility="off");
    plot(axesHandle, ...
        rightShoulderOuter(:, 1), rightShoulderOuter(:, 2), ...
        Color=[0.25, 0.25, 0.25], LineStyle=":", ...
        LineWidth=1.0, HandleVisibility="off");
    graphics = struct( ...
        "shoulderSurface", shoulderSurface, ...
        "laneEdge", laneEdge);
end

function fitPoint = localBoundaryFitPoints(perception, boundary)
    parameterRange = boundary.parameterRange;
    parameterCount = max( ...
        80, ceil(diff(parameterRange)/0.20)+1);
    parameter = linspace( ...
        parameterRange(1), parameterRange(2), parameterCount);
    lateral = polyval(boundary.coefficients, parameter);
    fitPoint = ( ...
        boundary.origin ...
        + boundary.longitudinalDirection*parameter ...
        + boundary.lateralDirection*lateral).';
    fitRange = vecnorm( ...
        fitPoint-perception.egoPose(1:2).', 2, 2);
    rangeTolerance = 100.0*eps(max( ...
        1.0, perception.rangeMaximum));
    fitPoint(fitRange > ...
        perception.rangeMaximum+rangeTolerance, :) = NaN;
end

function localUpdateBoundaryGraphics( ...
        fitHandle, sampleHandle, perception, boundary)
    fitPoint = localBoundaryFitPoints(perception, boundary);
    sourcePoint = boundary.sourcePoints;
    set(fitHandle, ...
        XData=fitPoint(:, 1), YData=fitPoint(:, 2));
    set(sampleHandle, ...
        XData=sourcePoint(:, 1), YData=sourcePoint(:, 2));
end

