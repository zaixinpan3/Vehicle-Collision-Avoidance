function metadata = renderEstimatedStateAvoidanceVideo( ...
        result, outputPath, varargin)
% renderEstimatedStateAvoidanceVideo Render one avoidance result as video.
%
% The synchronized visualization shows the road, the current finite
% quadratic outer-curb fits, their sensed source points, the shared
% target/road perception range, the known nominal-path-offset shoulder
% corridors, vehicle rectangles, plant and target truth, estimator outputs,
% ego speed, the signed rectangle
% separating-axis margin d_rect, controller inputs, and actual body-frame
% longitudinal/lateral accelerations. MATLAB writes Motion JPEG directly.
% MP4 output is transcoded to H.264 with ffmpeg for broad playback
% compatibility.

    options = localOptions(varargin{:});
    outputPath = localOutputPath(outputPath);
    localValidateResult(result);
    data = localAnimationData(result, options.framePeriod);

    outputDirectory = fileparts(outputPath);
    if strlength(outputDirectory) == 0
        outputDirectory = string(pwd);
        outputPath = fullfile(outputDirectory, outputPath);
    end
    if ~isfolder(outputDirectory)
        mkdir(outputDirectory);
    end

    [writerPath, writerProfile, transcodeToMp4] = ...
        localWriterConfiguration(outputPath);
    writer = VideoWriter(writerPath, writerProfile);
    writer.FrameRate = options.frameRate;
    if isprop(writer, "Quality")
        writer.Quality = options.quality;
    end

    [figureHandle, graphics] = localCreateFigure( ...
        result, data, options);
    figureCleanup = onCleanup(@() localCloseFigure(figureHandle));
    writerCleanup = onCleanup(@() localCloseWriter(writer));
    open(writer);

    frameSize = [1920, 1080];
    for frameIdx = 1:numel(data.time)
        localUpdateFigure(graphics, result, data, frameIdx);
        drawnow;
        frame = localFullHdFrame(getframe(figureHandle));
        writeVideo(writer, frame);
    end

    holdFrameCount = round( ...
        options.holdLastFrameSeconds * options.frameRate);
    if holdFrameCount > 0
        localShowCompletion(graphics, result, data);
        drawnow;
        frame = localFullHdFrame(getframe(figureHandle));
        for frameIdx = 1:holdFrameCount
            writeVideo(writer, frame);
        end
    end
    close(writer);
    clear writerCleanup;

    if transcodeToMp4
        localTranscodeToMp4(writerPath, outputPath, options);
        delete(writerPath);
    end

    fileInformation = dir(outputPath);
    coupling = data.coupling;
    metadata = struct( ...
        "outputPath", string(outputPath), ...
        "frameRate", options.frameRate, ...
        "framePeriod", options.framePeriod, ...
        "simulationDuration", data.time(end)-data.time(1), ...
        "frameCount", numel(data.time)+holdFrameCount, ...
        "videoDuration", ...
            (numel(data.time)+holdFrameCount)/options.frameRate, ...
        "width", frameSize(1), ...
        "height", frameSize(2), ...
        "fileSizeBytes", fileInformation.bytes, ...
        "minimumSeparatingAxisMargin", min(data.separationMargin), ...
        "collisionFree", all(data.separationMargin > 0.0), ...
        "perceptionRange", data.perception.rangeMaximum, ...
        "roadBoundaryVisualizationIncluded", true, ...
        "shoulderVisualizationIncluded", true, ...
        "roadShoulderWidth", ...
            result.perception.roadShoulderWidth, ...
        "roadOuterBoundaryOffsets", ...
            result.perception.roadOuterBoundaryOffsets, ...
        "roadTotalWidthIncludingShoulders", ...
            result.perception.roadTotalWidthIncludingShoulders, ...
        "perceivedRoadBoundaryCount", ...
            data.perception.boundaryCount, ...
        "maximumPerceivedRoadSourcePointRange", ...
            data.perception.maximumSourcePointRange, ...
        "maximumRenderedRoadBoundaryRange", ...
            data.perception.maximumRenderedFitRange, ...
        "minimumRoadBoundaryMargin", min(data.roadMargin), ...
        "noRoadBoundaryCrossing", ...
            result.roadSafety.noBoundaryCrossing, ...
        "firstTargetDetectionTime", ...
            data.estimate.firstDetectionTime, ...
        "preDetectionCruiseDuration", ...
            data.estimate.firstDetectionTime-data.time(1), ...
        "cruiseRecovered", result.avoidance.recoveredCruise, ...
        "maximumRecoverySpeedError", ...
            result.avoidance.maximumRecoverySpeedError, ...
        "maximumRecoveryLateralError", ...
            result.avoidance.maximumRecoveryLateralError, ...
        "maximumRecoveryHeadingError", ...
            result.avoidance.maximumRecoveryHeadingError, ...
        "maximumRecoveryCourseHeadingError", ...
            result.avoidance.maximumRecoveryHeadingError, ...
        "coupledManeuverObserved", coupling.significant, ...
        "coupledSampleCount", coupling.coupledSampleCount, ...
        "maximumContinuousCoupledDuration", ...
            coupling.maximumContinuousCoupledDuration, ...
        "maximumAbsoluteLongitudinalAcceleration", ...
            coupling.maximumAbsoluteLongitudinalAcceleration, ...
        "maximumAbsoluteLateralAcceleration", ...
            coupling.maximumAbsoluteLateralAcceleration, ...
        "maximumSimultaneousAccelerationProduct", ...
            coupling.maximumSimultaneousAccelerationProduct);
end

function options = localOptions(varargin)
    parser = inputParser;
    parser.FunctionName = mfilename;
    addParameter(parser, "FramePeriod", 0.025, @localPositiveScalar);
    addParameter(parser, "FrameRate", 20.0, @localPositiveScalar);
    addParameter(parser, "Quality", 90.0, @localValidQuality);
    addParameter(parser, "HoldLastFrameSeconds", ...
        1.0, @localNonnegativeScalar);
    addParameter(parser, "FigureVisible", false, @localLogicalScalar);
    addParameter(parser, "ScenarioLabel", "", @localTextScalar);
    addParameter(parser, "FfmpegPreset", "medium", @localTextScalar);
    addParameter(parser, "FfmpegCrf", 18.0, @localValidCrf);
    parse(parser, varargin{:});
    options = struct( ...
        "framePeriod", double(parser.Results.FramePeriod), ...
        "frameRate", double(parser.Results.FrameRate), ...
        "quality", double(parser.Results.Quality), ...
        "holdLastFrameSeconds", ...
            double(parser.Results.HoldLastFrameSeconds), ...
        "figureVisible", logical(parser.Results.FigureVisible), ...
        "scenarioLabel", string(parser.Results.ScenarioLabel), ...
        "ffmpegPreset", string(parser.Results.FfmpegPreset), ...
        "ffmpegCrf", double(parser.Results.FfmpegCrf));
end

function outputPath = localOutputPath(value)
    if ~(ischar(value) || (isstring(value) && isscalar(value)))
        error("renderEstimatedStateAvoidanceVideo:invalidOutputPath", ...
            "OutputPath must be a character vector or string scalar.");
    end
    outputPath = string(value);
    [~, ~, extension] = fileparts(outputPath);
    if ~ismember(lower(string(extension)), [".mp4", ".avi"])
        error("renderEstimatedStateAvoidanceVideo:invalidOutputFormat", ...
            "OutputPath must use an .mp4 or .avi extension.");
    end
end

function localValidateResult(result)
    requiredFields = [ ...
        "scenario"; "plantTrace"; "targetTruth"; ...
        "controllerConfiguration"; "controlTime"; "command"; ...
        "controlState"; ...
        "controllerEgoEstimate"; "targetEstimate"; "avoidance"; ...
        "baseline"; "estimator"; "controlTracking"; ...
        "perception"; "roadSafety"];
    if ~isstruct(result) || ~isscalar(result) ...
            || ~all(isfield(result, requiredFields))
        error("renderEstimatedStateAvoidanceVideo:invalidResult", ...
            "Result is not a complete estimator-in-the-loop scenario.");
    end
    if isempty(result.plantTrace.time) ...
            || isempty(result.targetTruth.time)
        error("renderEstimatedStateAvoidanceVideo:emptyResult", ...
            "Result must contain nonempty ego and target traces.");
    end
    if ~result.estimator.enabled
        error("renderEstimatedStateAvoidanceVideo:estimatorDisabled", ...
            "The visualization requires estimator-in-the-loop results.");
    end
    if ~isfield(result.perception, "rangeMaximum") ...
            || ~isfield(result.perception, "roadBoundaryFit") ...
            || ~isfield(result.perception, ...
                "roadBoundaryOffsets") ...
            || ~isfield(result.perception, ...
                "roadShoulderWidth") ...
            || ~isfield(result.perception, ...
                "roadOuterBoundaryOffsets") ...
            || ~isfield(result.perception, ...
                "roadTotalWidthIncludingShoulders") ...
            || ~isfinite(result.perception.rangeMaximum) ...
            || result.perception.rangeMaximum <= 0.0 ...
            || numel(result.perception.roadBoundaryOffsets) ~= 2 ...
            || any(~isfinite( ...
                result.perception.roadBoundaryOffsets), "all") ...
            || any(result.perception.roadBoundaryOffsets <= 0.0) ...
            || ~isscalar(result.perception.roadShoulderWidth) ...
            || ~isfinite(result.perception.roadShoulderWidth) ...
            || result.perception.roadShoulderWidth <= 0.0 ...
            || numel(result.perception.roadOuterBoundaryOffsets) ~= 2 ...
            || any(~isfinite( ...
                result.perception.roadOuterBoundaryOffsets), "all") ...
            || any(result.perception.roadOuterBoundaryOffsets ...
                <= result.perception.roadBoundaryOffsets, "all") ...
            || ~isscalar( ...
                result.perception.roadTotalWidthIncludingShoulders) ...
            || ~isfinite( ...
                result.perception.roadTotalWidthIncludingShoulders) ...
            || result.perception.roadTotalWidthIncludingShoulders <= 0.0 ...
            || ~iscell(result.perception.roadBoundaryFit) ...
            || isempty(result.perception.roadBoundaryFit) ...
            || any(cellfun(@isempty, ...
                result.perception.roadBoundaryFit))
        error("renderEstimatedStateAvoidanceVideo:" ...
            + "missingRoadPerception", ...
            "The visualization requires finite road-boundary fits.");
    end
    expectedOuterOffsets = ...
        result.perception.roadBoundaryOffsets(:) ...
            + result.perception.roadShoulderWidth;
    expectedTotalWidth = ...
        sum(result.perception.roadBoundaryOffsets) ...
            + 2.0*result.perception.roadShoulderWidth;
    geometryTolerance = 100.0*eps(max( ...
        [1.0; expectedOuterOffsets; expectedTotalWidth]));
    if any(abs( ...
            result.perception.roadOuterBoundaryOffsets(:) ...
                - expectedOuterOffsets) > geometryTolerance) ...
            || abs( ...
                result.perception.roadTotalWidthIncludingShoulders ...
                    - expectedTotalWidth) > geometryTolerance
        error("renderEstimatedStateAvoidanceVideo:" ...
            + "inconsistentShoulderGeometry", ...
            "Shoulder width, outer offsets, and total road width " ...
                + "must describe the same geometry.");
    end
    if ~isfield(result.roadSafety, ...
            "conservativeBoundaryFunctionMargin") ...
            || ~isfield(result.roadSafety, ...
                "noBoundaryCrossing")
        error("renderEstimatedStateAvoidanceVideo:" ...
            + "missingRoadSafety", ...
            "The visualization requires road-boundary safety results.");
    end
end

function data = localAnimationData(result, framePeriod)
    sourceTime = result.plantTrace.time(:);
    finiteMask = isfinite(sourceTime);
    sourceTime = sourceTime(finiteMask);
    [sourceTime, uniqueIdx] = unique(sourceTime, "stable");
    if numel(sourceTime) < 2
        error("renderEstimatedStateAvoidanceVideo:shortTrace", ...
            "The plant trace must contain at least two unique times.");
    end

    frameTime = (sourceTime(1):framePeriod:sourceTime(end)).';
    if sourceTime(end)-frameTime(end) ...
            > 100.0*eps(max(1.0, sourceTime(end)))
        frameTime(end+1, 1) = sourceTime(end);
    end

    ego = struct( ...
        "position", [ ...
            localInterpolate(sourceTime, ...
                result.plantTrace.positionX(finiteMask), ...
                uniqueIdx, frameTime), ...
            localInterpolate(sourceTime, ...
                result.plantTrace.positionY(finiteMask), ...
                uniqueIdx, frameTime)], ...
        "yaw", localInterpolate(sourceTime, ...
            unwrap(result.plantTrace.yaw(finiteMask)), ...
            uniqueIdx, frameTime), ...
        "speed", localInterpolate(sourceTime, ...
            result.plantTrace.longitudinalVelocity(finiteMask), ...
            uniqueIdx, frameTime));

    targetTime = result.targetTruth.time(:);
    [targetTime, targetUniqueIdx] = unique(targetTime, "stable");
    target = struct( ...
        "position", [ ...
            interp1(targetTime, ...
                result.targetTruth.position(targetUniqueIdx, 1), ...
                frameTime, "linear", "extrap"), ...
            interp1(targetTime, ...
                result.targetTruth.position(targetUniqueIdx, 2), ...
                frameTime, "linear", "extrap")], ...
        "yaw", interp1(targetTime, ...
            unwrap(result.targetTruth.yaw(targetUniqueIdx)), ...
            frameTime, "linear", "extrap"));

    estimate = localEstimatorSignals(result, frameTime);
    input = localInputSignals(result);
    if isfield(result, "maneuverCoupling")
        coupling = result.maneuverCoupling;
    else
        coupling = evaluateManeuverCoupling(result);
    end
    separationMargin = rectangleSeparationMargin( ...
        ego.position, ego.yaw, target.position, target.yaw, ...
        result.controllerConfiguration.vehicle.length, ...
        result.controllerConfiguration.vehicle.width, ...
        result.targetTruth.length, result.targetTruth.width);
    baselineMarginSource = ...
        result.baseline.separatingAxisMargin(finiteMask);
    baselineMargin = interp1(sourceTime, ...
        baselineMarginSource(uniqueIdx), ...
        frameTime, "linear", "extrap");
    trackingSampleCount = min( ...
        numel(result.controlTime), ...
        numel(result.controlTracking.lateralError));
    trackingTime = result.controlTime(1:trackingSampleCount);
    tracking = struct( ...
        "lateralError", interp1(trackingTime, ...
            result.controlTracking.lateralError( ...
                1:trackingSampleCount), ...
            frameTime, "linear", "extrap"), ...
        "headingError", interp1(trackingTime, ...
            unwrap(result.controlTracking.headingError( ...
                1:trackingSampleCount)), ...
            frameTime, "linear", "extrap"));
    perception = localPerceptionSignals(result, frameTime);
    roadMargin = localRoadMarginSignal( ...
        result, sourceTime, finiteMask, uniqueIdx, frameTime);

    data = struct( ...
        "time", frameTime, ...
        "ego", ego, ...
        "target", target, ...
        "estimate", estimate, ...
        "tracking", tracking, ...
        "input", input, ...
        "coupling", coupling, ...
        "separationMargin", separationMargin, ...
        "baselineMargin", baselineMargin, ...
        "perception", perception, ...
        "roadMargin", roadMargin);
end

function value = localInterpolate( ...
        sourceTime, sourceValue, uniqueIdx, queryTime)
    sourceValue = sourceValue(:);
    value = interp1(sourceTime, sourceValue(uniqueIdx), ...
        queryTime, "linear", "extrap");
end

function estimate = localEstimatorSignals(result, frameTime)
    sampleCount = min([ ...
        numel(result.controllerEgoEstimate), ...
        numel(result.targetEstimate), ...
        numel(result.estimator.sensorFrame), ...
        numel(result.controlTime)-1]);
    sampleTime = result.controlTime(1:sampleCount);
    egoPosition = NaN(sampleCount, 2);
    egoYaw = NaN(sampleCount, 1);
    egoSpeed = NaN(sampleCount, 1);
    targetPosition = NaN(sampleCount, 2);
    targetYaw = NaN(sampleCount, 1);
    radarTargetPosition = NaN(sampleCount, 2);
    radarDetected = false(sampleCount, 1);
    targetEstimateAvailable = false(sampleCount, 1);
    for sampleIdx = 1:sampleCount
        egoOutput = result.controllerEgoEstimate{sampleIdx};
        targetOutput = result.targetEstimate{sampleIdx};
        egoPosition(sampleIdx, :) = ...
            egoOutput.egoState([1, 4]).';
        egoYaw(sampleIdx) = egoOutput.egoYaw;
        egoSpeed(sampleIdx) = norm(egoOutput.egoState([2, 5]));
        if ~isempty(targetOutput)
            targetEstimateAvailable(sampleIdx) = true;
            targetPosition(sampleIdx, :) = ...
                targetOutput.targetPositionInertial(:).';
            targetVelocity = ...
                targetOutput.targetVelocityInertial(:);
            if norm(targetVelocity) > 100.0*eps
                targetYaw(sampleIdx) = atan2( ...
                    targetVelocity(2), targetVelocity(1));
            elseif sampleIdx > 1
                targetYaw(sampleIdx) = targetYaw(sampleIdx-1);
            end
        end
        frame = result.estimator.sensorFrame{sampleIdx};
        radarDetected(sampleIdx) = logical( ...
            frame.radarDetectionAvailable);
        if radarDetected(sampleIdx)
            rotation = localRotation(egoOutput.egoYaw);
            radarTargetPosition(sampleIdx, :) = ...
                (egoOutput.egoState([1, 4]) ...
                    + rotation ...
                        * frame.radarRelativePosition(:)).';
        end
    end
    targetYaw = localUnwrapFinite(targetYaw);
    frameRadarDetected = logical(localPreviousInterpolation( ...
        sampleTime, double(radarDetected), frameTime));
    firstDetectionIdx = find(radarDetected, 1, "first");
    if isempty(firstDetectionIdx)
        firstDetectionTime = NaN;
    else
        firstDetectionTime = sampleTime(firstDetectionIdx);
    end

    estimate = struct( ...
        "egoPosition", localLinearInterpolation( ...
            sampleTime, egoPosition, frameTime), ...
        "egoYaw", localLinearInterpolation( ...
            sampleTime, unwrap(egoYaw), frameTime), ...
        "egoSpeed", localLinearInterpolation( ...
            sampleTime, egoSpeed, frameTime), ...
        "targetPosition", localLinearInterpolation( ...
            sampleTime, targetPosition, frameTime), ...
        "targetYaw", localLinearInterpolation( ...
            sampleTime, targetYaw, frameTime), ...
        "targetEstimateAvailable", ...
            logical(localPreviousInterpolation( ...
                sampleTime, double(targetEstimateAvailable), ...
                frameTime)), ...
        "radarTargetPosition", localPreviousInterpolation( ...
            sampleTime, radarTargetPosition, frameTime), ...
        "radarDetected", frameRadarDetected, ...
        "firstDetectionTime", firstDetectionTime);
end

function value = localUnwrapFinite(value)
    finiteIdx = find(isfinite(value));
    if ~isempty(finiteIdx)
        value(finiteIdx) = unwrap(value(finiteIdx));
    end
end

function value = localLinearInterpolation(sampleTime, sampleValue, queryTime)
    sampleTime = sampleTime(:);
    value = interp1(sampleTime, sampleValue, queryTime, ...
        "linear", "extrap");
end

function value = localPreviousInterpolation(sampleTime, sampleValue, queryTime)
    sampleTime = sampleTime(:);
    value = interp1(sampleTime, sampleValue, queryTime, ...
        "previous", "extrap");
end

function input = localInputSignals(result)
    sampleCount = min(numel(result.command), numel(result.controlTime)-1);
    sampleTime = result.controlTime(1:sampleCount);
    frontAxleTorque = cellfun( ...
        @(value) value.frontAxleTorque, result.command(1:sampleCount));
    steeringAngle = cellfun( ...
        @(value) value.frontWheelSteeringAngle, ...
        result.command(1:sampleCount));
    input = struct( ...
        "time", sampleTime, ...
        "frontAxleTorque", frontAxleTorque(:), ...
        "steeringAngle", steeringAngle(:));
end

function perception = localPerceptionSignals(result, frameTime)
    fit = result.perception.roadBoundaryFit;
    sampleCount = min(numel(fit), numel(result.controlTime)-1);
    sampleTime = result.controlTime(1:sampleCount);
    stepIndex = ones(size(frameTime));
    timeTolerance = 100.0*eps(max(1.0, max(frameTime)));
    for frameIdx = 1:numel(frameTime)
        previousIdx = find(sampleTime <= ...
            frameTime(frameIdx)+timeTolerance, 1, "last");
        if ~isempty(previousIdx)
            stepIndex(frameIdx) = previousIdx;
        end
    end

    boundaryCount = 0;
    maximumSourcePointRange = 0.0;
    maximumRenderedFitRange = 0.0;
    for sampleIdx = 1:sampleCount
        currentPerception = fit{sampleIdx};
        boundaries = currentPerception.roadGeometry.boundaries;
        if numel(boundaries) ~= 2
            error("renderEstimatedStateAvoidanceVideo:" ...
                + "invalidRoadBoundaryCount", ...
                "Each road-perception sample must contain " ...
                    + "right and left boundaries.");
        end
        boundaryCount = max(boundaryCount, numel(boundaries));
        for boundaryIdx = 1:numel(boundaries)
            boundary = boundaries(boundaryIdx);
            maximumSourcePointRange = max( ...
                maximumSourcePointRange, ...
                max(boundary.sourcePointRange));
            fitPoint = localBoundaryFitPoints( ...
                currentPerception, boundary);
            finitePoint = all(isfinite(fitPoint), 2);
            if any(finitePoint)
                fitRange = vecnorm( ...
                    fitPoint(finitePoint, :) ...
                        - currentPerception.egoPose(1:2).', ...
                    2, 2);
                maximumRenderedFitRange = max( ...
                    maximumRenderedFitRange, max(fitRange));
            end
        end
    end

    perception = struct( ...
        "stepIndex", stepIndex, ...
        "rangeMaximum", result.perception.rangeMaximum, ...
        "boundaryCount", boundaryCount, ...
        "maximumSourcePointRange", maximumSourcePointRange, ...
        "maximumRenderedFitRange", maximumRenderedFitRange);
end

function roadMargin = localRoadMarginSignal( ...
        result, sourceTime, finiteMask, uniqueIdx, frameTime)
    margin = result.roadSafety ...
        .conservativeBoundaryFunctionMargin;
    if size(margin, 1) ~= numel(result.plantTrace.time)
        error("renderEstimatedStateAvoidanceVideo:" ...
            + "inconsistentRoadSafety", ...
            "Road margins must align with the plant trace.");
    end
    margin = min(margin(finiteMask, :), [], 2);
    roadMargin = interp1(sourceTime, margin(uniqueIdx), ...
        frameTime, "linear", "extrap");
end

function [figureHandle, graphics] = localCreateFigure( ...
        result, data, options)
    visibility = "off";
    if options.figureVisible
        visibility = "on";
    end
    figureHandle = figure( ...
        Name="Estimator-in-the-loop avoidance visualization", ...
        NumberTitle="off", ...
        Color="w", ...
        Visible=visibility, ...
        MenuBar="none", ...
        ToolBar="none", ...
        Resize="off", ...
        Position=[40, 40, 1280, 720]);
    layout = tiledlayout(figureHandle, 3, 4, ...
        TileSpacing="compact", Padding="compact");

    trajectoryAxes = nexttile(layout, 1, [3, 3]);
    hold(trajectoryAxes, "on");
    grid(trajectoryAxes, "on");
    axis(trajectoryAxes, "equal");
    roadGraphics = localDrawRoad( ...
        trajectoryAxes, result.scenario.centerline, ...
        result.perception.roadBoundaryOffsets, ...
        result.perception.roadShoulderWidth);
    perceptionRangeArea = patch(trajectoryAxes, NaN, NaN, ...
        [0.20, 0.70, 0.90], EdgeColor="none", ...
        FaceAlpha=0.07, HandleVisibility="off");
    perceptionRange = plot(trajectoryAxes, NaN, NaN, ...
        Color=[0.00, 0.55, 0.75], LineStyle="--", ...
        LineWidth=1.5, ...
        DisplayName=compose("%.0f m perception range", ...
            result.perception.rangeMaximum));
    centerline = plot(trajectoryAxes, ...
        result.scenario.centerline(:, 1), ...
        result.scenario.centerline(:, 2), ...
        "k--", LineWidth=1.1, DisplayName="Centerline");
    rightBoundaryFit = plot(trajectoryAxes, NaN, NaN, ...
        Color=[0.10, 0.60, 0.20], LineWidth=2.5, ...
        DisplayName="Sensed right outer curb");
    leftBoundaryFit = plot(trajectoryAxes, NaN, NaN, ...
        Color=[0.80, 0.18, 0.18], LineWidth=2.5, ...
        DisplayName="Sensed left outer curb");
    rightBoundarySamples = plot(trajectoryAxes, NaN, NaN, ...
        ".", Color=[0.05, 0.35, 0.10], MarkerSize=7, ...
        HandleVisibility="off");
    leftBoundarySamples = plot(trajectoryAxes, NaN, NaN, ...
        ".", Color=[0.50, 0.06, 0.06], MarkerSize=7, ...
        HandleVisibility="off");
    perceptionRangeLabel = text(trajectoryAxes, NaN, NaN, "", ...
        HorizontalAlignment="center", ...
        VerticalAlignment="bottom", FontSize=8, ...
        FontWeight="bold", Color=[0.00, 0.35, 0.50], ...
        BackgroundColor="w", Margin=2, ...
        HandleVisibility="off");
    baseline = plot(trajectoryAxes, ...
        result.baseline.egoPosition(:, 1), ...
        result.baseline.egoPosition(:, 2), ...
        Color=[0.55, 0.55, 0.55], ...
        LineStyle=":", LineWidth=1.2, ...
        DisplayName="No-avoidance baseline");
    targetPlan = plot(trajectoryAxes, ...
        data.target.position(:, 1), data.target.position(:, 2), ...
        Color=[0.85, 0.33, 0.10], ...
        LineStyle="--", LineWidth=1.0, ...
        DisplayName="Target truth path");
    egoTrail = plot(trajectoryAxes, NaN, NaN, ...
        Color=[0.00, 0.45, 0.74], LineWidth=2.3, ...
        DisplayName="Ego truth");
    targetTrail = plot(trajectoryAxes, NaN, NaN, ...
        Color=[0.85, 0.33, 0.10], LineWidth=2.0, ...
        DisplayName="Target truth");
    egoEstimateTrail = plot(trajectoryAxes, NaN, NaN, ...
        Color=[0.00, 0.72, 0.72], LineStyle=":", ...
        LineWidth=1.5, DisplayName="Ego estimate");
    targetEstimateTrail = plot(trajectoryAxes, NaN, NaN, ...
        Color=[0.64, 0.08, 0.75], LineStyle=":", ...
        LineWidth=1.5, DisplayName="Target estimate");
    egoPatch = patch(trajectoryAxes, NaN, NaN, ...
        [0.10, 0.55, 0.95], EdgeColor=[0.00, 0.18, 0.42], ...
        FaceAlpha=0.88, LineWidth=1.5, HandleVisibility="off");
    targetPatch = patch(trajectoryAxes, NaN, NaN, ...
        [0.95, 0.45, 0.10], EdgeColor=[0.45, 0.12, 0.02], ...
        FaceAlpha=0.88, LineWidth=1.5, HandleVisibility="off");
    egoNose = plot(trajectoryAxes, NaN, NaN, ...
        "k-", LineWidth=1.8, HandleVisibility="off");
    targetNose = plot(trajectoryAxes, NaN, NaN, ...
        "k-", LineWidth=1.8, HandleVisibility="off");
    egoEstimateMarker = plot(trajectoryAxes, NaN, NaN, ...
        "+", Color=[0.00, 0.72, 0.72], MarkerSize=10, ...
        LineWidth=2.0, HandleVisibility="off");
    targetEstimateMarker = plot(trajectoryAxes, NaN, NaN, ...
