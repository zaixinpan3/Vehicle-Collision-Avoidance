function dataset = localPlantInputDataset( ...
        command, intervalStart, intervalEnd, adapter)
    time = [intervalStart; intervalEnd];
    wheelAngle = [ ...
        adapter.steeringAngleSign ...
            * command.frontWheelSteeringAngle * ones(2, 1); ...
        0.0; 0.0];
    % command.axleLongitudinalForce = beta*[mu_f*Fzf; mu_r*Fzr].
    % Apply the common signed ratio to both axles through drive/brake torque.
    wheelForce = 0.5*command.axleLongitudinalForce([1; 1; 2; 2]);
    axleTorque = max(wheelForce, 0.0) ...
        .* adapter.forceToTorqueRadius;
    brakeTorque = max(-wheelForce, 0.0) ...
        .* adapter.forceToTorqueRadius;
    brakePressure = brakeTorque ...
        / adapter.brakeTorquePerPressure;

    directionCosineMatrix = zeros(3, 3, 4, 2);
    for sampleIdx = 1:2
        for wheelIdx = 1:4
            directionCosineMatrix(:, :, wheelIdx, sampleIdx) = eye(3);
        end
    end

    portNames = [ ...
        "WhlAng", "AxlTrq", "BrkPrs", "WindXYZ", ...
        "Ground", "Friction", "DCM"];
    portData = { ...
        repmat(wheelAngle.', 2, 1), ...
        repmat(axleTorque.', 2, 1), ...
        repmat(brakePressure.', 2, 1), ...
        zeros(2, 3), ...
        zeros(2, 4), ...
        ones(2, 4), ...
        directionCosineMatrix};

    dataset = Simulink.SimulationData.Dataset;
    for portIdx = 1:numel(portNames)
        signal = Simulink.SimulationData.Signal;
        signal.Name = portNames(portIdx);
        signal.Values = timeseries(portData{portIdx}, time);
        dataset = dataset.addElement(signal, portNames(portIdx));
    end
end

