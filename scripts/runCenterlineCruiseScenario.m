function [metrics, tracking] = localMetrics( ...
        controlState, command, failure, ...
        completedStepCount, requestedStepCount, ...
        terminalTaskCompleted, referenceSpeed, ...
        centerline, criteria, solveTime, sampleTime)
    speedError = controlState(:, 4) - referenceSpeed;
    tracking = localCenterlineTracking(controlState, centerline);
    lateralError = tracking.lateralError;
    headingError = tracking.headingError;
    controllerCompleted = ( ...
        completedStepCount == requestedStepCount ...
        || terminalTaskCompleted) ...
        && ~failure.occurred;

    if isempty(command)
        firstFrontAxleForce = NaN;
        firstLongitudinalAcceleration = NaN;
        meanFrontWheelSteeringAngle = NaN;
    else
        firstFrontAxleForce = command{1}.axleLongitudinalForce(1);
        firstLongitudinalAcceleration = ...
            command{1}.longitudinalAcceleration;
        meanFrontWheelSteeringAngle = mean(cellfun( ...
            @(value) value.frontWheelSteeringAngle, command));
    end
    speedWithinTolerance = max(abs(speedError)) ...
        <= criteria.maximumAbsoluteSpeedError;
    lateralWithinTolerance = max(abs(lateralError)) ...
        <= criteria.maximumAbsoluteLateralError;
    headingWithinTolerance = max(abs(headingError)) ...
        <= criteria.maximumAbsoluteHeadingError;

    metrics = struct();
    metrics.requestedControlSteps = requestedStepCount;
    metrics.completedControlSteps = completedStepCount;
    metrics.terminalTaskCompleted = terminalTaskCompleted;
    metrics.controllerCompletedScenario = controllerCompleted;
    metrics.maximumAbsoluteSpeedError = max(abs(speedError));
    metrics.finalSpeedError = speedError(end);
    metrics.maximumAbsoluteLateralError = ...
        max(abs(lateralError));
    metrics.finalLateralError = lateralError(end);
    metrics.maximumAbsoluteLateralPosition = ...
        metrics.maximumAbsoluteLateralError;
    metrics.maximumAbsoluteHeadingError = max(abs(headingError));
    metrics.finalHeadingError = headingError(end);
    metrics.centerlineDistanceTravelled = ...
        tracking.distanceAlongCenterline(end) ...
        - tracking.distanceAlongCenterline(1);
    metrics.meanFrontWheelSteeringAngle = ...
        meanFrontWheelSteeringAngle;
    metrics.speedWithinTolerance = speedWithinTolerance;
    metrics.lateralWithinTolerance = lateralWithinTolerance;
    metrics.headingWithinTolerance = headingWithinTolerance;
    metrics.firstFrontAxleForce = firstFrontAxleForce;
    metrics.firstLongitudinalAcceleration = ...
        firstLongitudinalAcceleration;
    if isempty(solveTime)
        metrics.meanSolveTime = NaN;
        metrics.maximumSolveTime = NaN;
        metrics.solveDeadlineMetEveryStep = false;
    else
        metrics.meanSolveTime = mean(solveTime);
        metrics.maximumSolveTime = max(solveTime);
        metrics.solveDeadlineMetEveryStep = all(solveTime <= sampleTime);
    end
    metrics.cruiseMaintained = controllerCompleted ...
        && speedWithinTolerance ...
        && lateralWithinTolerance ...
        && headingWithinTolerance;
end

function tracking = localCenterlineTracking(controlState, centerline)
    segment = diff(centerline, 1, 1);
    segmentLength = vecnorm(segment, 2, 2);
    segmentLengthSquared = segmentLength.^2;
    cumulativeLength = [0.0; cumsum(segmentLength)];
    stateCount = size(controlState, 1);

    projectedPosition = NaN(stateCount, 2);
    referenceHeading = NaN(stateCount, 1);
    lateralError = NaN(stateCount, 1);
    headingError = NaN(stateCount, 1);
    distanceAlongCenterline = NaN(stateCount, 1);

    for stateIdx = 1:stateCount
        position = controlState(stateIdx, 1:2);
        relativePosition = position - centerline(1:(end - 1), :);
        fraction = sum(relativePosition .* segment, 2) ...
            ./ segmentLengthSquared;
        fraction = min(max(fraction, 0.0), 1.0);
        projection = centerline(1:(end - 1), :) ...
            + fraction .* segment;
        distanceSquared = sum((position - projection).^2, 2);
        [~, segmentIdx] = min(distanceSquared);

        tangent = segment(segmentIdx, :) ...
            / segmentLength(segmentIdx);
        offset = position - projection(segmentIdx, :);
        projectedPosition(stateIdx, :) = ...
            projection(segmentIdx, :);
        referenceHeading(stateIdx) = atan2(tangent(2), tangent(1));
        lateralError(stateIdx) = ...
            tangent(1) * offset(2) - tangent(2) * offset(1);
        headingDifference = controlState(stateIdx, 3) ...
            - referenceHeading(stateIdx);
        headingError(stateIdx) = atan2( ...
            sin(headingDifference), cos(headingDifference));
        distanceAlongCenterline(stateIdx) = ...
            cumulativeLength(segmentIdx) ...
            + fraction(segmentIdx) * segmentLength(segmentIdx);
    end

    tracking = struct();
    tracking.projectedPosition = projectedPosition;
    tracking.referenceHeading = referenceHeading;
    tracking.lateralError = lateralError;
    tracking.headingError = headingError;
    tracking.distanceAlongCenterline = distanceAlongCenterline;
end

function localReport(result)
    metrics = result.metrics;
    fprintf("\n%s\n", result.scenario.description);
    fprintf("  Plant: %s\n", result.plant.source);
    fprintf("  Reference speed: %.3f m/s\n", ...
        result.scenario.referenceSpeed);
    fprintf("  Completed controller steps: %d / %d\n", ...
        metrics.completedControlSteps, metrics.requestedControlSteps);
    fprintf("  Mean / maximum solve time: %.6f / %.6f s\n", ...
        metrics.meanSolveTime, metrics.maximumSolveTime);
    fprintf("  Maximum absolute speed error: %.6f m/s\n", ...
        metrics.maximumAbsoluteSpeedError);
    fprintf("  Maximum absolute lateral tracking error: %.6f m\n", ...
        metrics.maximumAbsoluteLateralError);
    fprintf("  Maximum absolute heading error: %.6f rad\n", ...
        metrics.maximumAbsoluteHeadingError);
    fprintf("  First front-axle longitudinal force: %.6f N\n", ...
        metrics.firstFrontAxleForce);
    fprintf("  First predicted longitudinal acceleration: %.6f m/s^2\n", ...
        metrics.firstLongitudinalAcceleration);
    if result.failure.occurred
        fprintf("  Controller failure at t = %.3f s: %s\n", ...
            result.failure.time, result.failure.identifier);
        fprintf("  Failure message: %s\n", result.failure.message);
    end
    if result.passed
        fprintf("  Result: PASS\n\n");
    else
        fprintf("  Result: FAIL\n\n");
    end
end

