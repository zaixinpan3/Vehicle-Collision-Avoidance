function result = ...
        runCircularCenterlineStraightTargetAvoidanceScenario(varargin)
% runCircularCenterlineStraightTargetAvoidanceScenario Test avoidance on an arc.
%
% The ego nominally cruises at constant speed on a left circular
% centerline. The target moves at constant speed on a straight line tangent
% to the centerline. Its initial position is constructed so that the target
% and nominal ego centers coincide at the nominal collision time. Thus the
% no-avoidance trajectory is geometrically guaranteed to collide.

    options = localOptions(varargin{:});
    [centerline, centerlineGeometry] = ...
        circularCenterlinePolyline(options);
    collisionGeometry = localCollisionGeometry( ...
        centerline, options);
    targetStateFunction = @(time, egoState) ...
        localTargetState(time, egoState, ...
            collisionGeometry, options);
    geometry = centerlineGeometry;
    geometry.type = "circularArcStraightTargetCollision";
    geometry.targetMotion = "constantVelocityStraightLine";
    geometry.targetInitialDistance = ...
        collisionGeometry.targetInitialDistance;
    geometry.targetInitialPosition = ...
        collisionGeometry.targetInitialPosition;
    geometry.targetVelocity = collisionGeometry.targetVelocity;
    geometry.nominalCollisionTime = ...
        collisionGeometry.nominalCollisionTime;
    geometry.nominalCollisionPosition = ...
        collisionGeometry.nominalCollisionPosition;
    geometry.nominalTargetCollisionPosition = ...
        collisionGeometry.nominalTargetCollisionPosition;
    geometry.nominalCollisionHeading = ...
        collisionGeometry.nominalCollisionHeading;
    geometry.targetCollisionLateralOffset = ...
        options.targetCollisionLateralOffset;
    geometry.perceptionRange = options.perceptionRange;
    geometry.rightRoadBoundaryOffset = ...
        options.rightRoadBoundaryOffset;
    geometry.leftRoadBoundaryOffset = ...
        options.leftRoadBoundaryOffset;
    geometry.roadShoulderWidth = options.roadShoulderWidth;

    description = sprintf( ...
        "Left circular centerline (R = %.1f m) with a straight-line " ...
        + "target constructed to collide at t = %.3f s", ...
        options.radius, collisionGeometry.nominalCollisionTime);
    result = runCenterlineCruiseScenario( ...
        Centerline=centerline, ...
        InitialPosition=[0.0; 0.0], ...
        InitialYaw=0.0, ...
        InitialLateralVelocity=0.0, ...
        InitialYawRate=options.referenceSpeed / options.radius, ...
        Description=description, ...
        Geometry=geometry, ...
        Duration=options.duration, ...
        ReferenceSpeed=options.referenceSpeed, ...
        TargetStateFunction=targetStateFunction, ...
        UseStateEstimator=options.useStateEstimator, ...
        EstimatorConfiguration=options.estimatorConfiguration, ...
        PerceptionRange=options.perceptionRange, ...
        RoadBoundaryOffsets=[ ...
            options.rightRoadBoundaryOffset; ...
            options.leftRoadBoundaryOffset], ...
        RoadShoulderWidth=options.roadShoulderWidth, ...
        EgoCollisionSize=[ ...
            options.egoLength; options.egoWidth], ...
        TargetCollisionSize=[ ...
            options.targetLength; options.targetWidth], ...
        SpeedTolerance=options.recoverySpeedTolerance, ...
        LateralTolerance=options.recoveryLateralTolerance, ...
        HeadingTolerance=options.recoveryHeadingTolerance, ...
        Plot=false, ...
        Report=false, ...
        Progress=options.progress);

    result = localAvoidanceEvaluation( ...
        result, centerline, collisionGeometry, options);
    if options.report
        localReport(result);
    end
    if options.plot
        localPlot(result);
    end
end

