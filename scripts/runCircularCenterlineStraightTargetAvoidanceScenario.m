function length = localCenterlineLength(centerline)
    length = sum(vecnorm(diff(centerline, 1, 1), 2, 2));
end

function abscissa = localProjectToCenterline(position, centerline)
    segment = diff(centerline, 1, 1);
    segmentLength = vecnorm(segment, 2, 2);
    segmentLengthSquared = segmentLength.^2;
    relativePosition = position - centerline(1:(end - 1), :);
    fraction = sum(relativePosition .* segment, 2) ...
        ./ segmentLengthSquared;
    fraction = min(max(fraction, 0.0), 1.0);
    projection = centerline(1:(end - 1), :) ...
        + fraction .* segment;
    distanceSquared = sum((position - projection).^2, 2);
    [~, segmentIdx] = min(distanceSquared);
    cumulativeLength = [0.0; cumsum(segmentLength)];
    abscissa = cumulativeLength(segmentIdx) ...
        + fraction(segmentIdx) * segmentLength(segmentIdx);
end

function [position, heading] = ...
        localCenterlinePose(centerline, abscissa)
    segment = diff(centerline, 1, 1);
    segmentLength = vecnorm(segment, 2, 2);
    cumulativeLength = [0.0; cumsum(segmentLength)];
    queryAbscissa = abscissa(:);
    if any(queryAbscissa < 0.0) ...
            || any(queryAbscissa > cumulativeLength(end))
        error( ...
            "runCircularCenterlineStraightTargetAvoidanceScenario:" ...
            + "centerlineQueryOutsideDomain", ...
            "A requested nominal pose lies outside the centerline.");
    end

    position = NaN(numel(queryAbscissa), 2);
    heading = NaN(numel(queryAbscissa), 1);
    for queryIdx = 1:numel(queryAbscissa)
        segmentIdx = find( ...
            cumulativeLength <= queryAbscissa(queryIdx), ...
            1, "last");
        if segmentIdx == numel(cumulativeLength)
            segmentIdx = numel(segmentLength);
            fraction = 1.0;
        else
            fraction = (queryAbscissa(queryIdx) ...
                - cumulativeLength(segmentIdx)) ...
                / segmentLength(segmentIdx);
        end
        tangent = segment(segmentIdx, :) ...
            / segmentLength(segmentIdx);
        position(queryIdx, :) = centerline(segmentIdx, :) ...
            + fraction * segment(segmentIdx, :);
        heading(queryIdx) = atan2(tangent(2), tangent(1));
    end
    if isscalar(abscissa)
        position = position(1, :);
        heading = heading(1);
    end
end

function tracking = localCenterlineTracking(state, centerline)
    segment = diff(centerline, 1, 1);
    segmentLength = vecnorm(segment, 2, 2);
    segmentLengthSquared = segmentLength.^2;
    stateCount = size(state, 1);
    lateralError = NaN(stateCount, 1);
    headingError = NaN(stateCount, 1);

    for stateIdx = 1:stateCount
        position = state(stateIdx, 1:2);
        relativePosition = position ...
            - centerline(1:(end - 1), :);
        fraction = sum(relativePosition .* segment, 2) ...
            ./ segmentLengthSquared;
        fraction = min(max(fraction, 0.0), 1.0);
        projection = centerline(1:(end - 1), :) ...
            + fraction .* segment;
        distanceSquared = sum( ...
            (position - projection).^2, 2);
        [~, segmentIdx] = min(distanceSquared);
        tangent = segment(segmentIdx, :) ...
            / segmentLength(segmentIdx);
        offset = position - projection(segmentIdx, :);
        lateralError(stateIdx) = ...
            tangent(1) * offset(2) ...
            - tangent(2) * offset(1);
        referenceHeading = ...
            atan2(tangent(2), tangent(1));
        headingDifference = ...
            state(stateIdx, 3) - referenceHeading;
        headingError(stateIdx) = atan2( ...
            sin(headingDifference), cos(headingDifference));
    end
    tracking = struct( ...
        "lateralError", lateralError, ...
        "headingError", headingError);
end

function localReport(result)
    metrics = result.avoidance;
    fprintf("\n%s\n", result.scenario.description);
    fprintf("  Perception/control sample time: %.3f s\n", ...
        result.scenario.sampleTime);
    fprintf("  Target initial distance: %.6f m\n", ...
        metrics.targetInitialDistance);
    fprintf("  Constructed nominal collision time: %.6f s\n", ...
        metrics.nominalCollisionTime);
    fprintf("  Collision construction error: %.12g m\n", ...
        metrics.collisionConstructionError);
    fprintf("  Nominal collision SAT margin: %.6f m\n", ...
        metrics.nominalCollisionSeparatingAxisMargin);
    fprintf("  Baseline minimum SAT margin: %.6f m\n", ...
        metrics.minimumBaselineSeparatingAxisMargin);
    fprintf("  Controlled minimum SAT margin: %.6f m\n", ...
        metrics.minimumControlledSeparatingAxisMargin);
    fprintf("  Passing time / ego speed: %.3f s / %.3f m/s\n", ...
        metrics.passingTime, metrics.egoSpeedAtPassing);
    fprintf("  Minimum ego longitudinal speed: %.3f m/s\n", ...
        metrics.minimumEgoLongitudinalSpeed);
    fprintf("  Final-window maximum speed/lateral/heading errors: " ...
        + "%.6f m/s, %.6f m, %.6f rad\n", ...
        metrics.maximumRecoverySpeedError, ...
        metrics.maximumRecoveryLateralError, ...
        metrics.maximumRecoveryHeadingError);
    fprintf("  Mean / maximum solve time: %.6f / %.6f s\n", ...
        result.metrics.meanSolveTime, ...
        result.metrics.maximumSolveTime);
    if result.passed
        fprintf("  Result: PASS\n\n");
    else
        fprintf("  Result: FAIL\n\n");
    end
end

function localPlot(result)
    figure(Name=result.scenario.description);
    tiledlayout(2, 1);

    nexttile;
    plot(result.plantTrace.positionX, ...
        result.plantTrace.positionY, LineWidth=1.5);
    hold on;
    plot(result.targetTruth.position(:, 1), ...
        result.targetTruth.position(:, 2), LineWidth=1.5);
    plot(result.scenario.centerline(:, 1), ...
        result.scenario.centerline(:, 2), "k--");
    plot(result.baseline.egoPosition(:, 1), ...
        result.baseline.egoPosition(:, 2), ...
        Color=[0.6, 0.6, 0.6], LineStyle=":");
    grid on;
    axis equal;
    xlabel("Inertial x (m)");
    ylabel("Inertial y (m)");
