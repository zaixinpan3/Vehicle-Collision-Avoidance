function geometry = localCollisionGeometry(centerline, options)
    initialPosition = [0.0, 0.0];
    initialAbscissa = localProjectToCenterline( ...
        initialPosition, centerline);
    centerlineLength = localCenterlineLength(centerline);
    maximumCollisionTime = ...
        (centerlineLength - initialAbscissa) ...
        / options.referenceSpeed;
    residual = @(time) localInitialDistanceResidual( ...
        time, initialAbscissa, centerline, options);

    lowerTime = 0.0;
    upperTime = min(maximumCollisionTime, ...
        2.0 * options.targetInitialDistance ...
        / (options.referenceSpeed + options.targetSpeed));
    while residual(upperTime) < 0.0 ...
            && upperTime < maximumCollisionTime
        upperTime = min(maximumCollisionTime, ...
            max(upperTime + 0.5, 1.5 * upperTime));
    end
    if residual(upperTime) < 0.0
        error( ...
            "runCircularCenterlineStraightTargetAvoidanceScenario:" ...
            + "centerlineTooShort", ...
            "ArcLengthAfter is too short to construct the collision.");
    end
    collisionTime = fzero(residual, [lowerTime, upperTime]);
    collisionAbscissa = initialAbscissa ...
        + options.referenceSpeed * collisionTime;
    [collisionPosition, collisionHeading] = ...
        localCenterlinePose(centerline, collisionAbscissa);
    tangent = [cos(collisionHeading); sin(collisionHeading)];
    normal = [-tangent(2); tangent(1)];
    targetDirection = -tangent;
    targetVelocity = options.targetSpeed * targetDirection;
    targetCollisionPosition = collisionPosition.' ...
        + options.targetCollisionLateralOffset * normal;
    targetInitialPosition = targetCollisionPosition ...
        - collisionTime * targetVelocity;

    geometry = struct( ...
        "initialCenterlineAbscissa", initialAbscissa, ...
        "nominalCollisionTime", collisionTime, ...
        "nominalCollisionPosition", collisionPosition, ...
        "nominalTargetCollisionPosition", ...
            targetCollisionPosition, ...
        "nominalCollisionHeading", collisionHeading, ...
        "collisionTangent", tangent, ...
        "targetInitialPosition", targetInitialPosition, ...
        "targetVelocity", targetVelocity, ...
        "targetYaw", atan2(targetVelocity(2), targetVelocity(1)), ...
        "targetInitialDistance", ...
            norm(targetInitialPosition - initialPosition.'));
end

function residual = localInitialDistanceResidual( ...
        time, initialAbscissa, centerline, options)
    abscissa = initialAbscissa ...
        + options.referenceSpeed * time;
    [position, heading] = localCenterlinePose( ...
        centerline, abscissa);
    tangent = [cos(heading); sin(heading)];
    normal = [-tangent(2); tangent(1)];
    targetInitialPosition = position.' ...
        + options.targetCollisionLateralOffset * normal ...
        + options.targetSpeed * time * tangent;
    residual = norm(targetInitialPosition) ...
        - options.targetInitialDistance;
end

function target = localTargetState( ...
        time, ~, geometry, options)
    targetPosition = geometry.targetInitialPosition ...
        + geometry.targetVelocity * time;
    target = struct( ...
        "targetPositionInertial", targetPosition, ...
        "targetVelocityInertial", geometry.targetVelocity, ...
        "targetAccelerationInertial", [0.0; 0.0], ...
        "targetYawInertial", geometry.targetYaw, ...
        "targetYawRate", 0.0, ...
        "targetLength", options.targetLength, ...
        "targetWidth", options.targetWidth);
end

function result = localAvoidanceEvaluation( ...
        result, centerline, geometry, options)
    sampleTimeTolerance = 100.0 * eps(max( ...
        1.0, result.scenario.sampleTime));
    if abs(result.scenario.sampleTime - 0.1) > sampleTimeTolerance
        error( ...
            "runCircularCenterlineStraightTargetAvoidanceScenario:" ...
            + "invalidSampleTime", ...
            "The perception and control sample time must be 0.1 s.");
    end

    traceTime = result.plantTrace.time;
    if isempty(traceTime)
        result.targetTruth = localEmptyTargetTruth(options);
        result.baseline = localEmptyBaseline();
        result.controlled = struct( ...
            "separatingAxisMargin", zeros(0, 1));
        result.avoidance = localEmptyAvoidance(geometry, options);
        result.passed = false;
        return;
    end

    targetPosition = geometry.targetInitialPosition.' ...
        + traceTime * geometry.targetVelocity.';
    targetYaw = geometry.targetYaw * ones(size(traceTime));
    egoPosition = [ ...
        result.plantTrace.positionX, ...
        result.plantTrace.positionY];
    egoYaw = result.plantTrace.yaw;
    vehicle = result.controllerConfiguration.vehicle;
    controlledMargin = rectangleSeparationMargin( ...
        egoPosition, egoYaw, targetPosition, targetYaw, ...
        vehicle.length, vehicle.width, ...
        options.targetLength, options.targetWidth);

    baselineAbscissa = geometry.initialCenterlineAbscissa ...
        + options.referenceSpeed * traceTime;
    [baselinePosition, baselineYaw] = ...
        localCenterlinePose(centerline, baselineAbscissa);
    baselineMargin = rectangleSeparationMargin( ...
        baselinePosition, baselineYaw, targetPosition, targetYaw, ...
        vehicle.length, vehicle.width, ...
        options.targetLength, options.targetWidth);

    collisionTargetPosition = ...
        geometry.targetInitialPosition ...
        + geometry.targetVelocity ...
            * geometry.nominalCollisionTime;
    constructionError = norm(collisionTargetPosition ...
        - geometry.nominalTargetCollisionPosition);
    nominalCollisionMargin = ...
        rectangleSeparationMargin( ...
            geometry.nominalCollisionPosition, ...
            geometry.nominalCollisionHeading, ...
            collisionTargetPosition.', geometry.targetYaw, ...
            vehicle.length, vehicle.width, ...
            options.targetLength, options.targetWidth);

    relativeApproachCoordinate = ...
        (targetPosition - egoPosition) ...
        * geometry.collisionTangent;
    passingIdx = find(relativeApproachCoordinate <= 0.0, 1);
    if isempty(passingIdx)
        passedTarget = false;
        passingTime = NaN;
        passingSpeed = NaN;
    else
        passedTarget = true;
        passingTime = traceTime(passingIdx);
        passingSpeed = ...
            result.plantTrace.longitudinalVelocity(passingIdx);
    end

    [minimumControlledMargin, closestIdx] = ...
        min(controlledMargin);
    minimumBaselineMargin = min(baselineMargin);
    trackingState = [egoPosition, egoYaw];
    tracking = localCenterlineTracking( ...
        trackingState, centerline);
    velocityCourse = egoYaw + atan2( ...
        result.plantTrace.lateralVelocity, ...
        result.plantTrace.longitudinalVelocity);
    courseTracking = localCenterlineTracking( ...
        [egoPosition, velocityCourse], centerline);
    recoveryStartTime = max(0.0, ...
        options.duration - options.recoveryWindow);
    recoveryMask = traceTime >= recoveryStartTime;
    recoverySpeedError = ...
        result.plantTrace.longitudinalVelocity(recoveryMask) ...
        - options.referenceSpeed;
    recoveryLateralError = ...
        tracking.lateralError(recoveryMask);
    recoveryCourseError = ...
        courseTracking.headingError(recoveryMask);
    recoveryBodyHeadingError = ...
        tracking.headingError(recoveryMask);
    recoveredCruise = ~isempty(recoverySpeedError) ...
        && max(abs(recoverySpeedError)) ...
            <= options.recoverySpeedTolerance ...
        && max(abs(recoveryLateralError)) ...
            <= options.recoveryLateralTolerance ...
        && max(abs(recoveryCourseError)) ...
            <= options.recoveryHeadingTolerance;
    collisionFree = minimumControlledMargin > 0.0;
    baselineCollides = minimumBaselineMargin < 0.0;
    minimumEgoLongitudinalSpeed = min( ...
        result.plantTrace.longitudinalVelocity);
    remainedMoving = minimumEgoLongitudinalSpeed > 0.0;
    constructionTolerance = 1000.0 * eps(max( ...
        1.0, norm(geometry.nominalCollisionPosition)));
    collisionConstructionExact = ...
        constructionError <= constructionTolerance;

    avoidance = struct( ...
        "targetInitialDistance", ...
            geometry.targetInitialDistance, ...
        "targetInitialPosition", ...
            geometry.targetInitialPosition, ...
        "targetVelocity", geometry.targetVelocity, ...
        "nominalCollisionTime", ...
            geometry.nominalCollisionTime, ...
        "nominalCollisionPosition", ...
            geometry.nominalCollisionPosition, ...
        "nominalTargetCollisionPosition", ...
            geometry.nominalTargetCollisionPosition, ...
        "targetCollisionLateralOffset", ...
            options.targetCollisionLateralOffset, ...
        "collisionConstructionError", constructionError, ...
        "collisionConstructionExact", ...
            collisionConstructionExact, ...
        "nominalCollisionSeparatingAxisMargin", ...
            nominalCollisionMargin, ...
        "minimumControlledSeparatingAxisMargin", ...
            minimumControlledMargin, ...
        "minimumBaselineSeparatingAxisMargin", ...
            minimumBaselineMargin, ...
        "baselineCollides", baselineCollides, ...
        "collisionFree", collisionFree, ...
        "closestApproachTime", traceTime(closestIdx), ...
        "passedTarget", passedTarget, ...
        "passingTime", passingTime, ...
        "egoSpeedAtPassing", passingSpeed, ...
        "minimumEgoLongitudinalSpeed", ...
            minimumEgoLongitudinalSpeed, ...
        "remainedMoving", remainedMoving, ...
        "noRoadBoundaryCrossing", ...
            result.roadSafety.noBoundaryCrossing, ...
        "minimumRoadBoundaryFunctionMargin", ...
            result.roadSafety.minimumBoundaryFunctionMargin, ...
        "minimumLateralTrackingError", ...
            min(tracking.lateralError), ...
        "maximumLateralTrackingError", ...
            max(tracking.lateralError), ...
        "recoveredCruise", recoveredCruise, ...
        "recoveryWindow", options.recoveryWindow, ...
        "maximumRecoverySpeedError", ...
            max(abs(recoverySpeedError)), ...
        "maximumRecoveryLateralError", ...
            max(abs(recoveryLateralError)), ...
        "recoveryOrientationMetric", ...
            "inertialVelocityCourseRelativeToCenterline", ...
        "maximumRecoveryHeadingError", ...
            max(abs(recoveryCourseError)), ...
        "maximumRecoveryBodyHeadingError", ...
            max(abs(recoveryBodyHeadingError)));

    result.targetTruth = struct( ...
        "time", traceTime, ...
        "position", targetPosition, ...
        "yaw", targetYaw, ...
        "length", options.targetLength, ...
        "width", options.targetWidth);
    result.baseline = struct( ...
        "egoPosition", baselinePosition, ...
        "egoYaw", baselineYaw, ...
        "separatingAxisMargin", baselineMargin);
    result.controlled = struct( ...
        "separatingAxisMargin", controlledMargin, ...
        "centerlineTracking", tracking);
    result.avoidance = avoidance;
    result.passed = ~result.failure.occurred ...
        && result.metrics.controllerCompletedScenario ...
        && collisionConstructionExact ...
        && baselineCollides ...
        && collisionFree ...
        && result.roadSafety.noBoundaryCrossing ...
        && passedTarget ...
        && remainedMoving ...
        && recoveredCruise;
end

