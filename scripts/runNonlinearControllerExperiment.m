function summaries = runNonlinearControllerExperiment(outputDirectory,options)
%runNonlinearControllerExperiment Direct NLP with the actual noisy observer.
% The plant and controller both use modified Fiala. The optimizer evaluates
% nonlinear shooting equations, rectangle rotations and the declared terminal
% continuation. Joint observer/feedback margins are frozen at each frame's
% reference. This is a numerical nonlinear baseline, not a robust certificate.
% An unlimited observation length ends only on recovery or a recorded failure.
% FrameBudgetSeconds is checked between SQP iterations; an internal QP or
% line search can overrun it. It is not a hard real-time execution deadline.
    arguments
        outputDirectory (1,1) string
        options.Scenarios (1,:) string = ["headOn","stoppedLead","intersectionCrossing","curvedCrossing"]
        options.Speeds (1,:) double = [8,25,8,8]
        options.Frames (1,1) double {mustBePositive} = Inf
        options.MaximumIterations (1,1) double {mustBePositive,mustBeInteger} = 200
        options.FrameBudgetSeconds (1,1) double {mustBePositive} = 300
    end
    assert(numel(options.Scenarios)==numel(options.Speeds));
    root=fileparts(fileparts(mfilename('fullpath')));
    addpath(fullfile(root,'controller'),fullfile(root,'config'),fullfile(root,'estimator'));
    if ~isfolder(outputDirectory),mkdir(outputDirectory);end
    summaries=struct([]);estimator=estimatorControllerIntegrationConfig();
    for k=1:numel(options.Scenarios)
        name=options.Scenarios(k);speed=options.Speeds(k);
        cfg=struct('referenceSpeed',speed,'model',struct('speedMaximum',max(18,1.2*speed)), ...
            'controller',struct('horizonSteps',8+8*(speed>=15),'retainedTube',false, ...
                'jointAffinePrediction',true,'jointNonlinearPrediction',false), ...
            'collision',struct('encounterRangeMeters',50), ...
            'solver',struct('method',"nonlinear",'timeLimitSeconds',options.FrameBudgetSeconds, ...
                'maxIterations',options.MaximumIterations));
        stem=fullfile(outputDirectory,sprintf('%g-%s',speed,name));
        fprintf('START nonlinear %g m/s %s\n',speed,name);
        result=runNonlinearPredictiveSafetyValidation(Scenarios=name,Frames=options.Frames, ...
            ControllerConfiguration=cfg,RequireCollisionThreat=true, ...
            RequireBrakingInsufficient=any(name==["headOn","acceleratingHeadOn","stoppedLead","hardBrakingLead"]), ...
            EstimatorConfiguration=estimator,OutputFile=stem+".json", ...
            FailureFile=stem+"-failure.mat",ContinuationFile=stem+".mat");
        r=result.results;
        entry=struct('scenario',name,'speedMetersPerSecond',speed,'outcome',r.outcome, ...
            'executedFrames',r.executedFrames,'failureTimeSeconds',r.failureTime, ...
            'recovered',r.recovery.recovered,'minimumClearanceMeters',r.minimumReplayClearanceMeters, ...
            'firstFrameSeconds',r.firstFrameSeconds,'medianLaterSeconds',r.subsequentMedianSeconds, ...
            'p95LaterSeconds',r.subsequentP95Seconds,'maximumFrameSeconds',r.maximumFrameSeconds, ...
            'failedFrameSeconds',r.failedFrameSeconds,'horizonSteps',r.maximumHorizonSteps, ...
            'deadlineMisses',r.deadlineMisses,'failure',r.failure);
        if isempty(summaries),summaries=entry;else,summaries(end+1)=entry;end %#ok<AGROW>
        file=fopen(fullfile(outputDirectory,'summary.json'),'w');assert(file>=0);
        fprintf(file,'%s\n',jsonencode(summaries,PrettyPrint=true));fclose(file);
        fprintf('RESULT nonlinear %g %s holds=%d gap=%.7g recovery=%d max=%.7g failure=%s\n', ...
            speed,name,r.executedFrames,r.minimumReplayClearanceMeters,r.recovery.recovered,r.maximumFrameSeconds,r.failure);
    end
end
