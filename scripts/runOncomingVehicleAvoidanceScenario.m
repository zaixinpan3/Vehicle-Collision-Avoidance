    avoidance = struct( ...
        "targetInitialLongitudinalDistance", ...
            options.targetInitialLongitudinalDistance, ...
        "targetLateralOffset", options.targetLateralOffset, ...
        "offsetBelowCombinedHalfWidths", false, ...
        "minimumControlledSeparatingAxisMargin", NaN, ...
        "minimumBaselineSeparatingAxisMargin", NaN, ...
        "baselineCollides", false, ...
        "collisionFree", false, ...
        "closestApproachTime", NaN, ...
        "passedTarget", false, ...
        "passingTime", NaN, ...
        "egoSpeedAtPassing", NaN, ...
        "minimumEgoLongitudinalSpeed", NaN, ...
        "remainedMoving", false, ...
        "noRoadBoundaryCrossing", false, ...
        "minimumRoadBoundaryFunctionMargin", NaN, ...
        "minimumEgoLateralPosition", NaN, ...
        "maximumEgoLateralPosition", NaN, ...
        "recoveredCruise", false, ...
        "recoveryWindow", options.recoveryWindow, ...
        "maximumRecoverySpeedError", NaN, ...
        "maximumRecoveryLateralError", NaN, ...
        "recoveryOrientationMetric", ...
            "inertialVelocityCourseRelativeToCenterline", ...
        "maximumRecoveryHeadingError", NaN, ...
        "maximumRecoveryBodyHeadingError", NaN);
end

function localReport(result)
    metrics = result.avoidance;
    fprintf("\n%s\n", result.scenario.description);
    fprintf("  Perception/control sample time: %.3f s\n", ...
        result.scenario.sampleTime);
    fprintf("  Complete online frame median / maximum / deadline: %.3f / %.3f / %.3f ms\n", ...
        1000*median(result.runtime.frameSeconds),1000*max(result.runtime.frameSeconds), ...
        1000*result.runtime.deadlineSeconds);
    fprintf("  Complete frame deadline met / enforced: %d / %d\n", ...
        result.runtime.deadlineMet,result.runtime.enforced);
    fprintf("  Target lateral offset: %.3f m\n", ...
        metrics.targetLateralOffset);
    fprintf("  No-control minimum SAT margin: %.6f m\n", ...
        metrics.minimumBaselineSeparatingAxisMargin);
    fprintf("  Controlled minimum SAT margin: %.6f m\n", ...
        metrics.minimumControlledSeparatingAxisMargin);
    fprintf("  Passing time / ego speed: %.3f s / %.3f m/s\n", ...
        metrics.passingTime, metrics.egoSpeedAtPassing);
    fprintf("  Minimum ego longitudinal speed: %.3f m/s\n", ...
        metrics.minimumEgoLongitudinalSpeed);
    fprintf("  Minimum ego lateral position: %.6f m\n", ...
        metrics.minimumEgoLateralPosition);
    fprintf("  Final-window maximum speed/lateral/heading errors: " ...
        + "%.6f m/s, %.6f m, %.6f rad\n", ...
        metrics.maximumRecoverySpeedError, ...
        metrics.maximumRecoveryLateralError, ...
        metrics.maximumRecoveryHeadingError);
    fprintf("  Mean / maximum solve time: %.6f / %.6f s\n", ...
        result.metrics.meanSolveTime, result.metrics.maximumSolveTime);
    if result.passed
        fprintf("  Result: PASS\n\n");
    else
        fprintf("  Result: FAIL\n\n");
    end
end

function localPlot(result)
    figure(Name=result.scenario.description);
    tiledlayout(2, 1);

    nexttile;
    plot(result.plantTrace.positionX, ...
        result.plantTrace.positionY, LineWidth=1.5);
    hold on;
    plot(result.targetTruth.position(:, 1), ...
        result.targetTruth.position(:, 2), LineWidth=1.5);
    plot(result.scenario.centerline(:, 1), ...
        result.scenario.centerline(:, 2), "k--");
    grid on;
    axis equal;
    xlabel("Inertial x (m)");
    ylabel("Inertial y (m)");
    legend("Ego CG", "Target CG", "Centerline", Location="best");

    nexttile;
    plot(result.plantTrace.time, ...
        result.plantTrace.longitudinalVelocity, LineWidth=1.5);
    hold on;
    yline(result.scenario.referenceSpeed, "k--");
    grid on;
    xlabel("Time (s)");
    ylabel("Ego longitudinal speed (m/s)");
    legend("Ego", "Reference", Location="best");
end

function valid = localPositiveScalar(value)
    valid = isnumeric(value) && isreal(value) && isscalar(value) ...
        && isfinite(value) && value > 0.0;
end

function valid = localFiniteScalar(value)
    valid = isnumeric(value) && isreal(value) && isscalar(value) ...
        && isfinite(value);
end

function valid = localLogicalScalar(value)
    valid = (islogical(value) || isnumeric(value)) ...
        && isscalar(value) && isfinite(value);
end

function valid = localScalarStruct(value)
    valid = isstruct(value) && isscalar(value);
end
