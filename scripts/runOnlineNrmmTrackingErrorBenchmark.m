        "maximumAuditedRelativePositionM", Inf);
end

function within = localTruthWithinDomain(truth, cfg)
% localTruthWithinDomain Sampled truth check against the certified domain.
%
% Evaluated directly from the configuration so it stays available when
% gain synthesis fails; the derived target yaw-rate and acceleration-norm
% bounds repeat the closed forms in synthesizeNrmmObserverGains.

    targetDomain = cfg.target.domain;
    targetYawRateMaximum = targetDomain.speedMaximum ...
        * sin(targetDomain.sideslipMaximum)/targetDomain.rearAxleDistance;
    targetAccelerationNormBound = hypot( ...
        targetDomain.scalarAccelerationMaximum, ...
        targetDomain.speedMaximum*targetYawRateMaximum);
    tolerance = 1.0e-9;
    within = ...
        all(truth.egoSpeed <= cfg.ego.domain.speedMaximum+tolerance) ...
        && all(abs(truth.egoYawRate) ...
            <= cfg.ego.domain.yawRateMaximum+tolerance) ...
        && all(abs(truth.egoSideslip) ...
            <= cfg.ego.yaw.sideslipDomainMaximum+tolerance) ...
        && all(abs(truth.egoSingleTrackMismatch) ...
            <= cfg.ego.yaw.singleTrackYawRateMismatchMaximum+tolerance) ...
        && all(truth.targetSpeed ...
            >= targetDomain.speedMinimum-tolerance) ...
        && all(truth.targetSpeed ...
            <= targetDomain.speedMaximum+tolerance) ...
        && all(abs(truth.targetYawRate) ...
            <= targetYawRateMaximum+tolerance) ...
        && all(vecnorm(truth.targetAcceleration, 2, 2) ...
            <= targetAccelerationNormBound+tolerance) ...
        && all(vecnorm(truth.targetTransformedState(:, 1:2), 2, 2) ...
            <= targetDomain.relativePositionMaximum+tolerance);
end

function value = localVectorRmse(error, evaluation)
    magnitude = vecnorm(error, 2, 2);
    value = sqrt(mean(magnitude(evaluation).^2));
end

function record = localTrialRecord( ...
        definition, seed, completed, failureIdentifier, metrics)
% localTrialRecord Case labels followed by every trial metric field.

    record = struct( ...
        "caseName", definition.name, ...
        "maneuver", definition.maneuver, ...
        "noise", definition.noise, ...
        "initialization", definition.initialization, ...
        "sampleRateHz", definition.sampleRateHz, ...
        "seed", seed, ...
        "completed", completed, ...
        "failureIdentifier", failureIdentifier);
    for fieldName = string(fieldnames(metrics)).'
        record.(fieldName) = metrics.(fieldName);
    end
end

function summary = localSummaryRecord(definition, records)
    successful = [records.completed] & [records.allEstimatesFinite];
    successfulRecords = records(successful);
    failedRecords = records(~[records.completed]);
    failureIdentifiers = strings(0, 1);
    if ~isempty(failedRecords)
        failureIdentifiers = unique([failedRecords.failureIdentifier]);
    end
    summary = struct( ...
        "caseName", definition.name, ...
        "maneuver", definition.maneuver, ...
        "noise", definition.noise, ...
        "initialization", definition.initialization, ...
        "sampleRateHz", definition.sampleRateHz, ...
        "runCount", numel(records), ...
        "completedRunCount", sum([records.completed]), ...
        "failedRunCount", sum(~[records.completed]), ...
        "failureIdentifiers", strjoin(failureIdentifiers, "; "), ...
        "truthWithinCertifiedDomain", ...
            all([records.truthWithinCertifiedDomain]), ...
        "egoPositionRmseMeanM", localMeanMetric( ...
            successfulRecords, "egoPositionRmseM"), ...
        "egoVelocityRmseMeanMps", localMeanMetric( ...
            successfulRecords, "egoVelocityRmseMps"), ...
        "egoAccelerationRmseMeanMps2", localMeanMetric( ...
            successfulRecords, "egoAccelerationRmseMps2"), ...
        "egoYawRmseMeanDeg", localMeanMetric( ...
            successfulRecords, "egoYawRmseDeg"), ...
        "relativePositionRmseMeanM", localMeanMetric( ...
            successfulRecords, "relativePositionRmseM"), ...
        "relativePositionRmseWorstM", localMaximumMetric( ...
            successfulRecords, "relativePositionRmseM"), ...
        "relativePositionPeakWorstM", localMaximumMetric( ...
            successfulRecords, "relativePositionPeakM"), ...
        "targetVelocityEgoRmseMeanMps", localMeanMetric( ...
            successfulRecords, "targetVelocityEgoRmseMps"), ...
        "targetAccelerationEgoRmseMeanMps2", localMeanMetric( ...
            successfulRecords, "targetAccelerationEgoRmseMps2"), ...
        "targetAccelerationEgoRmseWorstMps2", localMaximumMetric( ...
            successfulRecords, "targetAccelerationEgoRmseMps2"), ...
        "targetInertialPositionRmseMeanM", localMeanMetric( ...
            successfulRecords, "targetInertialPositionRmseM"), ...
        "minimumEstimatedTargetSpeedWorstMps", localMinimumMetric( ...
            successfulRecords, "minimumEstimatedTargetSpeedMps"), ...
        "speedDomainValidCumulativeAll", isempty(successfulRecords) ...
            || all([successfulRecords.targetSpeedDomainValidCumulative]), ...
        "speedDomainValidFinalIntervalAll", isempty(successfulRecords) ...
            || all([ ...
            successfulRecords.targetSpeedDomainValidFinalInterval]));
end

function value = localMeanMetric(records, fieldName)
    if isempty(records)
        value = Inf;
    else
        value = mean([records.(fieldName)]);
    end
end

function value = localMaximumMetric(records, fieldName)
    if isempty(records)
        value = Inf;
    else
        value = max([records.(fieldName)]);
    end
end

function value = localMinimumMetric(records, fieldName)
    if isempty(records)
        value = -Inf;
    else
        value = min([records.(fieldName)]);
    end
end

function localReport(benchmark)
    fprintf("\nOnline NRMM tracking error benchmark\n");
    fprintf("  duration: %.3f s\n", benchmark.options.duration);
    fprintf("  Monte Carlo runs for noisy cases: %d\n", ...
        benchmark.options.monteCarloRuns);
    fprintf("  RMSE burn-in fraction: %.3f (peaks cover the " ...
        + "complete trial)\n", benchmark.options.burnInFraction);
    fprintf("  Error statistics use completed finite runs; failure " ...
        + "counts are separate.\n\n");
    fprintf("Execution and sampled truth-domain audit\n");
    disp(benchmark.summary(:, [ ...
        "caseName", "sampleRateHz", "completedRunCount", ...
        "failedRunCount", "failureIdentifiers", ...
        "truthWithinCertifiedDomain"]));
    fprintf("\nEgo-state RMSE\n");
    disp(benchmark.summary(:, [ ...
        "caseName", "egoPositionRmseMeanM", "egoVelocityRmseMeanMps", ...
        "egoAccelerationRmseMeanMps2", "egoYawRmseMeanDeg"]));
    fprintf("\nTarget RMSE in [rho; q; s] coordinates\n");
    fprintf("  Radar noise reaches the s channel through the " ...
        + "omega_T^3 innovation gain;\n  large s-channel RMSE in " ...
        + "noisy cases is expected and reported as measured.\n");
    disp(benchmark.summary(:, [ ...
        "caseName", "relativePositionRmseMeanM", ...
        "relativePositionRmseWorstM", "relativePositionPeakWorstM", ...
        "targetVelocityEgoRmseMeanMps", ...
        "targetAccelerationEgoRmseMeanMps2", ...
        "targetAccelerationEgoRmseWorstMps2"]));
    fprintf("\nTarget inertial reconstruction and domain audit\n");
    disp(benchmark.summary(:, [ ...
        "caseName", "targetInertialPositionRmseMeanM", ...
        "minimumEstimatedTargetSpeedWorstMps", ...
        "speedDomainValidCumulativeAll", ...
        "speedDomainValidFinalIntervalAll"]));
    failures = benchmark.trials(~benchmark.trials.completed, ...
        ["caseName", "seed", "failureIdentifier"]);
    if height(failures) > 0
        fprintf("\nRecorded failures (synthesis or runtime)\n");
        disp(failures);
    end
end

function rotated = localRotateRows(angle, vectors)
    rotated = [ ...
        cos(angle).*vectors(:, 1)-sin(angle).*vectors(:, 2), ...
        sin(angle).*vectors(:, 1)+cos(angle).*vectors(:, 2)];
end

function rotation = localRotation(angle)
    rotation = [cos(angle), -sin(angle); sin(angle), cos(angle)];
end

function value = localWrapToPi(value)
    value = mod(value+pi, 2.0*pi)-pi;
end

function options = localOptions(varargin)
    parser = inputParser;
    parser.FunctionName = mfilename;
    addParameter(parser, "Report", true, ...
        @(x) islogical(x) && isscalar(x));
    addParameter(parser, "Seed", 17, ...
        @(x) isnumeric(x) && isscalar(x) && isfinite(x));
    addParameter(parser, "Duration", 12.0, ...
        @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0.0);
    addParameter(parser, "MonteCarloRuns", 5, ...
        @(x) isnumeric(x) && isscalar(x) && isfinite(x) ...
        && x >= 1.0 && x == floor(x));
    addParameter(parser, "BurnInFraction", 0.25, ...
        @(x) isnumeric(x) && isscalar(x) && isfinite(x) ...
        && x >= 0.0 && x < 1.0);
    parse(parser, varargin{:});
    options = struct( ...
        "report", parser.Results.Report, ...
        "seed", double(parser.Results.Seed), ...
        "duration", double(parser.Results.Duration), ...
        "monteCarloRuns", double(parser.Results.MonteCarloRuns), ...
        "burnInFraction", double(parser.Results.BurnInFraction));
end

