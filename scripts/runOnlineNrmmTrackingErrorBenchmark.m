        "egoVelocityRmseMps", Inf, ...
        "egoAccelerationRmseMps2", Inf, ...
        "egoYawRmseDeg", Inf, ...
        "relativePositionRmseM", Inf, ...
        "relativePositionPeakM", Inf, ...
        "targetVelocityEgoRmseMps", Inf, ...
        "targetAccelerationEgoRmseMps2", Inf, ...
