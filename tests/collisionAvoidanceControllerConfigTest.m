classdef collisionAvoidanceControllerConfigTest < matlab.unittest.TestCase
    % collisionAvoidanceControllerConfigTest Signed braking-ratio contract.

    properties (TestParameter)
        boundField = {"brakingRatioMinimum", ...
            "brakingRatioMaximum"}
        invalidBound = struct("notANumber", NaN, "infinite", Inf, ...
            "complex", 1.0+1.0i, "empty", [], "vector", [1.0, 2.0], ...
            "text", "4", "logical", true)
        invalidInterval = struct("zeroWidth", [0.0, 0.0], ...
            "reversed", [4.0, -8.0], "positiveOnly", [1.0, 4.0], ...
            "negativeOnly", [-1.0, -0.2], "outsideRange", [-1.01, 1.0])
        removedOption = { ...
            struct("inputPenalty", struct("slewWeight", .5)), ...
            struct("model", struct("frontWheelSteeringAngleMaximum", .7)), ...
            struct("model", struct("frontWheelSteeringRateMaximum", 1)), ...
            struct("nonlinear", struct("maximumIterations", 8)), ...
            struct("nonlinear", struct("predictionToleranceMeters", .01)), ...
            struct("controller", struct("maximumLateralDeviationMeters", 10)), ...
            struct("nonlinear", struct("statePredictionTolerance", .01)), ...
            struct("nonlinear", struct("clfPredictionTolerance", .01)), ...
            struct("admission", struct("widthScale", 1.2)), ...
            struct("jointCertificate", struct("proximalWeight", .001)), ...
            struct("feedbackPrediction", struct("enabled", true)), ...
            struct("encounter", struct("taylorOrder", 6)), ...
            struct("solver", struct("frameDeadlineSeconds", 1)), ...
            struct("nonlinear", struct("maximumImprovementIterations", 0)), ...
            struct("certification", struct("enabled", false)), ...
            struct("certification", struct("enabled", true)), ...
            struct("disjunctive", struct("nodeBudget", 0)), ...
            struct("sequentialConvex", struct("penaltySchedule", [])), ...
            struct("collision", struct("disturbanceBound", 0)), ...
            struct("collision", struct("clearanceMargin", 0)), ...
            struct("clf", struct("trustRegionScale", Inf)), ...
            struct("clf", struct("relaxationWeight", 100)), ...
            struct("clf", struct("certificationRegionScale", 2)), ...
            struct("clf", struct("certificationFrontForceFraction", .4)), ...
            struct("clf", struct("shapeRatio", 10)), ...
            struct("solver", struct("function", [])), ...
            struct("solver", struct("stepToleranceRetry", [])), ...
            struct("solver", struct("method", "nonlinearShooting")), ...
            struct("solver", struct("method", "affineSocp")), ...
            struct("nonlinear", struct("horizonSeconds", 6)), ...
            struct("terminal", struct("horizonSeconds", 60)), ...
            struct("terminal", struct("acceptanceSteps", [1,0])), ...
            struct("terminal", struct("sqpIterations", 2)), ...
            struct("terminal", struct("levelMaximum", 1)), ...
            struct("terminal", struct("timeStepSeconds", .005)), ...
            struct("nonlinear", struct("certificateStep", .005)), ...
            struct("nonlinear", struct("maximumCertificateCells", 100)), ...
            struct("nonlinear", struct("targetConsistencyTolerance", 1e-8)), ...
            struct("nonlinear", struct("initialPlan", zeros(2,8))), ...
            struct("nonlinear", struct("proposalFunction", @sin))}
        invalidCrossingGap = {-0.1, Inf, NaN, [0.1, 0.2]}
        invalidActuation = {[], 1.0, struct([])}
        invalidReferenceWeight = {-1, Inf, NaN, [1,2]}
        performanceWeight = {"referenceDeviationWeight","nominalTrackingWeight","inputVariationWeight"}
        invalidSteeringRate = {0,-1,-Inf,NaN,[1,2],1i}
    end

    methods (TestClassSetup)
        function addControllerPaths(testCase)
            repositoryRoot = fileparts(fileparts(mfilename("fullpath")));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                fullfile(repositoryRoot, "config")));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                fullfile(repositoryRoot, "controller")));
        end
    end

    methods (Test)
        function compactPlanningRequiresAPositiveSafetyMargin(testCase)
            override=struct('outputFeedback',struct('clearanceMeters',0));
            testCase.verifyError(@()collisionAvoidanceControllerConfig(override), ...
                'collisionAvoidanceController:invalidConfiguration');
        end
        function compactTimingUsesTheWholeCallBudget(testCase)
            cfg=collisionAvoidanceControllerConfig();
            testCase.verifyEqual(cfg.outputFeedback.maximumSolveSeconds,1);
            testCase.verifyEqual(cfg.outputFeedback.method,"ipopt");
            testCase.verifyError(@()collisionAvoidanceControllerConfig(struct( ...
                'outputFeedback',struct('method',"dynamicMemoryIpopt"))), ...
                'collisionAvoidanceController:invalidConfiguration');
            explicit=collisionAvoidanceControllerConfig(struct('outputFeedback',struct('maximumSolveSeconds',.25)));
            testCase.verifyEqual(explicit.outputFeedback.maximumSolveSeconds,.25);
        end
    end

    methods (Test)
        function steeringRateIsUnboundedUnlessExplicitlyConfigured(testCase)
            defaults=collisionAvoidanceControllerConfig();
            supplied=collisionAvoidanceControllerConfig(struct('outputFeedback',struct('steeringRateMaximum',2)));
            testCase.verifyEqual(defaults.outputFeedback.steeringRateMaximum,Inf);
            testCase.verifyEqual(supplied.outputFeedback.steeringRateMaximum,2,AbsTol=0);
        end
        function invalidSteeringRatesAreRejected(testCase,invalidSteeringRate)
            testCase.verifyError(@()collisionAvoidanceControllerConfig(struct('outputFeedback', ...
                struct('steeringRateMaximum',invalidSteeringRate))), ...
                'collisionAvoidanceController:invalidConfiguration');
        end
        function generatedCodeOptimizationCanBeSelectedForExperiments(testCase)
            cfg=collisionAvoidanceControllerConfig(struct('outputFeedback',struct('nlpCompilerOptimization',1)));
            testCase.verifyEqual(cfg.outputFeedback.nlpCompilerOptimization,1);
        end
        function invalidCompilerOptimizationLevelsAreRejected(testCase)
            testCase.verifyError(@()collisionAvoidanceControllerConfig( ...
                struct('outputFeedback',struct('nlpCompilerOptimization',4))), ...
                'collisionAvoidanceController:invalidConfiguration');
        end
        function oldNumericalSettingsDoNotOverrideTheIpoptIterationLimit(testCase)
            expected=collisionAvoidanceControllerConfig(struct('outputFeedback',struct('nlpMaximumIterations',5)));
            saved=expected;
            for name=["restorationMaximumIterations","qpMaximumIterations","finiteDifferenceStep"]
                saved.outputFeedback.(name)=3;
                testCase.verifyError(@()collisionAvoidanceControllerConfig(struct('outputFeedback',struct(name,3))), ...
                    'collisionAvoidanceController:invalidConfiguration');
            end
            testCase.verifyError(@()collisionAvoidanceControllerConfig(saved), ...
                'collisionAvoidanceController:invalidConfiguration');
        end
        function theJointHorizonHasNoFixedStageDefault(testCase)
            cfg=collisionAvoidanceControllerConfig();
            testCase.verifyEmpty(cfg.outputFeedback.horizonSeconds);
            testCase.verifyFalse(isfield(cfg.outputFeedback,'horizonSteps'));
            testCase.verifyFalse(isfield(cfg.controller,'horizonSteps'));
        end
        function retiredJointStageCountsCannotSilentlyOverrideCoverage(testCase)
            testCase.verifyError(@()collisionAvoidanceControllerConfig( ...
                struct('outputFeedback',struct('horizonSteps',4))), ...
                'collisionAvoidanceController:invalidConfiguration');
        end
        function horizonCapacityIsIndependentOfAnyRetiredStageMinimum(testCase)
            cfg=collisionAvoidanceControllerConfig(struct('controller',struct('maximumHorizonSteps',10)));
            testCase.verifyEqual(cfg.controller.maximumHorizonSteps,10);
            testCase.verifyError(@()collisionAvoidanceControllerConfig(struct('controller',struct('horizonSteps',4))), ...
                'collisionAvoidanceController:invalidConfiguration');
        end
        function jointModelSchedulingCanBeDisabledAndRequiresAFiniteStepCount(testCase)
            cfg=collisionAvoidanceControllerConfig(struct('controller',struct('jointPredictionRefreshSteps',1)));
            testCase.verifyEqual(cfg.controller.jointPredictionRefreshSteps,1);
            for invalid=[0,-1,1.5,Inf,NaN]
                testCase.verifyError(@()collisionAvoidanceControllerConfig( ...
                    struct('controller',struct('jointPredictionRefreshSteps',invalid))), ...
                    'collisionAvoidanceController:invalidConfiguration');
            end
        end
        function targetRearAxleDistanceIsPositiveAndIndependentOfEgoGeometry(testCase)
            cfg=collisionAvoidanceControllerConfig(struct('target',struct('rearAxleDistance',1.8)));
            testCase.verifyEqual(cfg.target.rearAxleDistance,1.8);
            testCase.verifyEqual(cfg.vehicle.lr,1.65);
            testCase.verifyError(@()collisionAvoidanceControllerConfig(struct('target',struct('rearAxleDistance',0))), ...
                'collisionAvoidanceController:invalidConfiguration');
        end
        function fixedCollisionAndPlannerBuffersAreNotConfigurationOptions(testCase)
            cfg=collisionAvoidanceControllerConfig();
            testCase.verifyFalse(isfield(cfg.collision,'safetyMarginMeters'));
            testCase.verifyFalse(isfield(cfg.planner,'clearanceReserveMeters'));
            for retired={struct('collision',struct('safetyMarginMeters',.2)), ...
                    struct('planner',struct('clearanceReserveMeters',.2))}
                testCase.verifyError(@()collisionAvoidanceControllerConfig(retired{1}), ...
                    'collisionAvoidanceController:invalidConfiguration');
            end
        end

        function encounterRangeDefaultsToFiftyMetersAndMustBeFinite(testCase)
            % Collision rows apply only inside this perception radius.
            cfg = collisionAvoidanceControllerConfig();
            testCase.verifyEqual(cfg.collision.encounterRangeMeters, 50);
            testCase.verifyError(@() collisionAvoidanceControllerConfig( ...
                struct('collision', struct('encounterRangeMeters', Inf))), ...
                'collisionAvoidanceController:invalidConfiguration');
        end

        function encounterRangeHasNoArbitraryClearanceFloor(testCase)
            cfg=collisionAvoidanceControllerConfig(struct('collision',struct('encounterRangeMeters',.05)));
            testCase.verifyEqual(cfg.collision.encounterRangeMeters,.05);
            for range = [-1, 0, NaN, Inf]
                testCase.verifyError(@() collisionAvoidanceControllerConfig( ...
                    struct('collision', struct('encounterRangeMeters', range))), ...
                    'collisionAvoidanceController:invalidConfiguration');
            end
        end

        function solverPrecisionAndIterationLimitsAreValidated(testCase)
            invalid = {struct("constraintTolerance", 0.0), ...
                struct("optimalityTolerance", -1.0), ...
                struct("maxIterations", 0), struct("maxIterations", 1.5), ...
                struct("maxIterations", Inf)};
            for index = 1:numel(invalid)
                testCase.verifyError(@() collisionAvoidanceControllerConfig( ...
                    struct("solver", invalid{index})), ...
                    "collisionAvoidanceController:invalidConfiguration");
            end
        end

        function crossingTimeGapMustBeFiniteAndNonnegative(testCase, invalidCrossingGap)
            override = struct("performance", struct("crossingTimeGap", invalidCrossingGap));
            testCase.verifyError( ...
                @() collisionAvoidanceControllerConfig(override), ...
                "collisionAvoidanceController:invalidConfiguration");
        end

        function theOldAccelerationGainCannotRedefineThePaperRatio(testCase)
            override = struct("model", struct( ...
                "longitudinalInputGain", 0.8));
            testCase.verifyError( ...
                @() collisionAvoidanceControllerConfig(override), ...
                "collisionAvoidanceController:invalidConfiguration");
        end

        function removedAlgorithmOptionsAreRejected(testCase, removedOption)
            testCase.verifyError( ...
                @() collisionAvoidanceControllerConfig(removedOption), ...
                "collisionAvoidanceController:invalidConfiguration");
        end

        function unknownNestedOptionsAreRejected(testCase)
            override = struct("controller", struct("misspelledOption", 1));
            testCase.verifyError( ...
                @() collisionAvoidanceControllerConfig(override), ...
                "collisionAvoidanceController:invalidConfiguration");
        end

        function brakingRatioBoundsMustBeFiniteRealScalars( ...
                testCase, boundField, invalidBound)
            override = struct("actuation", struct(boundField, invalidBound));

            testCase.verifyError( ...
                @() collisionAvoidanceControllerConfig(override), ...
                "collisionAvoidanceController:invalidConfiguration");
        end

        function brakingRatioIntervalMustContainZeroWithPositiveWidth( ...
                testCase, invalidInterval)
            override = struct("actuation", struct( ...
                "brakingRatioMinimum", invalidInterval(1), ...
                "brakingRatioMaximum", invalidInterval(2)));

            testCase.verifyError( ...
                @() collisionAvoidanceControllerConfig(override), ...
                "collisionAvoidanceController:invalidConfiguration");
        end

        function actuationMustBeAScalarStructure(testCase, invalidActuation)
            override = struct("actuation", {invalidActuation});

            testCase.verifyError( ...
                @() collisionAvoidanceControllerConfig(override), ...
                "collisionAvoidanceController:invalidConfiguration");
        end

        function singlePrecisionBoundsAreNormalizedWithoutChangingUnits(testCase)
            override = struct("actuation", struct( ...
                "brakingRatioMinimum", single(-1.0), ...
                "brakingRatioMaximum", single(0.5)));

            cfg = collisionAvoidanceControllerConfig(override);

            testCase.verifyClass(cfg.actuation.brakingRatioMinimum, ...
                "double");
            testCase.verifyClass(cfg.actuation.brakingRatioMaximum, ...
                "double");
            testCase.verifyEqual(cfg.actuation.brakingRatioMinimum, ...
                -1.0, AbsTol=0.0);
            testCase.verifyEqual(cfg.actuation.brakingRatioMaximum, ...
                0.5, AbsTol=0.0);
        end

        function zeroMaximumStillAllowsBraking(testCase)
            override = struct("actuation", struct( ...
                "brakingRatioMaximum", 0.0));

            cfg = collisionAvoidanceControllerConfig(override);

            testCase.verifyEqual(cfg.actuation.brakingRatioMaximum, ...
                0.0, AbsTol=0.0);
            testCase.verifyLessThan(cfg.actuation.brakingRatioMinimum, ...
                0.0);
        end
    end
end
