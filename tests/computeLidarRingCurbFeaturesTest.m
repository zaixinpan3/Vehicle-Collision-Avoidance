        function computesLocalRangeHaarAndIlpResidual(testCase)
            frame = localSparseOpenArcFrame(1, 1000, 15, 1.0);
            validColumns = find(frame.valid);
            centerColumn = validColumns(8);
            frame.z(validColumns) = 0.2 * (1:numel(validColumns));
            adjacentChordLength = hypot( ...
                frame.x(validColumns(9)) - frame.x(centerColumn), ...
                frame.y(validColumns(9)) - frame.y(centerColumn));
            expectedMeanElevation = mean(frame.z(validColumns(6:10)));
            expectedSlopeMagnitude = 0.2 / adjacentChordLength;

            [linearFeatures, linearValidity] = ...
                computeLidarRingCurbFeatures(frame, struct());
            frame.z(centerColumn) = frame.z(centerColumn) + 1.0;
            [roughFeatures, roughValidity] = ...
                computeLidarRingCurbFeatures(frame, struct());

            testCase.verifyTrue( ...
                linearValidity.localHeightRange(centerColumn));
            testCase.verifyGreaterThan( ...
                linearFeatures.localHeightRange(centerColumn), 0.0);
            testCase.verifyEqual( ...
                linearFeatures.localMeanElevation(centerColumn), ...
                expectedMeanElevation, AbsTol=1.0e-12);
            testCase.verifyTrue( ...
                linearValidity.localMultiscaleHaarZ( ...
                    1, centerColumn, 3));
            testCase.verifyTrue( ...
                linearValidity.ilpLineFitResidual(centerColumn));
            testCase.verifyLessThan( ...
                linearFeatures.ilpLineFitResidual(centerColumn), 1.0e-10);
            testCase.verifyEqual( ...
                linearFeatures.ilpLineSlopeMagnitude(centerColumn), ...
                expectedSlopeMagnitude, AbsTol=1.0e-10);
            testCase.verifyTrue( ...
                roughValidity.ilpLineFitResidual(centerColumn));
            testCase.verifyGreaterThan( ...
                roughFeatures.ilpLineFitResidual(centerColumn), 0.1);
        end

        function computesSameRingSlopeAndHataDifferential(testCase)
            frame = localFrameFromAngles( ...
                1, 100, [0.0, 1.0, 2.0], 10.0);
            validColumns = find(frame.valid);
            centerColumn = validColumns(2);
            frame.z(validColumns) = [0.0, 1.0, 3.0];
            leftDistance = hypot( ...
                frame.x(centerColumn) - frame.x(validColumns(1)), ...
                frame.y(centerColumn) - frame.y(validColumns(1)));
            rightDistance = hypot( ...
                frame.x(validColumns(3)) - frame.x(centerColumn), ...
                frame.y(validColumns(3)) - frame.y(centerColumn));
            expectedSlopeMagnitude = max( ...
                abs(atan2(1.0, leftDistance)), ...
                abs(atan2(2.0, rightDistance)));

            [features, validity] = ...
                computeLidarRingCurbFeatures(frame, struct());

            testCase.verifyTrue( ...
                validity.sameRingSlopeMagnitude(centerColumn));
            testCase.verifyEqual( ...
                features.sameRingSlopeMagnitude(centerColumn), ...
                expectedSlopeMagnitude, AbsTol=1.0e-12);
            testCase.verifyTrue( ...
                validity.hataDifferentialHeightResponse(centerColumn));
            testCase.verifyEqual( ...
                features.hataDifferentialHeightResponse(centerColumn), ...
                6.0, AbsTol=1.0e-12);
            testCase.verifyTrue( ...
                validity.sameRingSlopeMagnitude(validColumns(1)));
            testCase.verifyFalse( ...
                validity.hataDifferentialHeightResponse(validColumns(1)));
        end

