        function chenAndHuangMatchVectorDefinitions(testCase)
            frame = localSparseCircularFrame(1, 1000, 360);
            validColumns = find(frame.valid);
            centerColumn = validColumns(100);
            [centerPoint, leftPoints, rightPoints] = ...
                localDefinitionPoints(frame, centerColumn, 2);
            neighborSum = sum([leftPoints; rightPoints], 1);
            expectedChen = norm(neighborSum - 4.0 * centerPoint) ...
                / (4.0 * norm(centerPoint));
            leftImmediate = leftPoints(1, :);
            rightImmediate = rightPoints(1, :);
            chord = rightImmediate - leftImmediate;
            expectedHuang = abs(dot(centerPoint, chord)) ...
                / (norm(centerPoint) * norm(chord));

            [features, validity] = ...
                computeLidarRingCurbFeatures(frame, struct());

            testCase.verifyTrue(validity.chenSmoothness(centerColumn));
            testCase.verifyEqual( ...
                features.chenSmoothness(centerColumn), expectedChen, ...
                AbsTol=1.0e-12);
            testCase.verifyEqual( ...
                features.huangTangentialStrength(centerColumn), ...
                expectedHuang, AbsTol=1.0e-12);
        end

        function huangUsesOnlyRoadPlaneProjection(testCase)
            referenceFrame = localSparseCircularFrame(1, 1000, 360);
            modifiedFrame = referenceFrame;
            validColumns = find(referenceFrame.valid);
            centerColumn = validColumns(100);
            leftColumn = validColumns(99);
            rightColumn = validColumns(101);
            modifiedFrame.z(centerColumn) = 20.0;
            modifiedFrame.z(leftColumn) = -15.0;
            modifiedFrame.z(rightColumn) = 35.0;
            centerPoint = [ ...
                referenceFrame.x(centerColumn), ...
                referenceFrame.y(centerColumn)];
            neighborChord = [ ...
                referenceFrame.x(rightColumn) ...
                    - referenceFrame.x(leftColumn), ...
                referenceFrame.y(rightColumn) ...
                    - referenceFrame.y(leftColumn)];
            expectedHuang = abs(dot(centerPoint, neighborChord)) ...
                / (norm(centerPoint) * norm(neighborChord));

            [referenceFeatures, referenceValidity] = ...
                computeLidarRingCurbFeatures(referenceFrame, struct());
            [modifiedFeatures, modifiedValidity] = ...
                computeLidarRingCurbFeatures(modifiedFrame, struct());

            testCase.verifyTrue( ...
                modifiedValidity.huangTangentialStrength(centerColumn));
            testCase.verifyEqual( ...
                modifiedFeatures.huangTangentialStrength(centerColumn), ...
                expectedHuang, AbsTol=1.0e-12);
            testCase.verifyEqual( ...
                modifiedFeatures.huangTangentialStrength(centerColumn), ...
                referenceFeatures.huangTangentialStrength(centerColumn), ...
                AbsTol=1.0e-12);
            testCase.verifyEqual( ...
                modifiedValidity.huangTangentialStrength(centerColumn), ...
                referenceValidity.huangTangentialStrength(centerColumn));
        end

