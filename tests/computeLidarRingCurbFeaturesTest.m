function frame = localSparseCircularFrame( ...
        numberOfRings, numberOfBins, numberOfReturns)
    angles = 360.0 * (0:(numberOfReturns - 1)) / numberOfReturns;
    frame = localFrameFromAngles( ...
        numberOfRings, numberOfBins, angles, ...
        (10.0 + (0:(numberOfRings - 1)).'));
end

function frame = localSparseOpenArcFrame( ...
        numberOfRings, numberOfBins, numberOfReturns, angleStep)
    angles = angleStep * (0:(numberOfReturns - 1));
    frame = localFrameFromAngles( ...
        numberOfRings, numberOfBins, angles, ...
        (10.0 + (0:(numberOfRings - 1)).'));
end

function frame = localFrameFromAngles( ...
        numberOfRings, numberOfBins, angles, radius)
    frame = struct( ...
        "x", nan(numberOfRings, numberOfBins), ...
        "y", nan(numberOfRings, numberOfBins), ...
        "z", nan(numberOfRings, numberOfBins), ...
        "range", nan(numberOfRings, numberOfBins), ...
        "valid", false(numberOfRings, numberOfBins));
    columns = round(linspace(1, numberOfBins, numel(angles)));
    ringRadius = reshape(radius, [], 1);
    ringRadius = repmat(ringRadius, 1, numel(angles));
    angleMatrix = repmat(angles, numberOfRings, 1);
    frame.x(:, columns) = ringRadius .* cosd(angleMatrix);
    frame.y(:, columns) = ringRadius .* sind(angleMatrix);
    frame.z(:, columns) = repmat( ...
        (0:(numberOfRings - 1)).', 1, numel(angles));
    frame.range(:, columns) = ringRadius;
    frame.valid(:, columns) = true;
end

function column = localColumnAtAngle(frame, targetAngle)
    columns = find(frame.valid(1, :));
    angles = mod(atan2d( ...
        frame.y(1, columns), frame.x(1, columns)), 360.0);
    [~, index] = min(abs( ...
        mod(angles - targetAngle + 180.0, 360.0) - 180.0));
    column = columns(index);
end

function [centerPoint, leftPoints, rightPoints] = ...
        localDefinitionPoints(frame, centerColumn, radius)
    columns = find(frame.valid(1, :));
    angles = mod(atan2d( ...
        frame.y(1, columns), frame.x(1, columns)), 360.0);
    [~, order] = sort(angles);
    columns = columns(order);
    centerIndex = find(columns == centerColumn, 1);
    pointCount = numel(columns);
    leftIndices = mod(centerIndex - (1:radius) - 1, pointCount) + 1;
    rightIndices = mod(centerIndex + (1:radius) - 1, pointCount) + 1;
    centerPoint = localPoint(frame, centerColumn);
    leftPoints = [ ...
        localPoint(frame, columns(leftIndices(1))); ...
        localPoint(frame, columns(leftIndices(2)))];
    rightPoints = [ ...
        localPoint(frame, columns(rightIndices(1))); ...
        localPoint(frame, columns(rightIndices(2)))];
end

function point = localPoint(frame, column)
    point = [frame.x(1, column), frame.y(1, column), frame.z(1, column)];
end

function frame = localTwoRingHataFrame( ...
        upperRange, lowerRange, azimuthDegrees)
    frame = struct( ...
        "x", nan(2, 20), ...
        "y", nan(2, 20), ...
        "z", nan(2, 20), ...
        "range", nan(2, 20), ...
        "valid", false(2, 20));
    upperColumn = 7;
    lowerColumn = 13;
    frame.x(1, upperColumn) = upperRange * cosd(azimuthDegrees);
    frame.y(1, upperColumn) = upperRange * sind(azimuthDegrees);
    frame.z(1, upperColumn) = -2.35;
    frame.range(1, upperColumn) = upperRange;
    frame.valid(1, upperColumn) = true;
    frame.x(2, lowerColumn) = lowerRange * cosd(azimuthDegrees);
    frame.y(2, lowerColumn) = lowerRange * sind(azimuthDegrees);
    frame.z(2, lowerColumn) = -2.35;
    frame.range(2, lowerColumn) = lowerRange;
    frame.valid(2, lowerColumn) = true;
end

function frame = localThreeRingHuangFrame(heights)
    numberOfBins = 20;
    pointColumn = 10;
    xCoordinates = [10.0; 7.0; 2.0];
    frame = struct( ...
        "x", nan(3, numberOfBins), ...
        "y", nan(3, numberOfBins), ...
        "z", nan(3, numberOfBins), ...
        "range", nan(3, numberOfBins), ...
        "valid", false(3, numberOfBins));
    frame.x(:, pointColumn) = xCoordinates;
    frame.y(:, pointColumn) = 0.0;
    frame.z(:, pointColumn) = heights(:);
    frame.range(:, pointColumn) = abs(xCoordinates);
    frame.valid(:, pointColumn) = true;
end
