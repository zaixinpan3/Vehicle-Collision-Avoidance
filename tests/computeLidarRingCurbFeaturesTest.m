        function computesHataAdjacentRingCompression(testCase)
            sensorHeight = 2.35;
            verticalAngles = [-10.0, -20.0];
            upperRange = sensorHeight / tand(10.0);
            lowerRange = sensorHeight / tand(20.0);
            frame = localTwoRingHataFrame( ...
                upperRange, lowerRange, 15.0);
            lowerColumn = find(frame.valid(2, :), 1, "first");
            cfg = struct( ...
                "ringFeatureSensorHeightM", sensorHeight, ...
                "ringFeatureVerticalAnglesDegrees", verticalAngles);

            [features, validity] = ...
                computeLidarRingCurbFeatures(frame, cfg);

            testCase.verifyTrue( ...
                validity.hataCompressionRaw(2, lowerColumn));
            testCase.verifyEqual( ...
                features.hataCompressionExpected(2, lowerColumn), ...
                upperRange - lowerRange, AbsTol=1.0e-12);
            testCase.verifyEqual( ...
                features.hataCompressionRaw(2, lowerColumn), ...
                0.0, AbsTol=1.0e-12);
            testCase.verifyEqual( ...
                features.hataCompressionNormalized(2, lowerColumn), ...
                0.0, AbsTol=1.0e-12);
            testCase.verifyFalse(any( ...
                validity.hataCompressionRaw(1, :), "all"));
        end

