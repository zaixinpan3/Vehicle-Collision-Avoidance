end

function localVerifySuccessfulAvoidance(testCase, result)
    testCase.verifyFalse(result.failure.occurred, ...
        localFailureDiagnostic(result));
    testCase.verifyTrue(result.metrics.controllerCompletedScenario);
    testCase.verifyTrue(result.avoidance.baselineCollides);
    testCase.verifyTrue(result.avoidance.collisionFree);
    testCase.verifyTrue(result.roadSafety.noBoundaryCrossing);
    testCase.verifyTrue( ...
        result.roadSafety.allRectanglesCoveredByPerceivedSegments);
    testCase.verifyGreaterThanOrEqual( ...
        result.roadSafety.minimumBoundaryFunctionMargin, ...
        -result.roadSafety.contactTolerance);
    testCase.verifyGreaterThan( ...
        result.avoidance.minimumControlledSeparatingAxisMargin, 0.0);
    testCase.verifyTrue(result.avoidance.passedTarget);
    testCase.verifyTrue(result.avoidance.remainedMoving);
    testCase.verifyGreaterThan( ...
        result.avoidance.minimumEgoLongitudinalSpeed, 0.0);
    testCase.verifyEqual( ...
        result.scenario.stateSource, "onlineNrmmTrackingRuntime");
    testCase.verifyTrue(result.estimator.enabled);
    testCase.verifyTrue( ...
        result.estimator.metrics.allEstimatesFinite);
    testCase.verifyTrue( ...
        result.estimator.metrics.controllerInputsFromEstimator);
    testCase.verifyTrue( ...
        result.estimator.metrics.sensorContractValid);
    testCase.verifyTrue( ...
        result.estimator.metrics.radarDetectionOccurred);
    testCase.verifyTrue( ...
        result.estimator.metrics.allRadarDetectionsWithinRange);
    testCase.verifyTrue( ...
        result.estimator.metrics.targetPublicationWithinRadarVisibility);
    firstTargetIdx = find(~cellfun( ...
        @isempty, result.targetEstimate), 1, "first");
    egoOutput = result.controllerEgoEstimate{firstTargetIdx};
    sensorFrame = result.estimator.sensorFrame{firstTargetIdx};
    rotation = [ ...
        cos(egoOutput.egoYaw), -sin(egoOutput.egoYaw); ...
        sin(egoOutput.egoYaw), cos(egoOutput.egoYaw)];
    synchronizedTargetPosition = egoOutput.egoState([1, 4]) ...
        + rotation*sensorFrame.radarRelativePosition.';
    firstTarget = result.targetEstimate{firstTargetIdx};
    observerCfg = result.estimator.configuration.observer;
    testCase.verifyLessThanOrEqual( ...
        firstTarget.lastRadarTime, firstTarget.stateTime+1.0e-12);
    measurementAge = max(0.0, ...
        firstTarget.stateTime-firstTarget.lastRadarTime);
    % A flowing observer is not a radar reset.  During the held-input
    % phase its relative-position rate is bounded by target speed, ego
    % speed, and rotation of the measured line of sight.  One observer
    % period covers the output/predictor phase offset at a coincident
    % timestamp; the remaining terms cover the two radar endpoints and
    % the published ego-position radius.
    relativeRateMaximum = ...
        observerCfg.target.domain.speedMaximum ...
        + observerCfg.ego.domain.speedMaximum ...
        + observerCfg.ego.domain.yawRateMaximum ...
            * result.estimator.configuration.sensor.radar.rangeMaximum;
    firstEstimateConsistencyRadius = relativeRateMaximum ...
        * (measurementAge+observerCfg.runtime.samplePeriod) ...
        + 2.0*result.estimator.configuration.sensor.radar ...
            .positionNoiseMaximum ...
        + result.estimator.configuration.publishedErrorBound ...
            .egoPosition;
    testCase.verifyLessThanOrEqual(norm( ...
        firstTarget.targetPositionInertial ...
            - synchronizedTargetPosition), ...
        firstEstimateConsistencyRadius);
    testCase.verifyLessThanOrEqual( ...
        result.estimator.metrics.maximumDetectedTargetRange, 30.0);
    testCase.verifyEqual( ...
        result.controllerConfiguration.vehicle.length, ...
        5.0, AbsTol=0.0);
    testCase.verifyEqual( ...
        result.controllerConfiguration.vehicle.width, ...
        2.0, AbsTol=0.0);
    testCase.verifyEqual( ...
        result.controllerConfiguration.target.defaultLength, ...
        5.0, AbsTol=0.0);
    testCase.verifyEqual( ...
        result.controllerConfiguration.target.defaultWidth, ...
        2.0, AbsTol=0.0);
    testCase.verifyEqual(result.perception.rangeMaximum, ...
        30.0, AbsTol=0.0);
    testCase.verifyEqual(result.perception.roadBoundaryOffsets, ...
        [6.0; 8.0], AbsTol=0.0);
    maximumRoadPointRange = max(cellfun( ...
        @(value) max([ ...
            value.roadGeometry.boundaries.maximumSourcePointRange]), ...
        result.perception.roadBoundaryFit));
    candidateRoadRows = cellfun( ...
        @(value) value.candidateSafetyRowCount, ...
        result.perception.controllerRoadAudit);
    testCase.verifyLessThanOrEqual( ...
        maximumRoadPointRange, 30.0 + 1.0e-10);
    testCase.verifyGreaterThan(min(candidateRoadRows), 0);
end

function localVerifyPreDetectionCruise(testCase, result)
    preDetection = evaluatePreDetectionCruise( ...
        result, MinimumDuration=2.0);
    testCase.verifyTrue(preDetection.passed);
    testCase.verifyTrue(preDetection.cruiseMaintained);
    testCase.verifyGreaterThanOrEqual( ...
        preDetection.preDetectionDuration, 2.0);
end

function target = localRadarExitTarget(time, ~)
    target = struct( ...
        "targetPositionInertial", [29.0 + 30.0*time; 0.0]);
end

function diagnostic = localFailureDiagnostic(result)
    if isempty(result.command)
        maximumSteering = NaN;
    else
        maximumSteering = max(cellfun(@(command) ...
            abs(command.frontWheelSteeringAngle), result.command));
    end
    diagnostic = sprintf( ...
        "%s | failure time %.3f s; dRect %.6f m; " ...
        + "road margin %.6f; max |steer| %.6f rad; " ...
        + "max |lateral error| %.6f m", ...
        result.failure.message, result.failure.time, ...
        result.avoidance.minimumControlledSeparatingAxisMargin, ...
        result.roadSafety.minimumBoundaryFunctionMargin, ...
        maximumSteering, ...
        max(abs(result.controlTracking.lateralError)));
end
