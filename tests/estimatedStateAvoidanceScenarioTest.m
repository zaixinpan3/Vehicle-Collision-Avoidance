        function acquiredTargetFollowsFiniteRadarLifecycle(testCase)
            cfg = localConfiguration(20260731);
            cfg.noiseModel = "none";
            initialEgo = struct( ...
                "position", [0.0; 0.0], ...
                "yawAngle", 0.0, ...
                "longitudinalVelocity", 15.0, ...
                "lateralVelocity", 0.0, ...
                "yawRate", 0.0);
            targetStateFunction = @(time, egoState) ...
                localRadarExitTarget(time, egoState);
            [context, initialization] = ...
                nrmmEstimatorControllerAdapter( ...
                    "initialize", cfg, initialEgo, ...
                    targetStateFunction);

            targetAtZero = targetStateFunction(0.0, initialEgo);
            [context, visibleEgo, visibleTarget, visibleFrame] = ...
                nrmmEstimatorControllerAdapter( ...
                    "sample", context, 0.0, initialEgo, ...
                    targetAtZero);
            nextEgo = initialEgo;
            nextEgo.position = [1.5; 0.0];
            targetAtNextSample = ...
                targetStateFunction(0.1, nextEgo);
            [context, hiddenEgo, hiddenTarget, hiddenFrame] = ...
                nrmmEstimatorControllerAdapter( ...
                    "sample", context, 0.1, nextEgo, ...
                    targetAtNextSample);
            retiredEgo = hiddenEgo;
            for time = (0.2:0.1:3.0)
                nextEgo.position = [15.0*time; 0.0];
                targetAtNextSample = ...
                    targetStateFunction(time, nextEgo);
                [context, retiredEgo, retiredTarget] = ...
                    nrmmEstimatorControllerAdapter( ...
                        "sample", context, time, nextEgo, ...
                        targetAtNextSample);
            end

            testCase.verifyTrue( ...
                initialization.targetInitiallyAcquired);
            testCase.verifyTrue(visibleFrame.radarDetectionAvailable);
            testCase.verifyNotEmpty(visibleTarget);
            testCase.verifyTrue(visibleEgo.targetEstimatePublished);
            testCase.verifyFalse(hiddenFrame.radarDetectionAvailable);
            testCase.verifyEmpty(hiddenTarget);
            testCase.verifyEmpty(hiddenEgo.targetEstimates);
            testCase.verifyTrue(hiddenEgo.targetTrackAcquired);
            testCase.verifyFalse(hiddenEgo.targetEstimatePublished);
            testCase.verifyEqual( ...
                hiddenEgo.targetPublicationPolicy, ...
                "currentRadarVisibilityRequiredInternalTrackMayCoast");
            testCase.verifyEqual( ...
                hiddenEgo.targetTrackStatus, "coasting");
            testCase.verifyEqual( ...
                hiddenEgo.targetTrackCoastAge, 0.0375, ...
                AbsTol=1.0e-12);
            testCase.verifyEmpty(retiredTarget);
            testCase.verifyFalse(retiredEgo.targetTrackAcquired);
            testCase.verifyFalse( ...
                retiredEgo.targetEstimatePublished);
            testCase.verifyEqual( ...
                retiredEgo.targetTrackStatus, "dormant");
            testCase.verifyEqual( ...
                retiredEgo.targetTrackRetirementCount, 1);
            testCase.verifyEqual( ...
                retiredEgo.targetLastRetirementTime, 0.575, ...
                AbsTol=1.0e-12);
            testCase.verifyTrue(all(isfinite( ...
                context.runtime.targetState), "all"));
            testCase.verifyTrue(all(isfinite( ...
                context.currentOutput.egoState), "all"));
        end
    end
