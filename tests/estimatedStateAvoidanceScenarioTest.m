        function sampledImuAndGnssPreserveRotationCorrespondence(testCase)
            cfg = localConfiguration(20260813);
            cfg.noiseModel = "none";
            initialEgo = struct( ...
                "position", [0.0; 0.0], ...
                "yawAngle", 0.0, ...
                "longitudinalVelocity", 10.0, ...
                "lateralVelocity", 0.0, ...
                "yawRate", 0.0);
            [context, ~] = nrmmEstimatorControllerAdapter( ...
                "initialize", cfg, initialEgo, @localRadarExitTarget);
            target = localRadarExitTarget(0.0, initialEgo);
            context = nrmmEstimatorControllerAdapter( ...
                "sample", context, 0.0, initialEgo, target);
            currentEgo = struct( ...
                "position", [0.9; 0.1], ...
                "yawAngle", 0.4, ...
                "longitudinalVelocity", 8.0, ...
                "lateralVelocity", 0.0, ...
                "yawRate", -0.2);
            target = localRadarExitTarget(0.1, currentEgo);
            [~, ~, ~, frame] = nrmmEstimatorControllerAdapter( ...
                "sample", context, 0.1, currentEgo, target);
            previousFraction = 0.875;
            previousYaw = previousFraction*currentEgo.yawAngle;
            previousSpeed = (1.0-previousFraction) ...
                    * initialEgo.longitudinalVelocity ...
                + previousFraction*currentEgo.longitudinalVelocity;
            previousRotation = [cos(previousYaw), -sin(previousYaw); ...
                sin(previousYaw), cos(previousYaw)];
            currentRotation = [cos(currentEgo.yawAngle), ...
                -sin(currentEgo.yawAngle); ...
                sin(currentEgo.yawAngle), cos(currentEgo.yawAngle)];
            expectedInertialAcceleration = ( ...
                currentRotation*[currentEgo.longitudinalVelocity; 0.0] ...
                - previousRotation*[previousSpeed; 0.0]) ...
                / cfg.observer.runtime.samplePeriod;
            measuredInertialAcceleration = currentRotation ...
                * [frame.longitudinalAcceleration; ...
                    frame.lateralAcceleration];

            testCase.verifyEqual(measuredInertialAcceleration, ...
                expectedInertialAcceleration, AbsTol=1.0e-12);
        end

        function initializationRemovesKinematicSideslipFromCourse(testCase)
            cfg = estimatorControllerIntegrationConfig();
            cfg.noiseModel = "none";
            trueYaw = 0.35;
            trueSideslip = 0.05;
            speed = 10.0;
            rearAxleDistance = ...
                cfg.observer.ego.yaw.rearAxleDistance;
            initialEgo = struct( ...
                "position", [0.0; 0.0], ...
                "yawAngle", trueYaw, ...
                "longitudinalVelocity", speed*cos(trueSideslip), ...
                "lateralVelocity", speed*sin(trueSideslip), ...
                "yawRate", speed*sin(trueSideslip)/rearAxleDistance);

            [~, initialization] = nrmmEstimatorControllerAdapter( ...
                "initialize", cfg, initialEgo, @localRadarExitTarget);

            testCase.verifyEqual(initialization.egoInitialYaw, ...
                trueYaw, AbsTol=1.0e-12);
            testCase.verifyEqual(initialization.egoInitialBodyVelocity, ...
                speed*[cos(trueSideslip); sin(trueSideslip)], ...
                AbsTol=1.0e-12);
        end

